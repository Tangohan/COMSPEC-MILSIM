"""Scénario « marqueurs présents en jeu » : menu Importer, liste, filtres, recherche, aperçu, import en une opération,
annulation, ré-import (déjà importés), lien gardé, états sans partie, terrain différent, aucun marqueur, lecture seule."""
import json

from _base import CTRL, E, Run, reset

reset('demo')
r = Run('marqueurs')
b = r.b
r.open()
n0 = r.count()
b.click('.pe-topacts details.toc-menu summary')
b.click('[data-run="importMarkers"]')
b.wait('document.querySelector(".pe-mk-list")')
M = E + '.markers.state'
r.eq(r.js(M + '.state'), 'ok', 'partie en liaison : liste affichée')
r.eq(r.js(M + '.recs.length'), 13, '12 marqueurs et 1 point ATAK lus')
rows = lambda: r.js('document.querySelectorAll(".pe-mk-row").length')
r.eq(rows(), 11, 'marqueurs de service écartés au départ (réapparition, module vide)')
r.eq(r.js('document.querySelectorAll(".pe-mk-row input:checked").length'), 11, 'tout est coché au départ')
r.check(r.js('document.querySelectorAll(".leaflet-planHandles-pane svg path, .leaflet-planHandles-pane .leaflet-marker-icon").length') > 8, 'aperçu de la sélection sur la carte')
r.shot('import_marqueurs')
b.click('[data-mk-f="system"]')
r.eq(rows(), 13, 'filtre retiré : les marqueurs de service reviennent')
b.click('[data-mk-f="system"]')
b.click('[data-mk-f="side"]')
r.eq(rows(), 10, 'mon camp seulement : le marqueur OPFOR sort (les marqueurs sans camp restent)')
b.click('[data-mk-f="side"]')
b.click('[data-mk-f="view"]')
r.eq(rows(), 10, 'dans la vue seulement : le marqueur lointain sort')
b.click('[data-mk-f="view"]')
b.click('#pe-mk-q')
b.type('acier')
r.eq(rows(), 1, 'recherche : un seul marqueur')
r.eq(r.js('document.activeElement && document.activeElement.id'), 'pe-mk-q', 'la recherche garde le curseur')
for _ in range(5):
    b.key('Backspace')
r.eq(rows(), 11, 'recherche effacée')
b.click('[data-mk-by="channel"]')
r.check(r.js('document.querySelectorAll(".pe-mk-group").length') >= 3, 'groupé par canal')
b.click('[data-mk-by="kind"]')
r.eq(r.js('document.querySelectorAll(".pe-mk-group").length'), 5, 'groupé par genre : unités, icônes, points, zones, tracés')
# Décocher un marqueur
b.click('[data-mk-id="loin"]')
r.eq(r.js('document.querySelectorAll(".pe-mk-row input:checked").length'), 10, 'un marqueur décoché')
b.click('[data-mk="go"]')
r.eq(r.count(), n0 + 10, 'import : dix éléments de plus')
r.eq(r.js('document.getElementById("pe-markers").hidden'), True, 'le volet se ferme')
els = r.js('JSON.stringify(Object.keys(%s.P.els).map(function (k) { return %s.P.els[k]; }).filter(function (e) { return e.props.gid; }).map(function (e) { return [e.props.gid, e.kind, e.geom, e.props.label || e.props.callsign || "", e.props.color, e.props.glink || false]; }))' % (E, E))
els = {e[0]: e for e in json.loads(els)}
r.eq(els['_USER_DEFINED #2/2/1'][1:4], ['unit', 'point', 'ALPHA 1'], 'marqueur OTAN b_inf : unité amie nommée')
r.eq(r.js('(function(){var e=Object.keys(%s.P.els).map(function(k){return %s.P.els[k];}).filter(function(e){return e.props.gid==="_USER_DEFINED #2/3/1";})[0];return [e.props.affil, e.props.sidc.slice(4,7)];})()' % (E, E)), ['H', 'UCA'], 'marqueur OTAN o_armor : hostile, blindés')
r.eq(els['zone_nord'][1:4], ['polygon', 'area', 'ZONE MINÉE'], 'rectangle tourné : zone à quatre sommets, texte gardé')
r.eq(els['ea_1'][1:3], ['ellipse', 'ellipse'], 'ellipse : ellipse')
r.eq(els['_USER_DEFINED #3/1/1'][1:3], ['arrow', 'line'], 'tracé fléché : flèche')
r.eq(els['_USER_DEFINED #2/1/1'][1:4], ['icon', 'point', 'OBJ ACIER'], 'icône : repère nommé')
r.eq(els['atak-wp-31'][1], 'rally', 'point ATAK de ralliement : point de ralliement')
palette = r.js('Object.keys(%s.G.GAME_COLORS).map(function (k) { return %s.G.GAME_COLORS[k]; })' % (E, E))
r.check(all(e[4] in palette for e in els.values() if e[1] != 'unit'), 'couleurs ramenées à notre palette')
r.check(not any(e[5] for e in els.values()), 'sans lien par défaut : simple copie')
r.saved()
r.eq(r.js('document.getElementById("plan-save").textContent.indexOf("Enregistré") === 0'), True, 'le site accepte tous les éléments importés')
# Tout est éditable : la zone importée se choisit
uid = r.js('Object.keys(%s.P.els).filter(function (k) { return %s.P.els[k].props.gid === "ea_1"; })[0]' % (E, E))
b.key('Escape')
p = r.at(5590, 4200)
b.click(p[0], p[1])
r.check(uid in r.sel(), 'la zone importée se choisit (%r)' % r.sel())
# Un seul Ctrl+Z défait tout l'import
b.key('Escape')
b.key('z', CTRL)
r.eq(r.count(), n0, 'un seul Ctrl+Z défait tout l’import')
b.key('y', CTRL)
r.eq(r.count(), n0 + 10, 'Ctrl+Y le refait')
# Ré-import : déjà importés
r.js(E + '.run("importMarkers")')
b.wait('document.querySelector(".pe-mk-list")')
r.eq(r.js('document.querySelectorAll(".pe-mk-row.is-known").length'), 10, 'ré-import : dix marqueurs signalés « déjà importé »')
r.eq(r.js('!!document.querySelector("[data-mk-set=mode]")'), True, 'choix proposé pour les marqueurs déjà importés')
b.click('[data-mk-f="link"]')
b.click('[data-mk="go"]')
r.eq(r.count(), n0 + 11, 'mise à jour : seul le marqueur encore absent est ajouté')
r.eq(r.js('Object.keys(%s.P.els).filter(function (k) { return %s.P.els[k].props.glink; }).length' % (E, E)), 11, 'lien avec le jeu gardé quand il est demandé')
r.js(E + '.run("importMarkers")')
b.wait('document.querySelector("[data-mk-set=mode]")')
r.js('(function(){var s=document.querySelector("[data-mk-set=mode]");s.value="skip";s.dispatchEvent(new Event("change",{bubbles:true}));})()')
r.eq(r.js('document.querySelector("[data-mk=go]").disabled'), True, '« ne pas y toucher » : plus rien à importer')
r.js('(function(){var s=document.querySelector("[data-mk-set=mode]");s.value="duplicate";s.dispatchEvent(new Event("change",{bubbles:true}));})()')
r.check('11' in r.js('document.querySelector("[data-mk=go]").textContent'), '« en double » : onze copies proposées')
b.key('Escape')
r.eq(r.js('document.getElementById("pe-markers").hidden'), True, 'Échap ferme le volet')
r.eq(r.js('document.querySelectorAll(".leaflet-planHandles-pane .leaflet-marker-icon").length'), 0, 'l’aperçu est retiré à la fermeture')
r.saved()
# États
for query, state, text in (('nolink=1', 'nolink', 'Aucune partie en liaison'), ('world=altis', 'mismatch', 'Terrain de la partie différent'), ('nomarkers=1', 'empty', 'Aucun marqueur')):
    r.open(query=query)
    r.js(E + '.run("importMarkers")')
    b.wait(M + '.state !== "loading"')
    b.pump(0.2)
    r.eq(r.js(M + '.state'), state, 'état « %s »' % text)
    r.check(text in r.js('document.getElementById("pe-markers").textContent'), 'message « %s » affiché' % text)
    if state == 'mismatch':
        r.shot('import_marqueurs_terrain')
r.open(query='user=9')
r.eq(r.js('document.querySelector("[data-run=importMarkers]").closest("details").hidden'), True, 'lecture seule : le menu Importer est masqué')
r.js(E + '.run("importMarkers")')
r.eq(r.js('document.getElementById("pe-markers").hidden'), True, 'lecture seule : l’import ne s’ouvre pas')
raise SystemExit(r.done())
