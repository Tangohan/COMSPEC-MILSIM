"""Scénario « temps et 3D » : phases, frise (tête de lecture glissée, clé auto, image clé posée en déplaçant une unité,
lecture), briefing (entrée, pas à pas, sortie), outils de relief, passage 2D ⇄ 3D avec la sélection gardée, déplacement
en 3D, terrain sans relief."""
from _base import E, Run, reset

reset('demo')
r = Run('temps et 3D')
b = r.b
r.open()

# --- Phases et frise
n = r.js(E + '.P.phases.length')
b.click('[data-run="addPhase"]')
r.eq(r.js(E + '.P.phases.length'), n + 1, 'phase ajoutée depuis la frise')
blk = b.rect('[data-ph-block="p2"]')
b.click(blk[0], blk[1])
r.eq(r.js(E + '.P.phase'), 'p2', 'clic sur une phase de la frise : phase affichée')
r.eq(r.js(E + '.P.time'), 30, 'l’instant passe au début de la phase')
r.near(r.js(E + '.shownOf("a3").pts[0]'), [4350, 3650], 1, 'ALPHA 3 est à sa position de H+30')
# Tête de lecture : glisser sur la règle
tr = r.js('(function(){var q=document.getElementById("pe-track").getBoundingClientRect();return [q.left,q.top,q.width];})()')
x = lambda t: tr[0] + (t + 10) / 90.0 * tr[2]
b.drag(x(30), tr[1] + 8, x(42), tr[1] + 8)
r.eq(r.js(E + '.P.time'), 42, 'tête de lecture glissée à H+42')
pa1 = r.js(E + '.shownOf("a1").pts[0]')
r.check(3900 < pa1[0] < 4900, 'ALPHA 1 est entre deux images clés (%r)' % pa1)
# Clé auto : déplacer ALPHA 6 à H+42 lui pose une image clé
b.click('#pe-autokey')
r.eq(r.js(E + '.P.autoKey'), True, 'clé auto activée')
p = r.el_at('cdu')
b.click(p[0], p[1])
b.drag(p[0], p[1], p[0] + 100, p[1] - 40)
track = r.js(E + '.P.els.cdu.props.track')
r.check(track is not None and len(track) == 2 and track[1]['t'] == 42, 'déplacement à H+42 : deux images clés (%r)' % track)
r.near(r.js(E + '.P.els.cdu.pts[0]'), [2950, 3600], 0.2, 'la position de départ ne bouge pas')
r.eq(r.js('document.querySelectorAll("#pe-track .pe-kf").length'), 2, 'les images clés de la sélection sont sur la frise')
r.shot('temps_cle_auto')
b.click('#pe-autokey')
# Plan entier puis lecture
b.click('#pe-whole')
r.eq(r.js(E + '.P.time'), None, 'plan entier : hors du temps')
b.click('#pe-play')
b.pump(2.0)
t = r.js(E + '.P.time')
r.check(t is not None and t > -10, 'lecture : le temps avance (%r)' % t)
b.click('#pe-play')
t1 = r.js(E + '.P.time')
b.pump(0.6)
r.eq(r.js(E + '.P.time'), t1, 'pause : le temps s’arrête')
# Phase : début glissé
g = b.rect('[data-ph-grip="p3"]')
b.drag(g[0], g[1], x(60), g[1])
r.eq(r.js(E + '.P.meta.timeline.phases.p3'), 60, 'début de phase glissé à H+60')
r.saved()

# --- Briefing
b.click('[data-run="briefing"]')
r.eq(r.js(E + '.P.briefing'), True, 'briefing ouvert')
r.eq(r.js('getComputedStyle(document.querySelector(".pe-left")).display'), 'none', 'briefing : volets masqués')
r.check(r.js('document.getElementById("plan-map").getBoundingClientRect().width') > 1800, 'briefing : la carte prend l’écran')
ph0 = r.js(E + '.P.phase')
b.key('ArrowRight')
b.pump(2.2)
r.check(r.js(E + '.P.phase') != ph0, 'briefing : → passe à la phase suivante')
b.key('l')
r.eq(r.js(E + '.P.tool'), 'select', 'briefing : les raccourcis d’outils sont coupés')
r.shot('temps_briefing')
b.key('Escape')
r.eq(r.js(E + '.P.briefing'), False, 'Échap : sortie du briefing')
r.check(r.js('document.querySelector(".pe-left").getBoundingClientRect().width') > 200, 'les volets reviennent')

# --- Relief : ligne de vue, coupe, zone vue
b.click('#pe-whole')
b.key('o')
b.click(*r.at(4350, 3650))
b.click(*r.at(5250, 4950))
r.check('Vue ' in r.js('document.getElementById("pe-analysis").textContent'), 'ligne de vue : verdict affiché')
b.key('w')
b.click(*r.at(4350, 3650))
r.check('%' in r.js('document.getElementById("pe-analysis").textContent'), 'zone vue : part du disque affichée')
b.key('Escape')
b.key('Escape')
r.eq(r.js(E + '.P.tool'), 'select', 'Échap : retour à la sélection')

# --- 2D ⇄ 3D
p = r.el_at('eni2')
b.click(p[0], p[1])
r.eq(r.sel(), ['eni2'], 'ENI 2 choisi en 2D')
c2 = r.js('(function(){var E=%s;var c=E.tm.toWorld(E.tm.map.getCenter());return [c[0],c[1],E.tm.metersPerPixel()];})()' % E)
b.key('3')
b.wait(E + '.P.mode === "3d" && ' + E + '.view3d', 30)
b.pump(1.5)
r.eq(r.sel(), ['eni2'], 'passage en 3D : la sélection est gardée')
v = r.js(E + '.view3d.getView()')
r.near([v['x'], v['y']], c2[:2], 30, '3D : même centre que la vue 2D')
r.check(abs(v['mpp'] - c2[2]) / c2[2] < 0.25, '3D : même échelle que la vue 2D (%.2f contre %.2f m/px)' % (v['mpp'], c2[2]))
r.check(r.js(E + '.view3d.stats().triangles') > 10000, '3D : terrain maillé')
# Choisir puis déplacer une unité en 3D
s = r.js('(function(){var E=%s;var d=E.shownOf("ch");var z=E.view3d.surfaceAt?E.view3d.surfaceAt(d.pts[0][0],d.pts[0][1]):0;var c=E.view3d.worldToClient(d.pts[0][0],d.pts[0][1],z);return c&&[c.x!==undefined?c.x:c[0],c.y!==undefined?c.y:c[1]];})()' % E)
b.click(s[0], s[1] - 4)
r.eq(r.sel(), ['ch'], '3D : clic sur une unité, elle est choisie')
before = r.pos('ch')
b.drag(s[0], s[1] - 4, s[0] + 120, s[1] + 30, steps=10)
after = r.pos('ch')
r.check(abs(after[0] - before[0]) + abs(after[1] - before[1]) > 80, '3D : unité déplacée en glissant sur le relief (%r → %r)' % (before, after))
r.shot('temps_3d')
b.key('3')
b.wait(E + '.P.mode === "2d"')
r.eq(r.sel(), ['ch'], 'retour en 2D : la sélection est gardée')
c3 = r.js('(function(){var E=%s;var c=E.tm.toWorld(E.tm.map.getCenter());return [c[0],c[1]];})()' % E)
r.near(c3, c2[:2], 60, 'retour en 2D : même centre')
r.saved()

# --- Terrain sans relief
r.open(query='nodem=1', wait_dem=False)
b.pump(1.5)
b.key('o')
r.check('Relief non disponible' in r.js('document.getElementById("plan-msg").textContent'), 'sans relief : la ligne de vue le dit')
b.key('Escape')
b.key('3')
b.wait(E + '.P.mode === "3d"', 30)
b.pump(0.8)
r.eq(r.js('document.getElementById("pe-3dnote").hidden'), False, 'sans relief : la vue 3D prévient qu’elle reste à plat')
r.shot('temps_3d_sans_relief')
raise SystemExit(r.done())
