"""Scénario « édition » : glisser depuis la bibliothèque et l'ORBAT, sélection (clic, Maj, cadre, lasso, Alt+clic),
déplacement, rotation, échelle, presse-papiers, annuler et rétablir, dessin, sommets, propriétés, calques,
enregistrement et rechargement. Vrais événements de souris et de clavier sur la vraie page."""
from _base import ALT, CTRL, E, SHIFT, Run, reset

reset('demo')
r = Run('édition')
b = r.b
r.open()
r.eq(r.count(), 24, 'plan chargé')

# --- Bibliothèque : glisser « Infanterie » sur la carte
b.click('[data-left="lib"]')
tile = b.rect('.pe-tile[data-lib="u:infantry"]')
dst = r.at(3600, 5400)
b.drag(tile[0], tile[1], dst[0], dst[1], steps=12)
r.eq(r.count(), 25, 'unité posée par glisser depuis la bibliothèque')
new = r.js('%s.P.sel[0]' % E)
r.near(r.pos(new), [3600, 5400], 30, 'unité posée où elle est lâchée')
r.eq(r.js('document.activeElement && document.activeElement.id'), 'prop-main', 'l’indicatif est prêt à être saisi')
b.type('BRAVO 1')
b.key('Enter')
b.pump(0.5)
r.eq(r.js('%s.P.els[%r].props.callsign' % (E, new)), 'BRAVO 1', 'indicatif saisi')
r.check('BRAVO 1' in r.js('document.getElementById("plan-map").textContent'), 'indicatif affiché sur la carte')
b.key('Escape')

# --- Bibliothèque : cliquer un graphisme (zone) puis tracer
b.click('.pe-tile[data-lib="u:armor"]')
r.eq(r.js(E + '.P.tool'), 'unit', 'tuile cliquée : outil armé')
p = r.at(3900, 5600)
b.click(p[0], p[1])
r.eq(r.count(), 26, 'unité posée au clic')
b.key('Escape')
b.key('Escape')

# --- ORBAT : glisser l'unité « à poser » sur la carte
b.click('[data-left="orbat"]')
node = b.rect('[data-node="res"]')
dst = r.at(3300, 5300)
b.drag(node[0] - 40, node[1], dst[0], dst[1], steps=12)
r.eq(r.js(E + '.P.els.res.props.placed !== false'), True, 'unité de l’ORBAT posée sur la carte')
r.near(r.pos('res'), [3300, 5300], 30, 'unité de l’ORBAT posée où elle est lâchée')
# Ranger : ALPHA 3 sous ALPHA 1
a3 = b.rect('[data-node="a3"]')
a1 = b.rect('[data-node="a1"]')
b.drag(a3[0] - 40, a3[1], a1[0] - 40, a1[1], steps=10)
r.eq(r.js(E + '.P.els.a3.props.parent'), 'a1', 'ORBAT : unité rattachée par glisser')

# --- Sélection
b.key('Escape')
p = r.el_at('eni2')
b.click(p[0], p[1])
r.eq(r.sel(), ['eni2'], 'clic : un élément choisi')
q = r.el_at('ch')
b.click(q[0], q[1], mods=SHIFT)
r.eq(r.sel(), ['ch', 'eni2'], 'Maj+clic : ajouté')
b.click(q[0], q[1], mods=SHIFT)
r.eq(r.sel(), ['eni2'], 'Maj+clic : retiré')
# Cadre autour de HLZ MERLE et MEDEVAC
a = r.at(2650, 3250)
c = r.at(3300, 2650)
b.drag(a[0], a[1], c[0], c[1])
r.check(set(['hlz', 'med']).issubset(set(r.sel())), 'cadre : HLZ et MEDEVAC choisis (%r)' % r.sel())
r.shot('edition_cadre')
# Lasso
b.key('q')
r.eq(r.js(E + '.P.tool'), 'lasso', 'touche Q : lasso')
pts = [r.at(5650, 4600), r.at(6350, 4550), r.at(6300, 3700), r.at(5500, 3750), r.at(5650, 4600)]
b.move(*pts[0])
b.mouse('mousePressed', pts[0][0], pts[0][1], 'left', None, 0, 1)
for x, y in pts[1:]:
    for i in range(1, 6):
        b.mouse('mouseMoved', x, y, 'left')
b.mouse('mouseReleased', pts[-1][0], pts[-1][1], 'left', 0, 0, 1)
b.pump(0.1)
r.check('nai' in r.sel() and 'eni2' in r.sel(), 'lasso : NAI 3 et ENI 2 choisis (%r)' % r.sel())
b.key('v')
# Alt+clic : élément du dessous (ENI 1 est dans OBJ ACIER)
p = r.el_at('eni1')
b.click(p[0], p[1])
r.eq(r.sel(), ['eni1'], 'clic sur l’unité dans la zone')
b.click(p[0], p[1], mods=ALT)
r.check(r.sel() != ['eni1'] and len(r.sel()) == 1, 'Alt+clic : élément du dessous (%r)' % r.sel())

# --- Déplacer, annuler, rétablir
before = r.pos('mo')
p = r.el_at('mo')
b.click(p[0], p[1])
r.eq(r.sel(), ['mo'], 'MORTIERS choisi')
b.drag(p[0], p[1], p[0] + 120, p[1] - 60)
after = r.pos('mo')
r.check(abs(after[0] - before[0]) > 300 and abs(after[1] - before[1]) > 150, 'déplacement à la souris (%r → %r)' % (before, after))
b.key('z', CTRL)
r.near(r.pos('mo'), before, 0.2, 'Ctrl+Z : remis en place')
b.key('y', CTRL)
r.near(r.pos('mo'), after, 0.2, 'Ctrl+Y : rétabli')
b.key('ArrowRight')
r.near(r.pos('mo'), [after[0] + 10, after[1]], 0.2, 'flèche : 10 m')
b.key('ArrowUp', SHIFT)
r.near(r.pos('mo'), [after[0] + 10, after[1] + 100], 0.2, 'Maj+flèche : 100 m')

# --- Rotation et échelle par les poignées (zone NAI 3)
p = r.at(5700, 4000)
b.click(p[0], p[1])
r.eq(r.sel(), ['nai'], 'NAI 3 choisie')
pts0 = r.js(E + '.P.els.nai.pts')
h = b.rect('[data-h="rot"]')
b.drag(h[0], h[1], h[0] + 90, h[1] + 40)
pts1 = r.js(E + '.P.els.nai.pts')
r.check(pts1 != pts0, 'poignée de rotation : la zone a tourné')
h = b.rect('[data-h="s:se"]')
b.drag(h[0], h[1], h[0] + 60, h[1] + 60)
pts2 = r.js(E + '.P.els.nai.pts')
r.check(pts2 != pts1, 'poignée d’échelle : la zone a changé de taille')
h = b.rect('[data-h="v:0"]')
b.drag(h[0], h[1], h[0] - 40, h[1] - 30)
pts3 = r.js(E + '.P.els.nai.pts')
r.check(pts3[0] != pts2[0] and pts3[1] == pts2[1], 'poignée de sommet : un seul sommet déplacé')
n = len(pts3)
h = b.rect('[data-h="m:0"]')
b.drag(h[0], h[1], h[0], h[1] - 40)
r.eq(len(r.js(E + '.P.els.nai.pts')), n + 1, 'poignée de milieu : sommet ajouté')
h = b.rect('[data-h="v:1"]')
b.click(h[0], h[1], count=2)
r.eq(len(r.js(E + '.P.els.nai.pts')), n, 'double-clic sur un sommet : retiré')
r.shot('edition_poignees')

# --- Presse-papiers
n0 = r.count()
p = r.el_at('cp1')
b.click(p[0], p[1])
clip = r.clip('copy')
r.check('athena-plan-clip' in clip, 'copier : notre format part dans le presse-papiers')
q = r.at(4200, 5700)
b.move(q[0], q[1])
r.clip('paste', clip)
b.pump(0.3)
r.eq(r.count(), n0 + 1, 'Ctrl+C puis Ctrl+V : un élément de plus')
pasted = r.js('%s.P.sel[0]' % E)
r.near(r.pos(pasted), [4200, 5700], 40, 'collé sous le curseur')
b.key('d', CTRL)
r.eq(r.count(), n0 + 2, 'Ctrl+D : dupliqué')
r.clip('cut')
r.eq(r.count(), n0 + 1, 'Ctrl+X : coupé')
b.key('Delete')
r.eq(r.count(), n0 + 1, 'Suppr sans sélection : rien')
b.click(*r.el_at(pasted))
b.key('Delete')
r.eq(r.count(), n0, 'Suppr : supprimé')
# Alt+glisser : duplique
p = r.el_at('med')
b.click(p[0], p[1])
b.drag(p[0], p[1], p[0] + 80, p[1] + 50, mods=ALT)
r.eq(r.count(), n0 + 1, 'Alt+glisser : copie déplacée')
r.near(r.pos('med'), [3050, 3050], 0.2, 'Alt+glisser : l’original ne bouge pas')
b.key('z', CTRL)
b.key('z', CTRL)
r.eq(r.count(), n0, 'annulation de la copie déplacée')

# --- Dessin : trait, flèche, polygone, cercle
b.key('Escape')
n0 = r.count()
b.key('l')
for x, y in ([3000, 5700], [3300, 5850], [3700, 5750]):
    b.click(*r.at(x, y))
b.key('Enter')
r.eq(r.count(), n0 + 1, 'trait tracé')
line = r.js('%s.P.sel[0]' % E)
r.eq(r.js('%s.P.els[%r].pts.length' % (E, line)), 3, 'trait à trois points')
r.eq(r.js(E + '.P.tool'), 'select', 'retour à la sélection après le tracé')
b.key('p')
for x, y in ([4300, 5600], [4600, 5600], [4500, 5850]):
    b.click(*r.at(x, y))
last = r.at(4250, 5850)
b.click(last[0], last[1], count=2)
r.eq(r.count(), n0 + 2, 'polygone fermé au double-clic')
r.eq(r.js('%s.P.els[%s.P.sel[0]].pts.length' % (E, E)), 4, 'polygone à quatre sommets')
b.key('c')
a = r.at(3500, 2700)
b.drag(a[0], a[1], a[0] + 50, a[1])
r.eq(r.count(), n0 + 3, 'cercle tracé en glissant')
b.key('a')
b.click(*r.at(3900, 2700))
b.key('Escape')
r.eq(r.count(), n0 + 3, 'Échap : tracé abandonné')
r.eq(r.js(E + '.P.draft'), None, 'aucun brouillon')
b.key('Escape')

# --- Les raccourcis ne partent pas pendant la saisie
p = r.el_at('eni2')
b.click(p[0], p[1])
b.click('#prop-main')
n1 = r.count()
b.type('lacp')
b.key('Delete')
b.key('Backspace')
r.eq(r.count(), n1, 'saisie dans un champ : aucun raccourci ne part')
r.eq(r.js(E + '.P.tool'), 'select', 'saisie dans un champ : l’outil ne change pas')
b.key('Escape')

# --- Calques : masquer, verrouiller
b.click('[data-left="layers"]')
shown0 = r.js(E + '.P.shown.length')
b.click('[data-lv="feux"]')
r.eq(r.js(E + '.P.shown.length'), shown0 - 1, 'calque masqué : ses éléments disparaissent')
b.click('[data-lv="feux"]')
b.click('[data-ll="base"]')
p = r.el_at('eni2')
before = r.pos('eni2')
b.click(p[0], p[1])
b.drag(p[0], p[1], p[0] + 80, p[1])
r.near(r.pos('eni2'), before, 0.2, 'calque verrouillé : rien ne bouge')
b.click('[data-ll="base"]')
rows = r.js('Array.prototype.map.call(document.querySelectorAll("[data-layer-row]"), function (n) { return n.getAttribute("data-layer-row"); })')
g = b.rect('[data-layer-row="%s"] .pe-grip' % rows[0])
t = b.rect('[data-layer-row="%s"]' % rows[1])
b.drag(g[0], g[1], t[0], t[1] + t[3] / 2 - 3, steps=10)
rows2 = r.js('Array.prototype.map.call(document.querySelectorAll("[data-layer-row]"), function (n) { return n.getAttribute("data-layer-row"); })')
r.eq(rows2, rows[::-1], 'calques : ordre changé par glisser')

# --- Enregistrement et rechargement
r.saved()
state = r.js('JSON.stringify(Object.keys(%s.P.els).sort().map(function (k) { var e = %s.P.els[k]; return [k, e.kind, e.pts, e.props.callsign || e.props.label || "", e.layer]; }))' % (E, E))
layers = r.js('JSON.stringify(%s.P.meta.layers.map(function (l) { return l.uid; }))' % E)
b.pump(1.5)
r.shot('edition_fin')
r.open()
state2 = r.js('JSON.stringify(Object.keys(%s.P.els).sort().map(function (k) { var e = %s.P.els[k]; return [k, e.kind, e.pts, e.props.callsign || e.props.label || "", e.layer]; }))' % (E, E))
r.check(state == state2, 'rechargement : les éléments reviennent à l’identique')
r.eq(r.js('JSON.stringify(%s.P.meta.layers.map(function (l) { return l.uid; }))' % E), layers, 'rechargement : ordre des calques gardé')
raise SystemExit(r.done())
