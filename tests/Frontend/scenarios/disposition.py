"""Scénario « disposition » : volets, frise et barre repliés ou dépliés (boutons, touches, double-clic), bords à
glisser, état gardé après rechargement, carte seule, petit écran (volet de droite replié tant que rien n'est choisi)."""
from _base import E, Run, reset

reset('demo')
r = Run('disposition')
b = r.b
r.open()
w = lambda sel: r.js('document.querySelector(%r).getBoundingClientRect().width' % sel)
h = lambda sel: r.js('document.querySelector(%r).getBoundingClientRect().height' % sel)
mapw = lambda: w('#plan-map')

m0 = mapw()
lw = w('#pe-left')
b.key('[')
r.check(w('#pe-left') < 60, 'touche [ : volet de gauche replié en rail (%s px)' % w('#pe-left'))
r.check(mapw() > m0 + 150, 'la carte gagne la place du volet')
r.eq(r.js('getComputedStyle(document.querySelector(".pe-left .pe-rail")).display'), 'flex', 'rail d’icônes visible')
b.click('[data-rail="left:orbat"]')
r.check(abs(w('#pe-left') - lw) < 2, 'rail : clic sur ORBAT déplie le volet')
r.eq(r.js('document.querySelector("[data-left=orbat]").getAttribute("aria-selected")'), 'true', 'rail : l’onglet demandé est ouvert')
b.key(']')
r.check(w('#pe-right') < 60, 'touche ] : volet de droite replié')
b.key(']')
# Bord à glisser : volet de gauche plus large
d = b.rect('[data-div="left"]')
b.drag(d[0], 400, d[0] + 90, 400)
r.check(abs(w('#pe-left') - (lw + 90)) < 6, 'bord glissé : volet de gauche élargi de 90 px (%s → %s)' % (lw, w('#pe-left')))
# Frise : hauteur, repli par double-clic
th = h('#pe-track')
d = b.rect('[data-div="time"]')
b.drag(600, d[1], 600, d[1] - 60)
r.check(abs(h('#pe-track') - (th + 60)) < 6, 'bord glissé : frise plus haute de 60 px (%s → %s)' % (th, h('#pe-track')))
b.key('9')
r.eq(r.js('getComputedStyle(document.getElementById("pe-track")).display'), 'none', 'touche 9 : frise repliée')
r.shot('disposition_replie')
b.key('9')
# Sections repliables
b.click('[data-right="plan"]')
b.click('details[data-fold="plan-phases"] > summary')
r.eq(r.js('document.querySelector("details[data-fold=plan-phases]").open'), False, 'section Phases repliée')
# Groupe d'outils replié
b.click('[data-group="draw"] .pe-tgroup-fold')
r.eq(r.js('Array.prototype.filter.call(document.querySelectorAll("[data-group=draw] [data-tool]"), function (x) { return x.offsetWidth > 0; }).length'), 1, 'groupe d’outils replié : un seul bouton reste')
b.pump(0.3)
state = [round(w('#pe-left')), round(h('#pe-track'))]
# Rechargement : tout est retenu
r.open()
r.eq([round(w('#pe-left')), round(h('#pe-track'))], state, 'rechargement : largeur du volet et hauteur de la frise gardées')
b.click('[data-right="plan"]')
r.eq(r.js('document.querySelector("details[data-fold=plan-phases]").open'), False, 'rechargement : section restée repliée')
r.eq(r.js('document.querySelector("[data-group=draw]").classList.contains("is-folded")'), True, 'rechargement : groupe d’outils resté replié')
# Carte seule
b.key('Escape')
b.key('0')
r.check(mapw() > 1800, 'touche 0 : carte seule (%s px)' % mapw())
r.shot('disposition_carte_seule')
b.key('Escape')
r.check(mapw() < 1700, 'Échap : les volets reviennent')
# La carte reste juste après un repli : un clic choisit bien l'élément visé
b.key('[')
p = r.el_at('eni2')
b.click(p[0], p[1])
r.eq(r.sel(), ['eni2'], 'après repli : le clic tombe sur le bon élément')
b.key('Escape')
b.key('Escape')
r.js('TocPlanEditor.run("layoutReset")')
# Petit écran : volet de droite replié tant que rien n'est choisi
b.viewport(1366, 768)
b.pump(0.4)
r.check(w('#pe-right') < 60, '1366 px : volet de droite replié sans sélection (%s px)' % w('#pe-right'))
p = r.el_at('eni2')
b.click(p[0], p[1])
r.check(w('#pe-right') > 250, '1366 px : le volet de droite s’ouvre avec la sélection')
r.eq(r.js('document.documentElement.scrollWidth <= window.innerWidth'), True, '1366 px : pas de défilement horizontal')
r.shot('disposition_1366')
b.key('Escape')
b.key('Escape')
b.viewport(1024, 768)
b.pump(0.4)
r.eq(r.js('document.documentElement.scrollWidth <= window.innerWidth'), True, '1024 px : pas de défilement horizontal')
r.check(mapw() > 500, '1024 px : la carte garde de la place (%s px)' % mapw())
r.shot('disposition_1024')
raise SystemExit(r.done())
