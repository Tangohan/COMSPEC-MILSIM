-- Nomenclatures nationales : distinctes des capacités génériques military_specialties.
-- Exécution officielle : étape 4910 de la file active ; aucun rattachement de membre implicite.
CREATE TABLE IF NOT EXISTS military_specialty_systems (
    id BIGINT UNSIGNED NOT NULL AUTO_INCREMENT,
    service_id BIGINT UNSIGNED NOT NULL,
    system_key VARCHAR(64) NOT NULL,
    name VARCHAR(255) NOT NULL,
    personnel_category VARCHAR(24) NOT NULL DEFAULT 'mixed',
    source_id BIGINT UNSIGNED DEFAULT NULL,
    archived_at DATETIME DEFAULT NULL,
    created_at DATETIME NOT NULL DEFAULT CURRENT_TIMESTAMP,
    updated_at DATETIME DEFAULT NULL,
    PRIMARY KEY (id),
    UNIQUE KEY uq_mss_key (system_key),
    KEY idx_mss_service (service_id),
    KEY idx_mss_source (source_id),
    CONSTRAINT fk_mss_service FOREIGN KEY (service_id) REFERENCES military_services (id) ON DELETE RESTRICT,
    CONSTRAINT fk_mss_source FOREIGN KEY (source_id) REFERENCES military_sources (id) ON DELETE RESTRICT
) ENGINE=InnoDB DEFAULT CHARSET=utf8mb4 COLLATE=utf8mb4_unicode_ci;

CREATE TABLE IF NOT EXISTS military_specialty_codes (
    id BIGINT UNSIGNED NOT NULL AUTO_INCREMENT,
    system_id BIGINT UNSIGNED NOT NULL,
    reference_key VARCHAR(120) NOT NULL,
    code VARCHAR(64) DEFAULT NULL,
    official_title VARCHAR(255) NOT NULL,
    label_fr VARCHAR(255) NOT NULL,
    label_en VARCHAR(255) NOT NULL,
    kind VARCHAR(24) NOT NULL DEFAULT 'specialty',
    is_pattern TINYINT(1) NOT NULL DEFAULT 0,
    description TEXT DEFAULT NULL,
    source_id BIGINT UNSIGNED DEFAULT NULL,
    source_locator VARCHAR(255) DEFAULT NULL,
    verification_status VARCHAR(24) NOT NULL DEFAULT 'unverified',
    verified_at DATE DEFAULT NULL,
    valid_from DATE DEFAULT NULL,
    valid_until DATE DEFAULT NULL,
    archived_at DATETIME DEFAULT NULL,
    created_at DATETIME NOT NULL DEFAULT CURRENT_TIMESTAMP,
    updated_at DATETIME DEFAULT NULL,
    PRIMARY KEY (id),
    UNIQUE KEY uq_msc_reference (reference_key),
    UNIQUE KEY uq_msc_system_code (system_id, code),
    KEY idx_msc_system_active (system_id, archived_at, code),
    KEY idx_msc_source (source_id),
    CONSTRAINT fk_msc_system FOREIGN KEY (system_id) REFERENCES military_specialty_systems (id) ON DELETE RESTRICT,
    CONSTRAINT fk_msc_source FOREIGN KEY (source_id) REFERENCES military_sources (id) ON DELETE RESTRICT
) ENGINE=InnoDB DEFAULT CHARSET=utf8mb4 COLLATE=utf8mb4_unicode_ci;

CREATE TABLE IF NOT EXISTS military_specialty_levels (
    id BIGINT UNSIGNED NOT NULL AUTO_INCREMENT,
    specialty_code_id BIGINT UNSIGNED NOT NULL,
    level_code VARCHAR(16) NOT NULL,
    official_title VARCHAR(255) NOT NULL,
    label_fr VARCHAR(255) NOT NULL,
    label_en VARCHAR(255) NOT NULL,
    awarded_code VARCHAR(64) DEFAULT NULL,
    sort_order INT NOT NULL DEFAULT 0,
    source_id BIGINT UNSIGNED DEFAULT NULL,
    source_locator VARCHAR(255) DEFAULT NULL,
    verification_status VARCHAR(24) NOT NULL DEFAULT 'unverified',
    verified_at DATE DEFAULT NULL,
    archived_at DATETIME DEFAULT NULL,
    created_at DATETIME NOT NULL DEFAULT CURRENT_TIMESTAMP,
    updated_at DATETIME DEFAULT NULL,
    PRIMARY KEY (id),
    UNIQUE KEY uq_msl_code_level (specialty_code_id, level_code),
    UNIQUE KEY uq_msl_code_id (specialty_code_id, id),
    KEY idx_msl_sort (specialty_code_id, sort_order),
    KEY idx_msl_source (source_id),
    CONSTRAINT fk_msl_code FOREIGN KEY (specialty_code_id) REFERENCES military_specialty_codes (id) ON DELETE RESTRICT,
    CONSTRAINT fk_msl_source FOREIGN KEY (source_id) REFERENCES military_sources (id) ON DELETE RESTRICT
) ENGINE=InnoDB DEFAULT CHARSET=utf8mb4 COLLATE=utf8mb4_unicode_ci;

CREATE TABLE IF NOT EXISTS personnel_job_role_specialty_codes (
    tenant_id INT UNSIGNED NOT NULL,
    job_role_id INT UNSIGNED NOT NULL,
    specialty_code_id BIGINT UNSIGNED NOT NULL,
    created_by INT UNSIGNED DEFAULT NULL,
    created_at DATETIME NOT NULL DEFAULT CURRENT_TIMESTAMP,
    updated_at DATETIME DEFAULT NULL,
    PRIMARY KEY (tenant_id, job_role_id, specialty_code_id),
    KEY idx_pjrsc_code (specialty_code_id),
    KEY idx_pjrsc_actor (created_by),
    CONSTRAINT fk_pjrsc_tenant FOREIGN KEY (tenant_id) REFERENCES tenants (id) ON DELETE CASCADE,
    CONSTRAINT fk_pjrsc_job FOREIGN KEY (tenant_id, job_role_id) REFERENCES personnel_job_roles (tenant_id, id) ON DELETE CASCADE,
    CONSTRAINT fk_pjrsc_code FOREIGN KEY (specialty_code_id) REFERENCES military_specialty_codes (id) ON DELETE RESTRICT,
    CONSTRAINT fk_pjrsc_actor FOREIGN KEY (created_by) REFERENCES users (id) ON DELETE SET NULL
) ENGINE=InnoDB DEFAULT CHARSET=utf8mb4 COLLATE=utf8mb4_unicode_ci;

CREATE TABLE IF NOT EXISTS personnel_profile_specialty_codes (
    id BIGINT UNSIGNED NOT NULL AUTO_INCREMENT,
    tenant_id INT UNSIGNED NOT NULL,
    user_id INT UNSIGNED NOT NULL,
    specialty_code_id BIGINT UNSIGNED NOT NULL,
    specialty_level_id BIGINT UNSIGNED DEFAULT NULL,
    status VARCHAR(24) NOT NULL DEFAULT 'declared',
    obtained_at DATE DEFAULT NULL,
    evidence_qualification_id BIGINT UNSIGNED DEFAULT NULL,
    validated_by INT UNSIGNED DEFAULT NULL,
    validated_at DATETIME DEFAULT NULL,
    created_at DATETIME NOT NULL DEFAULT CURRENT_TIMESTAMP,
    updated_at DATETIME DEFAULT NULL,
    PRIMARY KEY (id),
    UNIQUE KEY uq_ppsc_member_code (tenant_id, user_id, specialty_code_id),
    KEY idx_ppsc_member_status (tenant_id, user_id, status),
    KEY idx_ppsc_tenant_code (tenant_id, specialty_code_id),
    KEY idx_ppsc_code (specialty_code_id),
    KEY idx_ppsc_level (specialty_code_id, specialty_level_id),
    KEY idx_ppsc_user (user_id),
    KEY idx_ppsc_evidence (evidence_qualification_id),
    KEY idx_ppsc_actor (validated_by),
    CONSTRAINT fk_ppsc_tenant FOREIGN KEY (tenant_id) REFERENCES tenants (id) ON DELETE CASCADE,
    CONSTRAINT fk_ppsc_user FOREIGN KEY (user_id) REFERENCES users (id) ON DELETE CASCADE,
    CONSTRAINT fk_ppsc_code FOREIGN KEY (specialty_code_id) REFERENCES military_specialty_codes (id) ON DELETE RESTRICT,
    CONSTRAINT fk_ppsc_level FOREIGN KEY (specialty_code_id, specialty_level_id) REFERENCES military_specialty_levels (specialty_code_id, id) ON DELETE RESTRICT,
    CONSTRAINT fk_ppsc_evidence FOREIGN KEY (evidence_qualification_id) REFERENCES personnel_qualifications (id) ON DELETE RESTRICT,
    CONSTRAINT fk_ppsc_actor FOREIGN KEY (validated_by) REFERENCES users (id) ON DELETE SET NULL
) ENGINE=InnoDB DEFAULT CHARSET=utf8mb4 COLLATE=utf8mb4_unicode_ci;

