CREATE TABLE IF NOT EXISTS member_integration_invitations (
    id BIGINT UNSIGNED NOT NULL AUTO_INCREMENT,
    tenant_id INT UNSIGNED NOT NULL,
    appointment_id BIGINT UNSIGNED NOT NULL,
    user_id INT UNSIGNED NOT NULL,
    status VARCHAR(32) NOT NULL DEFAULT 'pending',
    response_token_hash CHAR(64) NOT NULL,
    token_expires_at DATETIME NOT NULL,
    revoked_at DATETIME NULL,
    personal_message TEXT NULL,
    response_comment VARCHAR(500) NULL,
    invited_by INT UNSIGNED NULL,
    invited_at DATETIME NOT NULL DEFAULT CURRENT_TIMESTAMP,
    responded_at DATETIME NULL,
    email_sent_at DATETIME NULL,
    reminded_at DATETIME NULL,
    created_at DATETIME NOT NULL DEFAULT CURRENT_TIMESTAMP,
    updated_at DATETIME NULL DEFAULT NULL ON UPDATE CURRENT_TIMESTAMP,
    PRIMARY KEY (id),
    UNIQUE KEY uq_mii_appointment_user (appointment_id, user_id),
    UNIQUE KEY uq_mii_token (response_token_hash),
    KEY idx_mii_tenant_user (tenant_id, user_id, status),
    CONSTRAINT fk_mii_tenant FOREIGN KEY (tenant_id) REFERENCES tenants (id) ON DELETE CASCADE ON UPDATE CASCADE,
    CONSTRAINT fk_mii_appointment FOREIGN KEY (appointment_id) REFERENCES member_integration_appointments (id) ON DELETE CASCADE ON UPDATE CASCADE,
    CONSTRAINT fk_mii_user FOREIGN KEY (user_id) REFERENCES users (id) ON DELETE CASCADE ON UPDATE CASCADE,
    CONSTRAINT fk_mii_inviter FOREIGN KEY (invited_by) REFERENCES users (id) ON DELETE SET NULL ON UPDATE CASCADE
) ENGINE=InnoDB DEFAULT CHARSET=utf8mb4 COLLATE=utf8mb4_unicode_ci;

