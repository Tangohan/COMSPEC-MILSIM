CREATE TABLE IF NOT EXISTS member_integration_events (
    id BIGINT UNSIGNED NOT NULL AUTO_INCREMENT,
    tenant_id INT UNSIGNED NOT NULL,
    integration_id BIGINT UNSIGNED NOT NULL,
    step_id BIGINT UNSIGNED NULL,
    actor_user_id INT UNSIGNED NULL,
    event_type VARCHAR(64) NOT NULL,
    visibility VARCHAR(16) NOT NULL DEFAULT 'staff',
    message TEXT NULL,
    metadata_json JSON NULL,
    created_at DATETIME NOT NULL DEFAULT CURRENT_TIMESTAMP,
    PRIMARY KEY (id),
    KEY idx_mie_integration (tenant_id, integration_id, created_at),
    KEY idx_mie_visibility (tenant_id, visibility),
    CONSTRAINT fk_mie_tenant FOREIGN KEY (tenant_id) REFERENCES tenants (id) ON DELETE CASCADE ON UPDATE CASCADE,
    CONSTRAINT fk_mie_integration FOREIGN KEY (integration_id) REFERENCES member_integrations (id) ON DELETE CASCADE ON UPDATE CASCADE,
    CONSTRAINT fk_mie_step FOREIGN KEY (step_id) REFERENCES member_integration_steps (id) ON DELETE SET NULL ON UPDATE CASCADE,
    CONSTRAINT fk_mie_actor FOREIGN KEY (actor_user_id) REFERENCES users (id) ON DELETE SET NULL ON UPDATE CASCADE
) ENGINE=InnoDB DEFAULT CHARSET=utf8mb4 COLLATE=utf8mb4_unicode_ci;

