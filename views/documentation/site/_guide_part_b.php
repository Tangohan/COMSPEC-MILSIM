    </p>
    <p>
        Un <strong>verrouillage de l’échange</strong> peut être appliqué par les pilotes (lecture seule du fil commun, blocage des nouvelles réponses),
        selon la politique interne ou la phase du dossier, y compris après clôture. Respectez toujours la mention de consultation seule lorsqu’elle
        apparaît : les échanges informels doivent alors passer par les canaux prévus par votre état-major.
    </p>
    <div class="site-docs__callout">
        <strong>Cohérence avec la modération.</strong> Le fil d’une coopération suit les mêmes principes de civilité que le reste du forum ; les
        signalements et interventions des modérateurs restent possibles selon les règles de votre communauté. Voir
        <a href="#moderation-forum">Modération &amp; signalements</a> pour le détail des outils disponibles.
    </div>

    <h3>Utilisation</h3>
    <p>
        Pour <strong>lancer</strong> une coopération : ouvrez la liste des dossiers, utilisez l’action de création, saisissez un titre clair, une
        typologie et, si utile, une échéance de réponse et des conditions suspensives rédigées en langage compréhensible par un lecteur extérieur à votre
        unité.
    </p>
    <p>
        Pour <strong>répondre à une invitation</strong> : ouvrez le dossier depuis votre propre liste, examinez la proposition, puis acceptez, refusez ou
        formulez une contre-proposition argumentée si le cadre initial ne convient pas entièrement.
    </p>
    <p>
        Pour <strong>autoriser le partage</strong> : ouvrez l’écran dédié, cochez les familles d’informations que vous acceptez de partager, complétez la
        justification si elle est demandée, puis saisissez le code reçu par courriel dans le délai indiqué.
    </p>
    <p>
        Pour <strong>participer une fois la coopération activée</strong> : utilisez l’espace commun pour les échanges opérationnels, choisissez une
        nature de message adaptée quand l’interface le propose (message standard, information officielle, décision validée), et gardez à l’esprit que le
        contexte peut indiquer explicitement quelle communauté vous représentez dans cet échange, même publié depuis votre compte personnel.
    </p>
    <p>
        Pour <strong>préparer une réunion</strong> : renseignez un ordre du jour dans l’outil avant le rendez-vous, afin que les autres unités sachent à
        quoi s’attendre et que le journal en garde une trace exploitable ensuite.
    </p>
    <p>
        Pour <strong>clôturer et capitaliser</strong> : une fois l’activité terminée, ouvrez l’onglet de clôture, renseignez le motif et le bilan, puis
        remplissez le retour d’expérience de votre communauté : c’est le moment où la mémoire institutionnelle progresse pour la coopération suivante.
    </p>
    <p>
        La liste des coopérations peut afficher des <strong>indicateurs de pilotage</strong> (dossiers actifs, invitations en attente, délais proches) et
        une zone <strong>actions attendues</strong> ; utilisez-la comme file de priorités avant d’ouvrir chaque dossier en détail. Selon l’évolution du
        portail, une coopération passée peut aussi être <strong>dupliquée</strong> pour démarrer un nouveau dossier sur un schéma proche — la duplication
        évite de tout ressaisir mais exige toujours une relecture, les partenaires et engagements précédents n’étant jamais repris sans validation humaine.
    </p>

    <h3>Cas particuliers</h3>
    <p>
        Certaines situations reviennent régulièrement ; voici comment les interpréter avant de solliciter un référent.
    </p>
    <dl class="site-docs__dl">
        <dt>Message « accès refusé » en ouvrant un dossier</dt>
        <dd>Vous n’êtes pas listé comme participant actif, ou votre rôle ne couvre pas cette action à cette étape. Vérifiez aussi que la bonne
            communauté active est bien sélectionnée en haut de l’écran.</dd>
        <dt>Impossible de répondre sur le fil commun</dt>
        <dd>La coopération n’est peut-être pas encore activée, un verrouillage est en place, ou votre permission d’écriture dans l’espace commun n’a
            pas été accordée. Demandez au pilote du dossier plutôt qu’au support technique.</dd>
        <dt>Code de confirmation jamais reçu</dt>
        <dd>Contrôlez le courrier indésirable et l’adresse associée à votre compte, puis patientez quelques minutes. Évitez de redemander plusieurs
            codes d’affilée : cela peut retarder la réception du bon code et déclencher un blocage temporaire.</dd>
        <dt>Un partenaire indique qu’il « ne voit rien »</dt>
        <dd>Le plus souvent : mauvaise communauté active de son côté, invitation encore en attente d’acceptation, ou habilitation manquante dans son
            unité. Faites-lui vérifier ces trois points dans l’ordre.</dd>
        <dt>Dossier resté « en cours » alors que l’activité est terminée</dt>
        <dd>Personne n’a lancé la clôture. Ouvrez l’onglet dédié et clôturez proprement : un dossier oublié en cours fausse les tableaux de bord et les
            indicateurs de pilotage de toutes les unités concernées.</dd>
        <dt>Désaccord sur ce qui avait été décidé au départ</dt>
        <dd>Consultez l’instantané de contexte enregistré à l’activation et la chronologie : ils font référence interne en cas de doute, même s’ils ne
            remplacent pas une décision formelle de votre chaîne de commandement.</dd>
        <dt>Rôle de dossier attribué mais toujours sans accès à un onglet</dt>
        <dd>Certains onglets restent réservés à des permissions plus larges (pilotage, clôture) même pour un membre déjà associé au dossier. Vérifiez
            l’intitulé exact du rôle qui vous a été attribué avant de conclure à une anomalie.</dd>
    </dl>
    <div class="site-docs__callout site-docs__callout--warn">
        <strong>Rappel de sécurité.</strong> Les règles de classification de l’information, les ordres internes et le jugement du commandement restent
        toujours prioritaires sur tout affichage du portail. En cas de doute sur ce qui peut être partagé avec une autre unité, ne publiez pas et
        sollicitez votre référent avant d’utiliser l’espace commun.
    </div>
</section>

<section id="moderation-forum" class="site-docs__section">
    <h2>Modération &amp; signalements</h2>
    <p class="site-docs__lead">
        La modération veille à ce que les espaces d’échange restent utilisables et respectueux : elle combine des outils pour les cadres de votre
        communauté et un filet de sécurité que chaque membre peut activer via le signalement.
    </p>

    <h3>Présentation générale</h3>
    <p>
        Deux niveaux se combinent. Des personnes désignées par votre communauté modèrent <strong>les contenus de l’unité</strong> : forum général,
        briefings, et le cas échéant les fils partagés d’une <a href="#cooperations-inter-unites">coopération inter-unités</a>. Un niveau « plateforme »
        distinct peut exister pour les équipes techniques globales, mais il ne concerne pas le quotidien d’une unité classique : il intervient sur des
        situations exceptionnelles dépassant le périmètre d’une seule communauté.
    </p>
    <p>
        Ce cloisonnement est volontaire : un modérateur d’une autre communauté n’a pas de droit d’intervention chez vous, et inversement. Chaque unité
        reste maîtresse de ses propres règles de civilité, dans le respect des règles générales de la plateforme.
    </p>

    <h3>Fonctionnement</h3>
    <p>
        Avec les habilitations adaptées, un modérateur peut <strong>épingler</strong> un sujet pour le maintenir visible en tête de catégorie,
        <strong>verrouiller</strong> un fil pour empêcher toute nouvelle réponse tout en conservant l’historique, ou intervenir directement sur des
        messages qui enfreignent le règlement (retrait, correction, avertissement à l’auteur selon les outils disponibles).
    </p>
    <p>
        Les outils d’<strong>administration des catégories</strong> permettent en complément de créer ou réorganiser des catégories, d’ajuster leur
        visibilité par rôle ou par affectation, et de définir qui peut y publier ou seulement y lire. Une catégorie mal calibrée en visibilité est
        souvent à l’origine d’une confusion (« pourquoi je ne vois pas ce fil ? ») plutôt qu’un problème de modération à proprement parler.
    </p>
    <p>
        Tout membre peut <strong>signaler</strong> un contenu problématique : harcèlement, spam, fuite d’information, propos inappropriés. Le
        signalement n’est pas une accusation publique : il ouvre un examen discret par les modérateurs, sans exposer votre identité aux autres
        participants du fil.
    </p>
    <p>
        Un signalement s’accompagne en général d’un <strong>motif</strong> choisi parmi une liste courte, pour orienter l’examen sans obliger le membre
        signalant à rédiger un texte long : propos inapproprié, harcèlement, contenu hors sujet ou publicitaire, information sensible partagée à tort,
        ou autre motif décrit librement lorsque aucune catégorie ne correspond.
    </p>
    <div class="site-docs__table-wrap">
        <table class="site-docs__table">
            <thead>
                <tr>
                    <th>État du signalement</th>
                    <th>Signification</th>
                </tr>
            </thead>
            <tbody>
                <tr>
                    <td>En attente</td>
                    <td>Reçu, pas encore examiné par un modérateur</td>
                </tr>
                <tr>
                    <td>En cours d’examen</td>
                    <td>Un modérateur consulte le contexte et décide d’une action éventuelle</td>
                </tr>
                <tr>
                    <td>Traité</td>
                    <td>Une décision a été prise (intervention, avertissement, classement sans suite)</td>
                </tr>
                <tr>
                    <td>Classé sans suite</td>
                    <td>Le contenu ne justifiait pas d’action après examen</td>
                </tr>
            </tbody>
        </table>
    </div>
    <p>
        Les signalements en attente apparaissent regroupés dans la console de modération, ce qui évite aux modérateurs de devoir surveiller
        manuellement chaque catégorie du forum. Le modérateur qui traite un signalement peut consulter le message d’origine dans son contexte complet
        avant d’agir, pour éviter une décision hors contexte.
    </p>
    <p>
        Les mesures disponibles suivent en général une <strong>gradation</strong>, du simple rappel des règles jusqu’à une restriction plus lourde
        d’accès au forum, en passant par le retrait d’un message précis ou le verrouillage d’un fil devenu ingérable. Le choix de la mesure reste une
        décision humaine du modérateur, éclairée par le contexte et l’historique, et non un barème appliqué mécaniquement.
    </p>

    <h3>Utilisation</h3>
    <ol class="site-docs__steps">
        <li><strong>Repérer un contenu problématique</strong> — Identifiez le message concerné et évitez d’y répondre publiquement de façon
            conflictuelle.</li>
        <li><strong>Utiliser le bouton de signalement</strong> — Décrivez brièvement le motif si un champ de commentaire est proposé, pour aider le
            modérateur à comprendre rapidement la situation.</li>
        <li><strong>Laisser le modérateur examiner</strong> — Le contexte du fil et l’historique de l’auteur sont consultés avant toute décision.</li>
        <li><strong>Action du modérateur</strong> — Selon la gravité : rien de plus si le signalement n’est pas fondé, avertissement, retrait du
            contenu, verrouillage du fil, voire mesure plus lourde selon les outils et le règlement de votre communauté.</li>
        <li><strong>Clôture du signalement</strong> — Le signalement est marqué comme traité une fois la situation réglée, ce qui le retire de la file
            active des modérateurs.</li>
    </ol>
    <p>
        Pour un sujet à haute valeur de référence (briefing officiel, annonce importante), pensez à l’<strong>épingler</strong> dès sa publication plutôt
        que d’attendre qu’il se noie dans le flux des messages plus récents.
    </p>

    <h3>Cas particuliers</h3>
    <p>
        <strong>Signalements répétés contre le même membre.</strong> Un historique de signalements sur un même auteur peut justifier une mesure plus
        ferme qu’un incident isolé ; les modérateurs disposent en général d’une vue d’ensemble de cet historique pour éviter de traiter chaque
        signalement en vase clos.
    </p>
    <p>
        <strong>Contestation d’une décision de modération.</strong> Si un membre estime qu’une intervention était disproportionnée, le canal adapté est
        un échange avec l’état-major de l’unité plutôt qu’une reprise du débat sur le fil concerné, qui peut déjà être verrouillé.
    </p>
    <p>
        <strong>Signalement dans une coopération inter-unités.</strong> Le fil partagé d’une coopération suit les mêmes principes de civilité que le
        reste du forum ; le signalement fonctionne de la même façon, mais l’intervention peut impliquer une coordination entre les modérateurs des
        différentes communautés participantes.
    </p>
    <p>
        <strong>Situation dépassant le périmètre de votre unité.</strong> Si un incident implique plusieurs communautés ou semble relever d’une règle
        générale de la plateforme plutôt que du règlement interne d’une seule unité, l’état-major peut relayer la situation vers le niveau plateforme
        plutôt que de tenter de la traiter isolément.
    </p>
    <p>
        <strong>Signalement visant un modérateur.</strong> Un membre peut signaler le comportement d’un modérateur comme n’importe quel autre contenu ;
        l’examen est alors confié à l’état-major ou à un autre modérateur habilité pour éviter que la personne visée traite elle-même le signalement.
    </p>
    <p>
        <strong>Catégorie mal configurée.</strong> Si un fil semble accessible à des personnes qui ne devraient pas le voir, ou inversement invisible
        pour des membres censés y avoir accès, vérifiez d’abord la configuration de visibilité de la catégorie avant de conclure à un problème de
        modération : les deux sujets sont liés mais se règlent avec des outils différents.
    </p>
    <div class="site-docs__callout">
        <strong>Bon réflexe.</strong> Privilégiez toujours le signalement et les canaux officiels plutôt qu’une « riposte » publique sur le forum, qui
        complique le travail de modération et nuit à l’image de l’unité aux yeux des autres membres.
    </div>
</section>

<section id="formations" class="site-docs__section">
    <h2>Formations (LMS &amp; Studio)</h2>
    <p class="site-docs__lead">
        Le module de formation couvre tout le cycle de vie d’un parcours pédagogique : de sa conception dans l’espace d’édition (Studio) jusqu’à son
        suivi par les apprenants dans le catalogue, avec les états de visibilité, les assignations, les évaluations et les attestations qui en découlent.
    </p>

    <h3>Présentation générale</h3>
    <p>
        Le <strong>catalogue</strong> liste les parcours accessibles : consultation libre, inscription selon les règles du parcours, ou
        <strong>assignation</strong> décidée par un formateur ou l’administration. Selon la configuration de la plateforme, il peut mêler des parcours
        <strong>publiés par votre communauté</strong> et des parcours <strong>proposés sur l’ensemble du site</strong>, repérés par une pastille distincte.
        Des filtres permettent d’afficher tous les parcours, uniquement ceux de la communauté, ou uniquement ceux proposés à toute la plateforme, en
        complément du filtre par thème et de la recherche.
    </p>
    <p>
        <strong>Mes parcours</strong> est la vue personnelle de l’apprenant : les formations suivies, en cours ou terminées, avec la progression, les
        scores obtenus et, si la formation le prévoit, l’attestation délivrée. C’est l’endroit où revenir pour reprendre une leçon interrompue sans
        rechercher à nouveau le parcours dans le catalogue complet.
    </p>
    <p>
        Le <strong>Studio</strong> est l’espace d’édition réservé aux équipes habilitées : c’est là que naît une formation, depuis sa fiche générale
        jusqu’à la structuration détaillée en modules et leçons.
    </p>
    <p>
        Les formations sont en général étiquetées par <strong>niveau</strong> (initiation, intermédiaire, avancé, expert) et par <strong>catégorie
        thématique</strong> (tactique, procédures, matériel, secourisme, transmissions, etc.), ce qui facilite le filtrage du catalogue lorsque le nombre
        de parcours proposés devient important.
    </p>

    <h3>Fonctionnement</h3>
    <p>
        Une formation se construit en Studio par une <strong>fiche</strong> (titre, résumé, niveau, durée indicative, objectifs pédagogiques), puis par une
        structuration en <strong>modules</strong> regroupant des <strong>leçons</strong>. Chaque leçon porte un type de contenu adapté à son objectif : texte
        enrichi, vidéo, fichier à consulter, audio, liste de contrôle, lien externe, ou présentation visuelle pas à pas.
    </p>
    <h4>Types de contenu de leçon</h4>
    <div class="site-docs__table-wrap">
        <table class="site-docs__table">
            <thead>
                <tr>
                    <th>Type de leçon</th>
                    <th>Usage recommandé</th>
                </tr>
            </thead>
            <tbody>
                <tr>
                    <td>Texte enrichi</td>
                    <td>Explication détaillée, procédure écrite, doctrine</td>
                </tr>
                <tr>
                    <td>Vidéo</td>
                    <td>Démonstration gestuelle, retour d’expérience filmé</td>
                </tr>
                <tr>
                    <td>Fichier à consulter</td>
                    <td>Référence à télécharger (fiche technique, aide-mémoire)</td>
                </tr>
                <tr>
                    <td>Liste de contrôle</td>
                    <td>Procédure pas à pas à cocher au fur et à mesure</td>
                </tr>
                <tr>
                    <td>Présentation visuelle</td>
                    <td>Déroulé pédagogique en plusieurs écrans successifs</td>
                </tr>
                <tr>
                    <td>Lien externe</td>
                    <td>Ressource complémentaire hébergée hors du portail</td>
                </tr>
            </tbody>
        </table>
    </div>
    <p>
        Les administrateurs de la plateforme peuvent indiquer si un parcours est destiné <strong>à la communauté courante</strong> ou
        <strong>proposé sur toute la plateforme</strong>, ce choix se faisant à la création et restant modifiable depuis la fiche. Les autres rôles
        voient la portée actuelle du parcours sans pouvoir la modifier.
    </p>
    <h4>États de visibilité d’une formation</h4>
    <div class="site-docs__table-wrap">
        <table class="site-docs__table">
            <thead>
                <tr>
                    <th>État</th>
                    <th>Qui la voit</th>
                    <th>Apparition dans le catalogue</th>
                </tr>
            </thead>
            <tbody>
                <tr>
                    <td>Brouillon</td>
                    <td>Auteurs et équipe pédagogique dans le Studio uniquement</td>
                    <td>Non</td>
                </tr>
                <tr>
                    <td>Privé</td>
                    <td>Groupe restreint défini par votre organisation (test, sessions sur invitation)</td>
                    <td>Non, sauf accès direct accordé</td>
                </tr>
                <tr>
                    <td>Publié</td>
                    <td>Apprenants autorisés, selon les règles d’accès et d’assignation</td>
                    <td>Oui</td>
                </tr>
                <tr>
                    <td>Archivé</td>
                    <td>Historique et données de suivi conservés pour rapport ou audit</td>
                    <td>Non, plus proposé comme offre active</td>
                </tr>
            </tbody>
        </table>
    </div>
    <p>
        Le passage à <strong>publié</strong> peut être soumis à une <strong>permission dédiée</strong> : seuls certains rôles valident la mise en ligne
        d’un parcours vers le catalogue. Si le menu de publication existe mais que l’action est refusée, c’est en général cette permission qui manque,
        pas une anomalie du portail.
    </p>
    <p>
        L’<strong>assignation</strong> désigne l’attribution d’un parcours à un ou plusieurs membres par un formateur ou l’administration, indépendamment
        d’une inscription spontanée. Une formation peut combiner les deux logiques : accessible librement dans le catalogue pour certains, et assignée
        de façon obligatoire pour d’autres selon leur poste ou leur qualification à acquérir.
    </p>
    <p>
        Les <strong>quiz</strong> évaluent la compréhension des leçons : score minimal éventuel, nombre de tentatives autorisées, correction automatique
        ou relecture par un formateur selon le type de question. Une formation peut conditionner la poursuite du parcours à la réussite d’un quiz
        intermédiaire, ou se contenter d’un quiz final récapitulatif. Les questions à choix unique ou multiple se corrigent automatiquement ; une
        question à réponse libre peut nécessiter une relecture humaine avant que le score final ne soit calculé.
    </p>
    <p>
        Une fois le parcours complété selon les règles définies, une <strong>attestation</strong> peut être délivrée automatiquement, consultable ensuite
        depuis « Mes parcours ». Elle atteste que le membre a suivi et validé le contenu à la date indiquée, utile pour le suivi des qualifications
        internes. Selon la configuration retenue, l’attestation peut aussi être exportée pour être jointe à un dossier opérateur ou présentée en dehors
        du portail.
    </p>
    <p>
        Une formation <strong>proposée sur toute la plateforme</strong> peut être assignée à des membres de plusieurs communautés différentes lorsque
        les administrateurs de la plateforme le permettent ; chaque apprenant suit alors sa progression normalement depuis « Mes parcours », sans avoir
        besoin d’appartenir à la communauté qui a créé le parcours.
    </p>
    <p>
        Les personnes chargées du <strong>pôle formation</strong> ou de la <strong>conformité</strong> peuvent disposer d’un <strong>journal
        d’audit</strong> listant les actions sensibles sur les parcours : création ou modification importante, changement de visibilité, publication,
        assignation à des membres. Chaque ligne indique quand l’action a eu lieu, qui l’a effectuée, une formulation claire du type d’action, l’objet
        concerné (formation, module ou leçon selon le cas) et un résumé utile au contrôle interne. Si cet écran n’apparaît pas pour vous, votre rôle ne
        couvre pas la supervision pédagogique.
    </p>

    <h3>Utilisation</h3>
    <p>
        <strong>Côté apprenant :</strong>
    </p>
    <ol class="site-docs__steps">
        <li><strong>Parcourir le catalogue</strong> — Filtrez par thème, portée (communauté ou plateforme) ou recherchez un mot-clé pour trouver un
            parcours pertinent.</li>
        <li><strong>S’inscrire ou attendre une assignation</strong> — Selon la formation, inscrivez-vous librement ou attendez d’être désigné par un
            formateur.</li>
        <li><strong>Suivre les leçons dans l’ordre proposé</strong> — Complétez les modules successivement ; certaines leçons peuvent être
            obligatoires avant d’accéder à la suite.</li>
        <li><strong>Passer les quiz</strong> — Répondez aux évaluations intermédiaires ou finales selon les règles du parcours.</li>
        <li><strong>Récupérer l’attestation</strong> — Une fois le parcours validé, retrouvez l’attestation dans « Mes parcours ».</li>
        <li><strong>Reprendre un parcours interrompu</strong> — Revenez sur « Mes parcours » plutôt que sur le catalogue général pour reprendre
            exactement où vous vous étiez arrêté.</li>
    </ol>
    <p>
        <strong>Côté auteur ou formateur :</strong>
    </p>
    <ol class="site-docs__steps">
        <li><strong>Créer la fiche du parcours</strong> — Renseignez titre, résumé, niveau, durée indicative et objectifs dans le Studio.</li>
        <li><strong>Structurer modules et leçons</strong> — Organisez le contenu de façon progressive, en choisissant le type de contenu adapté à chaque
            leçon.</li>
        <li><strong>Relire en brouillon ou en privé</strong> — Faites tester le parcours par un petit groupe avant toute mise en ligne large.</li>
        <li><strong>Publier</strong> — Une fois le contenu prêt et la permission requise obtenue, basculez le parcours en état publié pour le rendre
            éligible au catalogue.</li>
        <li><strong>Assigner et suivre</strong> — Attribuez le parcours aux membres concernés, puis suivez les complétions et, le cas échéant, corrigez
            les rendus nécessitant une relecture humaine.</li>
        <li><strong>Consulter le journal d’audit</strong> — Vérifiez régulièrement les actions sensibles enregistrées si vous êtes chargé de la
            conformité pédagogique.</li>
    </ol>

    <h3>Cas particuliers</h3>
    <p>
        <strong>Formation archivée à réactiver.</strong> Un parcours devenu obsolète peut être archivé sans perdre son contenu ni l’historique de suivi ;
        le repasser en publié le réintègre au catalogue si votre organisation souhaite le remettre en usage, après relecture pour vérifier qu’il reste à
        jour.
    </p>
    <p>
        <strong>Parcours privé sur invitation.</strong> Certaines sessions (formation pilote, groupe restreint, préparation d’un événement précis)
        restent volontairement en état privé : elles ne doivent pas être publiées largement même si leur contenu est stabilisé, le choix relevant d’une
        décision organisationnelle plutôt que de la qualité du contenu.
    </p>
    <p>
        <strong>Échec répété à un quiz.</strong> Si le nombre de tentatives autorisées est atteint sans réussite, un formateur peut réinitialiser la
        tentative ou proposer un accompagnement complémentaire avant une nouvelle évaluation, selon la politique pédagogique retenue.
    </p>
    <p>
        <strong>Attestation à réviser.</strong> Si le contenu d’un parcours change significativement après la délivrance d’attestations, votre
        organisation peut décider de redemander une validation aux membres déjà attestés, plutôt que de considérer l’ancienne attestation comme
        automatiquement caduque : la décision relève du pôle formation.
    </p>
    <p>
        <strong>Publication refusée malgré un menu visible.</strong> Comme rappelé plus haut, l’action de publication peut être grisée ou refusée si la
        permission dédiée manque à votre rôle, y compris pour un auteur ayant créé l’intégralité du contenu : la <a href="#moderation-forum">séparation
        des rôles</a> s’applique aussi à la pédagogie, pour qu’une mise en ligne large reste toujours validée par un rôle habilité.
    </p>
    <p>
        <strong>Membre assigné qui a quitté l’unité.</strong> Si un membre part avant d’avoir terminé un parcours obligatoire, l’assignation devenue
        sans objet peut être retirée par le formateur ou l’administration, sans que cela n’efface l’historique de progression déjà enregistré.
    </p>
    <p>
        <strong>Contenu à corriger après publication.</strong> Une erreur repérée après la mise en ligne d’un parcours ne nécessite pas forcément un
        retour en brouillon : une correction ciblée d’une leçon reste possible pendant que le parcours demeure publié, selon les outils du Studio.
        Pour une refonte plus large, un passage temporaire en privé pendant la relecture évite d’exposer un contenu incomplet aux apprenants en cours de
        parcours.
    </p>
    <p>
        <strong>Portée d’un parcours à changer.</strong> Faire passer un parcours de « communauté » à « proposé sur toute la plateforme » (ou
        inversement) reste réservé aux administrateurs de la plateforme : un formateur local ne peut pas étendre seul la portée d’une formation qu’il a
        créée.
    </p>
    <div class="site-docs__callout site-docs__callout--tip">
        <strong>À retenir.</strong> Le journal d’audit sert à l’explicabilité interne (qui a publié quoi, quand) ; il ne remplace pas d’éventuels
        rapports pédagogiques ou exports statistiques disponibles ailleurs dans l’outil.
    </div>
</section>

<section id="documents" class="site-docs__section">
    <h2>Documents</h2>
    <p class="site-docs__lead">
        L’espace documentaire centralise les fichiers officiels de votre communauté — ordres, modèles, procédures — avec des versions, des droits
        d’accès précis et une distinction claire entre documents ouverts et documents sensibles.
    </p>

    <h3>Présentation générale</h3>
    <p>
        La <strong>bibliothèque documentaire</strong> remplace les échanges informels de fichiers par un espace structuré : chaque document a un
        emplacement stable, une version courante et, selon les réglages de votre organisation, un historique des versions précédentes. L’objectif est
        que chacun retrouve la <strong>bonne version</strong> du bon document sans dépendre d’un envoi individuel par messagerie.
    </p>
    <p>
        L’accès dépend des <strong>permissions</strong> : certains dossiers sont réservés aux cadres ou à des unités précises, d’autres sont ouverts à
        toute la communauté. Un document peut aussi être marqué <strong>sensible</strong>, ce qui restreint sa consultation à des rôles explicitement
        habilités, indépendamment du dossier dans lequel il se trouve.
    </p>
    <p>
        La bibliothèque distingue en général les <strong>documents officiels durables</strong> (ordres permanents, procédures de référence) des
        <strong>documents ponctuels</strong> liés à une activité précise (annexes d’un briefing, support d’une formation). Cette distinction guide le
        rangement : un document durable gagne à vivre dans un dossier thématique stable, tandis qu’un document ponctuel peut rester rattaché à
        l’activité qui l’a produit.
    </p>

    <h3>Fonctionnement</h3>
    <p>
        La plupart des membres <strong>consultent</strong> et téléchargent les documents auxquels ils ont accès. Le <strong>dépôt</strong>, la gestion des
        versions et l’ajustement des droits d’accès sont en général réservés aux rôles « gestion documentaire » ou équivalent, pour garder une base
        cohérente plutôt que de laisser chacun déposer librement sans contrôle.
    </p>
    <div class="site-docs__table-wrap">
        <table class="site-docs__table">
            <thead>
                <tr>
                    <th>Droit</th>
                    <th>Ce qu’il permet</th>
                </tr>
            </thead>
            <tbody>
                <tr>
                    <td>Lecture</td>
                    <td>Consulter et télécharger les documents d’un dossier</td>
                </tr>
                <tr>
                    <td>Dépôt</td>
                    <td>Ajouter un document ou publier une nouvelle version d’un document existant</td>
                </tr>
                <tr>
                    <td>Administration</td>
                    <td>Organiser l’arborescence, ajuster les droits d’accès, archiver ou retirer un document</td>
                </tr>
            </tbody>
        </table>
    </div>
    <p>
        Chaque nouvelle <strong>version</strong> d’un document remplace la version courante affichée par défaut, sans supprimer les révisions
        précédentes : il reste possible de consulter l’historique pour comprendre ce qui a changé ou pour retrouver une ancienne référence si une
        procédure faisait explicitement mention d’une version datée.
    </p>
    <p>
        Les <strong>droits d’accès fins</strong> distinguent en général la lecture, le dépôt et l’administration d’un dossier ou d’un document précis,
        et peuvent être définis par rôle, par service ou par périmètre. Un membre peut ainsi consulter un dossier sans pouvoir y déposer de nouveau
        document, tandis qu’un gestionnaire documentaire cumule les deux.
    </p>
    <p>
        Les équipes habilitées disposent d’un espace de gestion dédié pour organiser la base documentaire proprement : arborescence de dossiers par
        thème ou niveau d’accès, historique et audit des actions sensibles (dépôt, mise à jour, archivage, ajustements d’accès), et possibilité de lier
        un document à d’autres objets du portail (une formation, un dossier de coopération) pour éviter les copies dispersées.
    </p>
    <p>
        Des <strong>métadonnées</strong> accompagnent souvent chaque document (propriétaire, date de validité, niveau de diffusion, mots-clés) pour
        faciliter la recherche et rappeler qui reste responsable du contenu dans la durée. Une convention de nommage stable — thème, version, date —
        complète utilement ces métadonnées lorsque les fichiers sont aussi consultés hors du portail.
    </p>
    <div class="site-docs__callout site-docs__callout--warn">
        <strong>Documents sensibles.</strong> Un document marqué sensible n’apparaît pas pour les rôles non habilités, même s’ils ont accès au dossier
        qui le contient. Ne diffusez jamais un tel document hors des canaux autorisés par votre organisation, même à un collègue qui vous semble
        légitime.
    </div>

    <h3>Utilisation</h3>
    <ol class="site-docs__steps">
        <li><strong>Parcourir l’arborescence</strong> — Ouvrez le dossier correspondant au thème recherché parmi ceux auxquels vous avez accès.</li>
        <li><strong>Consulter ou télécharger</strong> — Ouvrez le document dans le portail ou téléchargez-le selon les options proposées.</li>
        <li><strong>Vérifier la version</strong> — Repérez la date ou le numéro de version affiché avant de vous appuyer sur un document pour une
            décision importante.</li>
        <li><strong>Déposer une mise à jour</strong> — Si vous disposez du droit de dépôt, publiez une nouvelle version en conservant un nom de fichier
            explicite plutôt que de renommer arbitrairement.</li>
        <li><strong>Renseigner les métadonnées</strong> — Complétez propriétaire, niveau de diffusion et mots-clés au dépôt pour que le document reste
            facile à retrouver et à attribuer plus tard.</li>
        <li><strong>Demander un accès manquant</strong> — Si un dossier vous semble pertinent mais reste inaccessible, sollicitez le gestionnaire
            documentaire de votre unité plutôt que de contourner la restriction.</li>
        <li><strong>Archiver un document obsolète</strong> — Si vous disposez du droit d’administration, archivez plutôt que supprimez pour conserver
            la traçabilité.</li>
    </ol>

    <h3>Cas particuliers</h3>
    <p>
        <strong>Version obsolète encore utilisée.</strong> Si un document ancien continue de circuler après une mise à jour, privilégiez l’archivage de
        l’ancienne version plutôt que sa suppression pure et simple : conserver une trace évite les malentendus si quelqu’un cite une version périmée
        de bonne foi.
    </p>
    <p>
        <strong>Conflit de version.</strong> Si deux mises à jour sont déposées presque simultanément, le gestionnaire documentaire tranche laquelle
        devient la version courante ; l’autre reste consultable dans l’historique pour ne perdre aucun travail.
    </p>
    <p>
        <strong>Accès refusé à un document apparemment ouvert.</strong> Un document peut être marqué sensible indépendamment du dossier qui semble
        pourtant accessible : dans ce cas, l’accès au dossier ne suffit pas, une habilitation supplémentaire est nécessaire au niveau du document
        lui-même.
    </p>
    <p>
        <strong>Document lié à un autre module.</strong> Un document rattaché à une formation ou à un dossier de <a
        href="#cooperations-inter-unites">coopération inter-unités</a> reste soumis à ses propres droits d’accès documentaires : être participant du
        module lié ne garantit pas automatiquement la visibilité du document si celui-ci est par ailleurs restreint.
    </p>
    <p>
        <strong>Dossier trop volumineux pour rester lisible.</strong> Lorsqu’un dossier accumule un grand nombre de documents hétérogènes, il devient
        souvent plus efficace de le scinder en sous-dossiers thématiques plutôt que d’ajouter des métadonnées de plus en plus complexes pour compenser
        un rangement devenu confus.
    </p>
    <p>
        <strong>Document sensible à déclasser.</strong> Si un document initialement marqué sensible n’a plus besoin de cette restriction (fin de
        confidentialité, procédure devenue publique), un rôle habilité peut le déclasser explicitement ; ce changement doit rester une décision
        consciente et non un simple oubli de configuration.
    </p>
</section>

<section id="courrier-officiel" class="site-docs__section">
    <h2>Courrier officiel</h2>
    <p class="site-docs__lead">
        Le bureau courrier structure la rédaction, la validation, la signature et l’archivage des courriers officiels de votre organisation, pour
        remplacer les échanges de fichiers épars par un circuit tracé et cohérent.
    </p>

    <h3>Présentation générale</h3>
    <p>
        Le <strong>bureau courrier</strong> permet de suivre les courriers entrants et sortants, leur statut de traitement et les actions attendues de
        chacun. Il s’adresse aux fonctions administratives ou de commandement amenées à produire des correspondances officielles : ordres, notes de
        service, réponses formelles à d’autres unités ou à des instances externes. Si ce module n’apparaît pas pour vous, votre fonction n’y est
        simplement pas associée.
    </p>
    <p>
        Un courrier suit un <strong>circuit de traitement</strong> comparable à celui d’un document papier classique, mais entièrement suivi dans le
        portail : rédaction, relecture, signature, envoi, puis archivage, chaque étape étant horodatée et attribuée à une personne.
    </p>
    <p>
        Le bureau courrier distingue aussi les courriers <strong>sortants</strong> (produits par votre organisation) des courriers <strong>entrants</strong>
        (reçus, puis enregistrés pour garder une trace de leur réception et de leur traitement). Un courrier entrant peut déclencher la rédaction d’un
        courrier sortant en réponse, les deux restant liés dans le suivi du dossier.
    </p>

    <h3>Fonctionnement</h3>
    <h4>Circuit de traitement d’un courrier</h4>
    <div class="site-docs__table-wrap">
        <table class="site-docs__table">
            <thead>
                <tr>
                    <th>État</th>
                    <th>Signification</th>
                    <th>Qui agit</th>
                </tr>
            </thead>
            <tbody>
                <tr>
                    <td>Brouillon</td>
                    <td>Rédaction en cours, non finalisée</td>
                    <td>Le rédacteur</td>
                </tr>
                <tr>
                    <td>Validation</td>
                    <td>Relecture par un responsable avant signature</td>
                    <td>Le ou les validateurs désignés</td>
                </tr>
                <tr>
                    <td>Signé</td>
                    <td>Contenu approuvé et formellement signé</td>
                    <td>Le signataire habilité</td>
                </tr>
                <tr>
                    <td>Envoyé</td>
                    <td>Transmis au destinataire, interne ou externe</td>
                    <td>Le rédacteur ou le bureau courrier</td>
                </tr>
                <tr>
                    <td>Archivé</td>
                    <td>Conservé pour référence et traçabilité administrative</td>
                    <td>Automatique ou manuel selon la politique interne</td>
                </tr>
            </tbody>
        </table>
    </div>
    <p>
        L’<strong>éditeur de courrier</strong> propose des <strong>modèles</strong> avec des variables de fusion (expéditeur, objet, références,
        destinataire) pour accélérer la rédaction des correspondances récurrentes tout en garantissant une présentation homogène. Une
        <strong>numérotation</strong> et une <strong>classification</strong> peuvent être appliquées selon les règles administratives de votre
        organisation, pour retrouver facilement un courrier par sa référence plutôt que par son seul intitulé.
    </p>
    <p>
        La <strong>signature</strong> et sa vérification, lorsque ces options sont activées, garantissent qu’un courrier « signé » a bien été validé
        par la personne habilitée avant son envoi. Un export ou une impression au format adapté à la diffusion externe reste possible pour les besoins
        d’archivage réglementaire hors du portail.
    </p>
    <p>
        Dans un contexte de forte charge, des <strong>presets</strong> et des <strong>extraits de texte réutilisables</strong> permettent d’uniformiser
        les réponses officielles et de limiter les erreurs de forme entre plusieurs rédacteurs d’une même unité.
    </p>
    <p>
        Un niveau de <strong>priorité</strong> ou d’<strong>urgence</strong> peut être associé à un courrier pour le distinguer visuellement des
        correspondances courantes dans les listes du bureau courrier, aidant les validateurs et signataires à traiter en premier ce qui ne peut pas
        attendre.
    </p>

    <h3>Utilisation</h3>
    <ol class="site-docs__steps">
        <li><strong>Créer un brouillon</strong> — Choisissez un modèle adapté ou partez d’une page vierge, renseignez l’objet et les destinataires.</li>
        <li><strong>Rédiger le contenu</strong> — Complétez le corps du courrier en vous appuyant sur les variables de fusion disponibles pour les
            champs récurrents.</li>
        <li><strong>Soumettre à validation</strong> — Envoyez le brouillon vers le ou les responsables désignés pour relecture.</li>
        <li><strong>Faire signer</strong> — Une fois la validation obtenue, transmettez au signataire habilité pour la signature formelle.</li>
        <li><strong>Envoyer</strong> — Transmettez le courrier signé au destinataire selon le canal prévu (interne, externe, papier si nécessaire).</li>
        <li><strong>Vérifier l’archivage</strong> — Confirmez que le courrier envoyé est correctement classé pour rester traçable dans la durée.</li>
        <li><strong>Enregistrer un courrier entrant</strong> — Consignez sa réception, son objet et, si une réponse est attendue, l’échéance associée.</li>
    </ol>
    <p>
        Utilisez les filtres et les étiquettes disponibles pour prioriser les dossiers urgents ou en attente de réponse, notamment lorsque plusieurs
        rédacteurs partagent le même bureau courrier.
    </p>

    <h3>Cas particuliers</h3>
    <p>
        <strong>Courrier refusé en validation.</strong> Si un validateur retourne le courrier, celui-ci repasse en brouillon pour correction plutôt que
        d’être bloqué : reprenez la rédaction en tenant compte des remarques avant de le soumettre à nouveau.
    </p>
    <p>
        <strong>Signataire indisponible.</strong> Selon l’organisation de votre unité, un second signataire habilité peut être désigné pour éviter qu’un
        courrier urgent reste bloqué à l’étape de signature en l’absence d’une personne.
    </p>
    <p>
        <strong>Destinataire externe à la plateforme.</strong> Un courrier envoyé hors du portail (impression, transmission par un canal externe) doit
        malgré tout être marqué comme « envoyé » dans l’outil pour que le suivi administratif reste exact, même si l’envoi réel s’est fait par un autre
        moyen.
    </p>
    <p>
        <strong>Courrier archivé à retrouver.</strong> Utilisez la numérotation ou la classification plutôt qu’une recherche par mémoire du contenu :
        un courrier ancien correctement classé au moment de l’archivage se retrouve bien plus vite qu’en parcourant l’historique au hasard.
    </p>
    <p>
        <strong>Erreur repérée après signature.</strong> Un courrier déjà signé ne se corrige pas en place : selon la gravité de l’erreur, votre
        organisation annule l’envoi et reprend un nouveau brouillon référencé, plutôt que de modifier un contenu déjà approuvé formellement.
    </p>
    <p>
        <strong>Courrier entrant sans réponse attendue.</strong> Tous les courriers entrants ne nécessitent pas de réponse ; marquez-les comme traités
        une fois pris en compte pour ne pas les laisser encombrer indéfiniment la liste des actions en attente.
    </p>
</section>

<section id="evenements-messages-pointage" class="site-docs__section">
    <h2>Événements, messages &amp; pointage</h2>
    <p class="site-docs__lead">
        Ce module couvre trois usages complémentaires de la vie courante d’une unité : la planification et la confirmation de présence aux activités,
        les échanges internes courts distincts du forum, et l’enregistrement des présences lors des manœuvres.
    </p>

    <h3>Présentation générale</h3>
    <p>
        Le calendrier ou la liste d’<strong>événements</strong> annonce les activités collectives : entraînements, briefings, opérations simulées,
        réunions. Chaque événement peut demander une confirmation de présence (<strong>RSVP</strong>), pour donner à l’organisateur une vision claire du
        nombre de participants attendus avant même le jour J.
    </p>
    <p>
        Les <strong>messages internes</strong> permettent des échanges courts et directs entre membres, sans passer par le forum public : ils
        conviennent à une coordination rapide, une question ponctuelle ou un rappel personnel, là où le forum reste réservé à l’information durable et
        structurée à destination d’un public plus large. Les deux canaux ne se substituent pas l’un à l’autre : une décision importante gagne à être
        actée sur le forum ou en briefing, même si elle a été discutée en message.
    </p>
    <p>
        Le <strong>pointage</strong> enregistre les présences ou les passages lors d’une manœuvre ou d’un exercice, selon les règles définies par votre
        organisation. Il donne une trace fiable de qui était réellement présent, complémentaire des confirmations de présence données à l’avance qui
        restent, elles, de simples intentions.
    </p>

    <h3>Fonctionnement</h3>
    <p>
        Un événement porte une date, un lieu ou un cadre, une description, et éventuellement des places limitées ou des critères d’éligibilité (unité,
        rôle). La <strong>confirmation de présence</strong> peut proposer plusieurs réponses (présent, absent, incertain) et être modifiable jusqu’à une
        échéance donnée, pour laisser de la souplesse tout en donnant un signal exploitable à l’organisateur.
    </p>
    <div class="site-docs__table-wrap">
        <table class="site-docs__table">
            <thead>
                <tr>
                    <th>Réponse RSVP</th>
                    <th>Signification pour l’organisateur</th>
                </tr>
            </thead>
            <tbody>
                <tr>
                    <td>Présent</td>
                    <td>Participation attendue, à compter dans l’effectif prévisionnel</td>
                </tr>
                <tr>
                    <td>Incertain</td>
                    <td>Participation possible mais non garantie, à relancer si besoin</td>
                </tr>
                <tr>
                    <td>Absent</td>
                    <td>Participation exclue, aucune relance nécessaire</td>
                </tr>
                <tr>
                    <td>Sans réponse</td>
                    <td>Aucune confirmation reçue ; à considérer comme un point d’attention avant l’échéance</td>
                </tr>
            </tbody>
        </table>
    </div>
    <p>
        Un événement peut être <strong>ponctuel</strong> (une date unique) ou <strong>récurrent</strong> (une permanence hebdomadaire, un entraînement
        mensuel) : dans ce second cas, la confirmation de présence se fait en général occurrence par occurrence, pour refléter la disponibilité réelle
        de chacun plutôt qu’un engagement figé sur toute la série.
    </p>
    <p>
        Des <strong>rappels par courriel</strong> peuvent être envoyés automatiquement à l’approche de l’événement, selon vos préférences de
        notification. Pour les organisations qui l’activent, un <strong>lien d’abonnement calendrier</strong> permet de synchroniser les événements sur
        un agenda externe (application mobile, bureau, client de messagerie), afin de ne pas devoir revenir sur le portail pour connaître son propre
        planning.
    </p>
    <p>
        Les <strong>messages internes</strong> se distinguent du forum par leur portée : un message est en général adressé à une ou plusieurs personnes
        précises, tandis qu’un sujet de forum s’adresse à toute une catégorie. Cette différence structurelle explique pourquoi une information destinée
        à toute l’unité doit être publiée en briefing plutôt qu’envoyée en message individuel à chacun.
    </p>
    <p>
        Le <strong>pointage</strong> se déclenche en général à l’ouverture d’une manœuvre ou d’un créneau défini (« check-in ») : chaque participant
        confirme sa présence effective sur le moment, ce qui alimente ensuite le suivi RH et les retours d’activité, indépendamment de ce qui avait été
        annoncé lors de la confirmation de présence initiale.
    </p>
    <p>
        Côté back-office, les responsables planifient les événements, publient les convocations, suivent les confirmations puis exploitent les
        présences pointées pour le suivi RH. Selon votre plan, des <strong>quotas de création mensuelle</strong> d’événements peuvent s’appliquer.
    </p>
    <p>
        Un événement peut être rattaché à d’autres modules du portail : une fiche du <a href="#mur-operationnel">mur opérationnel</a>, un briefing du
        <a href="#forum-et-briefings">forum</a>, ou une réunion planifiée dans un dossier de <a href="#cooperations-inter-unites">coopération
        inter-unités</a>. Ce lien évite de ressaisir les mêmes informations à plusieurs endroits et garde une cohérence entre les écrans.
    </p>

    <h3>Utilisation</h3>
    <ol class="site-docs__steps">
        <li><strong>Consulter le calendrier</strong> — Repérez les prochaines activités et leurs échéances de confirmation.</li>
        <li><strong>Confirmer votre présence</strong> — Répondez présent, absent ou incertain avant l’échéance indiquée par l’organisateur.</li>
        <li><strong>Ajuster votre réponse si nécessaire</strong> — Modifiez votre confirmation tant que la fenêtre le permet plutôt que de prévenir
            uniquement par un canal informel.</li>
        <li><strong>S’abonner au calendrier externe</strong> — Utilisez le lien d’abonnement, si votre organisation le propose, pour retrouver vos
            échéances directement dans votre agenda habituel.</li>
        <li><strong>Utiliser la messagerie pour un échange rapide</strong> — Réservez les messages internes aux questions ponctuelles adressées à une
            ou quelques personnes, pas aux annonces destinées à toute l’unité.</li>
        <li><strong>Pointer votre présence</strong> — Au début de la manœuvre ou de l’exercice, effectuez le check-in prévu pour être compté comme
            présent.</li>
        <li><strong>Régler vos préférences de notification</strong> — Ajustez les rappels par courriel depuis votre espace personnel selon votre
            besoin réel.</li>
    </ol>
    <p>
        Côté organisateur, publiez la convocation suffisamment en avance pour laisser le temps aux confirmations de se stabiliser, puis relancez
        spécifiquement les réponses « incertain » ou « sans réponse » à l’approche de l’échéance plutôt que de solliciter à nouveau tout le monde.
    </p>

    <h3>Cas particuliers</h3>
    <p>
        <strong>Désistement de dernière minute.</strong> Modifiez votre confirmation de présence dès que possible, même après l’échéance affichée si
        l’outil le permet encore : un désistement tardif mais signalé reste toujours plus utile pour l’organisateur qu’une absence silencieuse le jour
        de l’activité.
    </p>
    <p>
        <strong>Présent confirmé mais absent au pointage.</strong> L’écart entre la confirmation de présence et le pointage réel est normal et attendu :
        c’est précisément ce que le pointage sert à mesurer. Un écart récurrent pour un même membre peut toutefois être suivi côté RH.
    </p>
    <p>
        <strong>Message interne utilisé comme canal d’annonce générale.</strong> Si une information censée toucher toute l’unité circule uniquement par
        messages individuels, elle risque de ne pas atteindre tout le monde ; privilégiez alors un sujet de forum ou un briefing pour garantir une
        diffusion homogène et traçable.
    </p>
    <p>
        <strong>Événement complet.</strong> Si les places disponibles sont toutes prises, une confirmation supplémentaire peut être placée en liste
        d’attente selon la configuration retenue par l’organisateur, plutôt que refusée sans alternative.
    </p>
    <p>
        <strong>Litige sur une présence pointée.</strong> En cas d’erreur ou de contestation sur un pointage (oubli de check-in, erreur de saisie), le
        responsable de l’activité peut corriger manuellement l’enregistrement côté back-office ; signalez la situation rapidement plutôt que longtemps
        après l’exercice, lorsque le contexte est encore facile à vérifier.
    </p>
    <p>
        <strong>Occurrence isolée d’un événement récurrent à annuler.</strong> Annuler une seule date d’une série récurrente n’annule pas les
        occurrences suivantes : chaque date reste indépendante pour la confirmation de présence, même si le motif d’annulation (météo, indisponibilité
        du terrain) peut concerner ponctuellement plusieurs dates à la suite.
    </p>
    <p>
        <strong>Message interne resté sans réponse.</strong> Si un message important n’obtient pas de réaction, envisagez un canal plus visible
        (annonce forum, rappel en réunion) plutôt que de multiplier les messages individuels similaires, qui risquent d’être noyés au même titre que le
        premier.
    </p>
    <div class="site-docs__callout site-docs__callout--tip">
        <strong>Bon réflexe.</strong> Réservez le pointage aux activités qui en ont réellement besoin (manœuvres, exercices encadrés) : l’utiliser pour
        chaque petite réunion informelle alourdit le suivi sans apporter de valeur RH supplémentaire.
    </div>
