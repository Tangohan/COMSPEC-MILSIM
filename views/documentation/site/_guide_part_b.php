<section id="personnel-et-orbat" class="site-docs__section">
    <h2>Personnel, ORBAT &amp; profils métier</h2>
    <p class="site-docs__lead">
        Cette famille d’écrans rassemble tout ce qui décrit <strong>qui compose votre communauté</strong> : l’annuaire des membres, la fiche personnelle
        de chacun, l’ordre de bataille (ORBAT) qui organise les postes, et les engagements visibles sur le mur opérationnel. C’est le référentiel humain
        auquel se raccrochent le forum, les formations, les documents et les événements dès qu’il faut savoir « qui est qui » et « qui fait quoi ».
    </p>

    <h3>Présentation générale</h3>
    <p>
        L’<strong>annuaire</strong> liste les membres de votre organisation avec un niveau de détail qui dépend de vos habilitations : certains voient
        une fiche courte (nom d’usage, affectation, grade), d’autres accèdent à des blocs plus complets (spécialités, historique, informations
        administratives). L’annuaire n’est pas un simple carnet d’adresses : c’est la porte d’entrée vers chaque <strong>fiche personnel</strong>, qui
        centralise l’essentiel d’un membre au même endroit plutôt que de disperser l’information entre forum, messages et tableurs externes.
    </p>
    <p>
        <strong>Ma fiche</strong> est la vue personnelle de votre propre dossier : c’est l’endroit où vous complétez vous-même vos informations,
        consultez votre historique et suivez vos engagements. Elle s’ouvre différemment de la fiche d’un tiers dans l’annuaire, car vous y avez presque
        toujours le droit de modifier vos propres champs, même si vous ne pouvez pas modifier ceux d’un autre membre.
    </p>
    <p>
        L’<strong>ordre de bataille (ORBAT)</strong> présente la structure hiérarchique de l’unité : sections, groupes, postes de commandement,
        chaîne de responsabilité. Il sert de plan de référence pour la coordination sur le terrain et pour comprendre, en un coup d’œil, qui dépend de
        qui. L’ORBAT et l’annuaire sont complémentaires : l’ORBAT montre l’organisation, l’annuaire montre les personnes qui l’occupent.
    </p>

    <h3>Fonctionnement</h3>
    <p>
        Chaque fiche s’articule autour de plusieurs blocs d’information dont le contenu exact varie selon les réglages de votre communauté, mais qui
        suivent en général la même logique :
    </p>
    <div class="site-docs__table-wrap">
        <table class="site-docs__table">
            <thead>
                <tr>
                    <th>Bloc</th>
                    <th>Contenu typique</th>
                    <th>Qui peut le modifier</th>
                </tr>
            </thead>
            <tbody>
                <tr>
                    <td>Identité</td>
                    <td>Nom d’usage, pseudonyme, contact, présentation courte</td>
                    <td>Le membre lui-même, RH avec droit de gestion</td>
                </tr>
                <tr>
                    <td>Affectation</td>
                    <td>Unité, poste occupé, grade, date d’arrivée</td>
                    <td>État-major, RH (S1), cadres selon délégation</td>
                </tr>
                <tr>
                    <td>Profil opérationnel</td>
                    <td>Spécialités, dotations, qualifications internes, transmissions</td>
                    <td>Le membre (déclaratif), validé ensuite par un référent</td>
                </tr>
                <tr>
                    <td>Informations sensibles</td>
                    <td>Éléments médicaux ou personnels dont la diffusion est restreinte</td>
                    <td>Rôles explicitement habilités (ex. RH, OPSAN) uniquement</td>
                </tr>
            </tbody>
        </table>
    </div>
    <p>
        Les <strong>grades</strong> et les <strong>affectations</strong> structurent la fiche et alimentent directement l’ORBAT : changer l’affectation
        d’un membre depuis sa fiche peut déplacer son poste dans l’organigramme sans ressaisie manuelle. Selon la politique de votre unité, la
        modification d’un grade peut être libre pour l’état-major ou nécessiter une double validation (proposition puis confirmation par un supérieur).
    </p>
    <p>
        Pour accélérer la saisie, des <strong>profils métier</strong> prédéfinis (officier opérations, chef de section, fusilier, JTAC, medic, logisticien,
        transmetteur, etc.) peuvent préremplir des champs cohérents : poste type, dotation radio, classe d’équipement, spécialités d’armes. Ce ne sont pas
        des statuts automatiques figés : ils servent de point de départ, toujours ajustable ensuite au cas par cas pour refléter la réalité du membre.
    </p>
    <p>
        Un <strong>indicateur de complétude</strong> peut accompagner chaque fiche pour rappeler les champs encore vides ou à confirmer. Il aide les RH et
        l’état-major à repérer les dossiers à finaliser avant une échéance (recrutement, mission, contrôle administratif), sans bloquer les autres usages
        du portail : une fiche incomplète reste consultable, elle est simplement signalée comme « à compléter ».
    </p>
    <p>
        Les <strong>engagements affichés sur le mur opérationnel</strong> (permanences, missions, formations auxquelles un membre est rattaché) peuvent être
        rappelés depuis sa fiche, pour donner une vue rapide de ce sur quoi la personne est mobilisée sans devoir rouvrir chaque fiche du
        <a href="#mur-operationnel">mur &amp; tableau opérationnel</a> une par une.
    </p>
    <div class="site-docs__callout site-docs__callout--warn">
        <strong>Informations sensibles.</strong> Les données médicales ou personnelles qu’un membre accepte de partager (allergies, contre-indications,
        contacts d’urgence) ne sont visibles que par les rôles explicitement habilités par votre organisation. Un membre « simple » qui consulte une
        fiche ne voit jamais ce bloc, même s’il apparaît pour un RH ou un référent santé.
    </div>

    <h3>Utilisation</h3>
    <ol class="site-docs__steps">
        <li><strong>Consulter l’annuaire</strong> — Parcourez la liste des membres, filtrez par unité ou par poste, ouvrez une fiche pour voir le niveau
            de détail auquel vous avez droit.</li>
        <li><strong>Ouvrir « Ma fiche »</strong> — Accédez à votre propre dossier depuis votre espace personnel plutôt que depuis l’annuaire général.</li>
        <li><strong>Compléter les blocs déclaratifs</strong> — Renseignez identité, profil opérationnel et coordonnées ; utilisez un profil métier pour
            préremplir puis ajustez les champs qui ne correspondent pas exactement à votre situation.</li>
        <li><strong>Demander une correction sur un champ géré par les RH</strong> — Pour l’affectation, le grade ou une information sensible, signalez la
            demande à votre référent plutôt que de tenter une modification directe si le champ n’est pas ouvert à la saisie.</li>
        <li><strong>Suivre vos engagements</strong> — Repérez sur votre fiche les permanences ou missions auxquelles vous êtes rattaché, puis ouvrez le
            mur opérationnel pour le détail complet.</li>
        <li><strong>Parcourir l’ORBAT</strong> — Utilisez la vue hiérarchique pour identifier rapidement un poste, un responsable de section ou une chaîne
            de commandement avant une opération.</li>
    </ol>

    <h3>Cas particuliers</h3>
    <p>
        <strong>Fiche en double.</strong> Si un même membre apparaît deux fois dans l’annuaire (ancien compte, erreur de recrutement), ne créez pas de
        contenu sur l’une des deux fiches : signalez le doublon aux RH, qui fusionnent ou archivent la fiche superflue pour préserver l’historique correct.
    </p>
    <p>
        <strong>Mutation vers une autre unité.</strong> Un changement d’affectation important (transfert de section, détachement) doit être répercuté sur
        la fiche et sur l’ORBAT en même temps ; sinon, le membre peut apparaître au bon endroit dans un écran et à l’ancien endroit dans un autre.
    </p>
    <p>
        <strong>Membre parti ou inactif.</strong> Plutôt que de supprimer une fiche, votre organisation archive généralement le dossier : l’historique
        (missions, formations suivies, affectations passées) reste consultable par les rôles habilités, mais le membre disparaît des listes actives et
        de l’ORBAT courant.
    </p>
    <p>
        <strong>Désaccord sur une information.</strong> Si un membre conteste une donnée saisie par un tiers (grade, spécialité), le bon réflexe est
        d’ouvrir un échange avec le référent RH plutôt que de modifier soi-même un champ verrouillé : la fiche personnel fait référence pour d’autres
        modules (formations, mur opérationnel), une correction informelle non tracée peut créer des incohérences ailleurs.
    </p>
    <p>
        <strong>Visibilité des informations médicales.</strong> Selon la politique de votre unité, un référent santé (rôle « OPSAN » ou équivalent) peut
        voir un sous-ensemble d’informations sensibles que les cadres eux-mêmes ne voient pas : ce cloisonnement est volontaire et ne dépend pas du grade
        du cadre concerné.
    </p>
</section>

<section id="dossier-operateur" class="site-docs__section">
    <h2>Dossier opérateur</h2>
    <p class="site-docs__lead">
        Le <strong>dossier opérateur</strong> est le dossier administratif qui accompagne l’accréditation d’un membre : il ne remplace pas la fiche
        personnel, il en est le complément documentaire lorsqu’une validation formelle est nécessaire avant de considérer quelqu’un comme pleinement
        opérationnel dans votre organisation.
    </p>

    <h3>Présentation générale</h3>
    <p>
        Là où la fiche personnel décrit <em>qui est le membre</em> (identité, affectation, spécialités), le dossier opérateur répond à une question
        différente : <em>a-t-il été accrédité selon la procédure de l’unité ?</em> Il regroupe les pièces attendues, les étapes de validation déjà
        franchies et celles qui restent à traiter, pour que l’état-major ou les instructeurs disposent d’une vue claire sur l’avancement de chaque
        candidature à l’accréditation.
    </p>
    <p>
        Ce dossier peut concerner une accréditation générale (« membre titulaire ») ou une accréditation plus spécifique (qualification à un poste
        sensible, accès à un module précis). Le contenu exact — champs demandés, pièces attendues, nombre d’étapes de validation — dépend entièrement
        des exigences définies par votre organisation : il n’existe pas de gabarit unique imposé par le portail.
    </p>
    <p>
        Une même organisation peut faire vivre <strong>plusieurs types d’accréditation</strong> en parallèle : une accréditation générale à l’arrivée
        d’un nouveau membre, puis des accréditations spécifiques déclenchées plus tard (habilitation radio, encadrement d’exercice, accès à un poste de
        commandement). Un même membre peut ainsi cumuler plusieurs dossiers opérateur à des stades différents, chacun suivant son propre circuit
        d’instruction sans bloquer les autres.
    </p>

    <h3>Fonctionnement</h3>
    <p>
        Un dossier opérateur avance généralement selon trois grandes phases, résumées ci-dessous :
    </p>
    <div class="site-docs__table-wrap">
        <table class="site-docs__table">
            <thead>
                <tr>
                    <th>Phase</th>
                    <th>Ce qui se passe</th>
                    <th>Qui agit</th>
                </tr>
            </thead>
            <tbody>
                <tr>
                    <td>Constitution</td>
                    <td>Le membre renseigne les champs demandés et joint les pièces attendues</td>
                    <td>Le membre concerné</td>
                </tr>
                <tr>
                    <td>Instruction</td>
                    <td>Examen du contenu, vérification des pièces, demande de complément si nécessaire</td>
                    <td>Instructeur ou référent désigné</td>
                </tr>
                <tr>
                    <td>Décision</td>
                    <td>Validation, réserve (complément attendu) ou refus motivé</td>
                    <td>Instructeur, référent ou état-major selon le niveau d’accréditation</td>
                </tr>
            </tbody>
        </table>
    </div>
    <p>
        Chaque étape franchie reste visible dans l’historique du dossier, ce qui évite de devoir redemander « où en est-on » à chaque échange entre le
        membre et son référent.
    </p>
    <p>
        Certaines organisations distinguent explicitement <strong>« Mon accréditation »</strong> — la vue personnelle et synthétique que voit le membre
        sur l’état de sa propre démarche (pièces manquantes, étape en cours, décision rendue) — du <strong>dossier documentaire complet</strong> géré côté
        instruction, qui peut contenir des notes internes, des échanges d’instruction ou des pièces que le membre n’a pas vocation à consulter en détail.
        Cette distinction protège la confidentialité du travail d’instruction tout en gardant le candidat informé de sa progression.
    </p>
    <p>
        Les pièces jointes autorisées (formats, taille, nature du document) sont encadrées par votre organisation : respectez les indications affichées
        sur l’écran de dépôt pour éviter un rejet automatique de la pièce. Selon le type d’accréditation, les pièces attendues peuvent aller d’une simple
        déclaration sur l’honneur à un compte rendu d’évaluation pratique rédigé par un instructeur.
    </p>
    <p>
        Le ou les <strong>référents chargés de l’instruction</strong> ne sont pas forcément les mêmes selon le type d’accréditation : un référent
        pédagogique peut instruire une qualification liée à une formation, tandis qu’un référent RH instruit une accréditation générale de membre
        titulaire. Cette répartition évite qu’une seule personne concentre toutes les décisions, quelle que soit leur nature.
    </p>
    <div class="site-docs__callout site-docs__callout--tip">
        <strong>À retenir.</strong> Un dossier opérateur incomplet n’est pas un échec : c’est un état de travail normal. Complétez-le progressivement et
        laissez l’instructeur indiquer explicitement ce qui manque plutôt que de deviner.
    </div>

    <h3>Utilisation</h3>
    <ol class="site-docs__steps">
        <li><strong>Ouvrir le dossier proposé</strong> — Depuis votre espace personnel, accédez à l’écran d’accréditation associé à votre profil ou à
            votre candidature.</li>
        <li><strong>Renseigner les champs demandés</strong> — Complétez les informations attendues par votre organisation, section par section.</li>
        <li><strong>Joindre les pièces attendues</strong> — Déposez les documents demandés en respectant les formats et tailles indiqués.</li>
        <li><strong>Soumettre le dossier</strong> — Une fois les éléments réunis, validez l’envoi ; le dossier passe alors en instruction.</li>
        <li><strong>Suivre l’avancement</strong> — Consultez « Mon accréditation » pour voir si une pièce complémentaire est demandée ou si une décision
            a été rendue.</li>
        <li><strong>Répondre à une demande de complément</strong> — Si l’instructeur signale un manque, complétez rapidement pour ne pas ralentir le
            traitement de votre dossier.</li>
        <li><strong>Consulter la décision rendue</strong> — Une fois la décision enregistrée, relisez le motif éventuel avant d’envisager toute nouvelle
            démarche.</li>
    </ol>
    <p>
        Côté instructeur, le traitement suit la même logique en miroir : ouvrir le dossier depuis la liste des candidatures à instruire, vérifier les
        pièces, demander un complément si nécessaire en indiquant clairement ce qui manque, puis enregistrer la décision avec un motif compréhensible
        par le membre concerné.
    </p>

    <h3>Cas particuliers</h3>
    <p>
        <strong>Dossier refusé.</strong> Un refus s’accompagne normalement d’un motif compréhensible : lisez-le attentivement avant de recontacter votre
        référent. Selon la politique de l’unité, une nouvelle soumission peut être possible après un délai ou une fois le point bloquant corrigé.
    </p>
    <p>
        <strong>Pièce jointe rejetée.</strong> Si un fichier n’est pas accepté (format ou taille non conformes), le message d’erreur indique la contrainte
        à respecter : reconvertissez ou recompressez le document avant un nouvel envoi plutôt que de multiplier les tentatives identiques.
    </p>
    <p>
        <strong>Accréditation à renouveler.</strong> Certaines qualifications ont une portée limitée dans le temps ou doivent être revues après un
        changement de poste : votre organisation peut alors rouvrir un dossier existant plutôt que d’en créer un nouveau, afin de conserver l’historique
        complet des validations précédentes.
    </p>
    <p>
        <strong>Écart entre « Mon accréditation » et l’avis de l’instructeur.</strong> Si le statut affiché côté membre semble en retard par rapport à un
        échange déjà eu avec un instructeur, patientez le temps que la décision soit formellement enregistrée : les échanges informels ne mettent pas à
        jour automatiquement l’état officiel du dossier.
    </p>
    <p>
        <strong>Plusieurs dossiers ouverts en même temps.</strong> Si un membre est engagé dans une accréditation générale et une accréditation
        spécifique simultanément, chaque dossier avance à son propre rythme : l’avancement de l’un n’accélère ni ne bloque l’autre, sauf si votre
        organisation a explicitement lié les deux démarches.
    </p>
    <p>
        <strong>Instructeur indisponible.</strong> Si un référent d’instruction est temporairement absent, l’état-major peut réattribuer le dossier à un
        autre instructeur habilité plutôt que de laisser la candidature sans suivi pendant une longue période.
    </p>
</section>

<section id="forum-et-briefings" class="site-docs__section">
    <h2>Forum &amp; briefings</h2>
    <p class="site-docs__lead">
        Le forum est l’espace d’échange écrit et durable de votre communauté : il porte les annonces, les discussions courantes et les
        <strong>briefings</strong> qui préparent une activité, tout en respectant des règles de visibilité par catégorie et par section.
    </p>

    <h3>Présentation générale</h3>
    <p>
        Le forum est organisé en <strong>catégories</strong> (annonces, briefings, discussions générales, sections thématiques, etc.), chacune contenant
        des <strong>sujets</strong>. À l’intérieur d’un sujet, les messages s’enchaînent selon le tri choisi (le plus souvent chronologique), ce qui permet
        de suivre une discussion du début à la fin sans se perdre.
    </p>
    <p>
        Les <strong>briefings</strong> sont des sujets à vocation opérationnelle : ils préparent une mission, un entraînement ou un événement, et
        contiennent en général les informations que chaque participant doit avoir lues avant le rendez-vous. Ils peuvent être publiés dans une catégorie
        dédiée pour rester faciles à retrouver, séparément des discussions informelles.
    </p>
    <p>
        Certaines <strong>catégories privées</strong> ne sont visibles que par les membres d’un groupe précis (état-major, une section, un cercle de
        confiance) : leur existence même peut être masquée à qui n’y a pas accès, pour éviter de laisser deviner qu’une discussion sensible existe.
    </p>
    <div class="site-docs__table-wrap">
        <table class="site-docs__table">
            <thead>
                <tr>
                    <th>Type de catégorie</th>
                    <th>Visibilité typique</th>
                    <th>Usage courant</th>
                </tr>
            </thead>
            <tbody>
                <tr>
                    <td>Annonces</td>
                    <td>Toute la communauté, souvent en lecture pour la plupart des membres</td>
                    <td>Informations officielles descendantes</td>
                </tr>
                <tr>
                    <td>Briefings</td>
                    <td>Participants d’une activité ou d’une section précise</td>
                    <td>Préparation de missions et d’entraînements</td>
                </tr>
                <tr>
                    <td>Discussions générales</td>
                    <td>Toute la communauté</td>
                    <td>Échanges informels, questions courantes</td>
                </tr>
                <tr>
                    <td>Sections privées</td>
                    <td>Groupe restreint (état-major, section, cercle de confiance)</td>
                    <td>Discussions internes ou sensibles</td>
                </tr>
            </tbody>
        </table>
    </div>

    <h3>Fonctionnement</h3>
    <p>
        Pour créer un sujet ou répondre, utilisez l’éditeur prévu par le forum. Selon la configuration de votre communauté, des <strong>pièces
        jointes</strong> (images, documents) peuvent être ajoutées, avec des limites de taille et de type de fichier destinées à préserver la fluidité du
        forum et à éviter les dépôts inadaptés.
    </p>
    <p>
        L’accès à une catégorie dépend de votre rôle et, parfois, de votre affectation : un membre d’une section peut voir une catégorie réservée à cette
        section sans y avoir accès pour une autre. Les briefings d’une opération peuvent ainsi n’être visibles que par les participants concernés, sans
        empêcher le reste de la communauté de consulter les catégories ouvertes à tous.
    </p>
    <p>
        Les sujets importants peuvent être <strong>épinglés</strong> pour rester en tête de catégorie, et un sujet clos peut être <strong>verrouillé</strong>
        pour empêcher de nouvelles réponses tout en conservant l’historique lisible. Ces actions relèvent de la modération, détaillée dans la section
        <a href="#moderation-forum">Modération &amp; signalements</a>.
    </p>
    <p>
        Un abonnement à un sujet ou à une catégorie peut déclencher une <strong>notification</strong> à chaque nouvelle réponse, selon vos préférences
        personnelles. C’est particulièrement utile pour un briefing amené à évoluer avant l’activité : plutôt que de rouvrir le fil par habitude, vous
        êtes prévenu dès qu’une consigne change.
    </p>
    <p>
        Une recherche interne au forum permet de retrouver un sujet par mot-clé plutôt que de parcourir manuellement chaque catégorie ; elle est
        particulièrement utile pour retrouver un ancien briefing servant de référence à une nouvelle activité similaire.
    </p>

    <h3>Utilisation</h3>
    <ol class="site-docs__steps">
        <li><strong>Choisir la bonne catégorie</strong> — Repérez la catégorie adaptée au sujet (annonce, briefing, discussion générale) avant de créer un
            nouveau sujet, pour rester facilement retrouvable.</li>
        <li><strong>Rédiger le sujet ou la réponse</strong> — Utilisez l’éditeur pour formuler un message clair ; ajoutez une pièce jointe si le contenu
            le justifie et si votre communauté l’autorise.</li>
        <li><strong>Lire un briefing avant l’activité</strong> — Ouvrez le sujet de briefing associé à une mission ou un entraînement avant le rendez-vous
            pour connaître le cadre, les consignes et les points de vigilance.</li>
        <li><strong>S’abonner à un sujet actif</strong> — Activez les notifications sur un fil amené à évoluer pour ne pas manquer une mise à jour de
            dernière minute.</li>
        <li><strong>Suivre un sujet</strong> — Revenez régulièrement sur un fil actif si vous préférez ne pas dépendre des notifications.</li>
        <li><strong>Signaler un contenu problématique</strong> — Utilisez le bouton de signalement plutôt qu’une réponse publique conflictuelle si un
            message enfreint le règlement.</li>
    </ol>

    <h3>Cas particuliers</h3>
    <p>
        <strong>Section privée invisible pour vous.</strong> Si un collègue mentionne une catégorie que vous ne voyez pas, ce n’est en général pas une
        anomalie : votre rôle ou votre affectation ne couvre pas cette section. Demandez à un référent si vous pensez devoir y avoir accès.
    </p>
    <p>
        <strong>Briefing manqué.</strong> Si vous rejoignez une activité en cours de préparation, ouvrez d’abord le sujet de briefing correspondant avant
        de poser des questions déjà traitées dans le fil : cela évite de disperser l’information entre le forum et d’autres canaux.
    </p>
    <p>
        <strong>Sujet verrouillé après clôture d’une activité.</strong> Un briefing ancien peut être verrouillé une fois l’activité terminée pour préserver
        son contenu comme référence ; ouvrez un nouveau sujet pour tout retour d’expérience plutôt que de tenter de répondre sur un fil clos.
    </p>
    <p>
        <strong>Pièce jointe refusée.</strong> Si un fichier ne peut pas être joint, vérifiez son format et sa taille par rapport aux limites affichées à
        l’écran ; les documents volumineux gagnent souvent à être déposés dans l’espace <a href="#documents">Documents</a> puis liés depuis le forum.
    </p>
    <p>
        <strong>Briefing partagé entre plusieurs unités.</strong> Lorsqu’un briefing concerne une activité menée avec une autre communauté, il peut être
        plus adapté de le tenir dans l’espace commun d’une <a href="#cooperations-inter-unites">coopération inter-unités</a> plutôt que dans une
        catégorie interne, afin que toutes les unités participantes y aient également accès.
    </p>
    <p>
        <strong>Trop de notifications reçues.</strong> Si le forum génère plus de notifications que souhaité, ajustez vos préférences personnelles plutôt
        que de vous désabonner de catégories utiles : un réglage plus fin (résumé regroupé, fréquence réduite) permet souvent de garder l’essentiel sans
        être submergé.
    </p>
</section>

<section id="cooperations-inter-unites" class="site-docs__section">
    <h2>Coopérations inter-unités</h2>
    <p class="site-docs__lead">
        Ce module organise une <strong>collaboration officielle entre deux communautés ou plus</strong> de la même plateforme : brief commun, partage
        d’informations encadré, réunions et suivi d’engagement. Il fournit un <strong>dossier dédié</strong>, une <strong>chronologie</strong> et un
        <strong>espace de discussion partagé</strong>, avec des règles d’accès explicites, sans remplacer ni le forum de votre unité ni vos canaux externes.
    </p>
    <div class="site-docs__callout site-docs__callout--tip">
        <strong>Accès au module.</strong> Si aucun menu « Coopérations inter-unités » n’apparaît, votre compte n’a simplement pas l’habilitation
        correspondante dans la communauté active. Demandez à un responsable de vous l’attribuer, ou de confirmer que la fonction est ouverte aux membres
        comme vous.
    </div>

    <h3>Présentation générale</h3>
    <p>
        Une coopération distingue toujours une <strong>communauté à l’initiative</strong> (souvent dite « unité support »), qui propose la coopération et
        héberge en général l’espace commun une fois celle-ci ouverte, et une ou plusieurs <strong>communautés partenaires</strong>, invitées à rejoindre le
        dossier. Chacune peut accepter, refuser ou négocier avant de participer pleinement aux échanges.
    </p>
    <p>
        Le <strong>dossier de coopération</strong> regroupe la proposition, les invitations, le journal des événements et plusieurs onglets de travail
        (réunion, structures, clôture, retour d’expérience). Pensez-y comme à un <em>dossier vivant</em> qui avance par étapes clairement identifiées,
        chaque étape n’ouvrant que les actions pertinentes à ce moment précis.
    </p>
    <p>
        L’accès principal se fait depuis le <strong>back-office de votre communauté</strong>, dans la zone regroupant les outils métier. Un raccourci peut
        aussi apparaître depuis le tableau de bord selon votre profil. Si un ancien favori pointait vers une adresse différente du module, le portail
        redirige automatiquement vers l’emplacement actuel : le contenu reste identique, seule l’adresse affichée peut changer.
    </p>
    <p>
        Les <strong>permissions</strong> mobilisées par ce module se combinent à plusieurs niveaux : votre rôle général dans la communauté détermine si
        vous voyez le module et pouvez lancer une nouvelle coopération, tandis qu’un rôle attribué nommément dans un dossier précis affine ce que vous y
        êtes autorisé à faire (voir, rédiger, piloter). Un cadre habilité au niveau communauté ne dispose donc pas forcément de tous les droits sur
        chaque dossier existant sans y être explicitement associé.
    </p>

    <h3>Fonctionnement</h3>
    <p>
        La logique générale d’un dossier suit un enchaînement d’étapes, même si le détail des boutons peut varier légèrement selon votre rôle :
    </p>
    <ol class="site-docs__steps">
        <li><strong>Proposition</strong> — L’unité à l’initiative rédige un titre clair, choisit une typologie (entraînement conjoint, appui, échange
            d’information…) et, si besoin, une date limite de réponse et des conditions suspensives (points à lever avant de considérer la coopération
            comme prête à avancer).</li>
        <li><strong>Invitations et acceptation</strong> — Les communautés partenaires sont invitées ; chacune accepte, refuse ou formule une
            contre-proposition. Tant que les parties requises n’ont pas toutes accepté, le dossier ne peut pas avancer vers l’ouverture de l’espace
            commun.</li>
        <li><strong>Autorisation de partage (consentement personnel)</strong> — Chaque participant concerné confirme explicitement, pour son propre
            compte, les familles d’informations qu’il accepte de partager dans ce cadre (brief, organigramme, qualifications, documents de séance…). Pour
            les partages jugés sensibles, une courte justification peut être demandée.</li>
        <li><strong>Confirmation par code de courriel</strong> — Un code à usage limité dans le temps est envoyé sur l’adresse du compte : il doit être
            saisi sur la page indiquée pour valider l’autorisation de partage. En cas d’échec répété, respectez le délai affiché avant de redemander un
            code.</li>
        <li><strong>Activation</strong> — Le dossier passe en « coopération en cours ». Un instantané de contexte peut être enregistré (participants,
            grandes lignes de la proposition, éléments de structure déjà saisis) pour servir de référence en cas de différend ultérieur sur ce qui avait
            été acté au départ.</li>
        <li><strong>Espace commun</strong> — Le fil de discussion partagé devient disponible, avec un message d’accueil récapitulant l’objet, les unités
            engagées et les règles de bon usage.</li>
        <li><strong>Réunion</strong> — Planification d’un rendez-vous (titre, ordre du jour, date, participants attendus), puis enregistrement dans le
            journal une fois tenue, avec lien vers un compte rendu si votre unité en fournit un.</li>
        <li><strong>Clôture</strong> — Motif, bilan synthétique et niveau de conservation des éléments selon les choix proposés par le pilote du dossier.</li>
        <li><strong>Retour d’expérience (REX)</strong> — Après clôture, chaque communauté remplit un formulaire structuré (réussites, difficultés,
            recommandations) ; les personnes habilitées peuvent consulter une vue consolidée regroupant les contributions de toutes les unités.</li>
    </ol>
    <p>
        Le <strong>journal</strong> consigne, de façon horodatée, chaque événement marquant : invitations, validations, ouvertures, messages notables liés
        au processus. Il permet à tout participant de se resynchroniser sans relire l’intégralité du fil de discussion.
    </p>
    <h4>Onglets disponibles pendant la coopération en cours</h4>
    <div class="site-docs__table-wrap">
