    <h3>Utilisation</h3>
    <p>
        Attribuer un rôle à un nouveau membre reste l’action la plus courante en matière de gouvernance quotidienne : elle se fait en général depuis la fiche du membre ou depuis l’espace de gestion des
        effectifs, par une personne disposant de l’État-major ou d’une habilitation équivalente. Comme évoqué au chapitre précédent, des <strong>profils prédéfinis de permissions</strong> (membre actif,
        instructeur, RH &amp; recrutement, modérateur organisation, gestion documentaire, commandement d’unité, pôle formation, cellule recrutement…) permettent d’aligner rapidement un compte sur une
        fonction sans reconstruire un jeu de permissions à la main.
    </p>
    <p>
        Un même membre peut tout à fait porter plusieurs rôles à la fois — par exemple Opérateur et Instructeur — dès lors que sa fonction réelle dans l’unité le justifie ; les permissions des deux rôles
        s’additionnent alors, comme expliqué dans le chapitre <a href="#droits-permissions-et-roles">Droits, permissions &amp; rôles</a>.
    </p>

    <h3>Cas particuliers</h3>
    <p>
        Rien n’empêche une organisation de renommer un rôle par défaut pour mieux correspondre à son vocabulaire interne (par exemple « Chef de section » au lieu de « Cadre »), ou d’en créer de nouveaux
        entièrement sur mesure. Ce qui prime toujours pour le comportement du site, c’est l’ensemble des permissions effectivement rattachées au rôle, indépendamment de son intitulé affiché.
    </p>
    <p>
        Un membre en <strong>Période d’essai</strong> qui semble avoir moins d’accès que ses camarades n’est pas nécessairement mal configuré : ce rôle est volontairement restrictif, le temps que sa
        titularisation soit actée par l’état-major. De même, un compte « Visiteur » qui ne voit qu’une partie limitée du site correspond à un usage attendu, par exemple pour un futur candidat qui explore
        l’unité avant de déposer un dossier de candidature.
    </p>
</section>

<section id="navigation-et-recherche" class="site-docs__section">
    <h2>Navigation &amp; recherche</h2>
    <p class="site-docs__lead">
        Le portail regroupe un grand nombre de modules ; la navigation et la recherche existent pour que vous n’ayez jamais besoin de mémoriser où se trouve chaque fonction pour la retrouver rapidement.
    </p>

    <h3>Présentation générale</h3>
    <p>
        La barre de navigation en haut de l’écran regroupe les zones principales du site : accueil, tableau de bord, opérations, ressources, personnel, formations, administration, selon ce que vos droits
        autorisent à afficher. Plutôt que de lister tous les écrans à plat, elle les organise en <strong>méga-menus</strong> thématiques, afin qu’un domaine entier (par exemple tout ce qui concerne les
        formations) reste regroupé visuellement même s’il contient plusieurs sous-écrans.
    </p>

    <h3>Fonctionnement</h3>
    <p>
        Chaque entrée de menu est reliée, en coulisse, à une ou plusieurs permissions. Si vous n’avez pas l’habilitation correspondante, l’entrée n’apparaît simplement pas, plutôt que d’être affichée
        grisée ou verrouillée : c’est pour cette raison que deux membres d’une même unité peuvent voir des barres de navigation sensiblement différentes, sans que cela traduise une anomalie.
    </p>
    <p>
        Une <strong>recherche globale</strong> complète la navigation par menu : elle permet de retrouver rapidement un module, une fiche personnel, un document ou tout autre élément indexé par le site,
        sans avoir à parcourir les menus pas à pas. Selon la configuration de votre instance, un raccourci clavier peut ouvrir cette recherche instantanément, où que vous soyez sur le site.
    </p>

    <h3>Utilisation</h3>
    <p>
        Pour un résultat pertinent, commencez par un <strong>mot-clé court et distinctif</strong> (un nom, un intitulé de formation, un mot précis d’un document) plutôt qu’une phrase complète, puis affinez
        si la liste de résultats est trop longue. La recherche respecte vos permissions : elle ne vous proposera jamais un contenu auquel vous n’avez pas accès, ce qui évite de « découvrir » l’existence
        d’une information sans pouvoir l’ouvrir.
    </p>
    <div class="site-docs__callout">
        <strong>Astuce.</strong> Si vous cherchez un module précis plutôt qu’un contenu (par exemple « mur opérationnel » ou « courrier »), la recherche vous mènera généralement plus vite à l’écran voulu
        qu’un parcours manuel dans les méga-menus, surtout lorsque vous découvrez encore l’organisation du site.
    </div>

    <h3>Cas particuliers</h3>
    <p>
        Si un module que vous savez actif dans votre organisation n’apparaît dans aucun menu ni dans la recherche, la cause la plus probable reste une permission manquante plutôt qu’un module désactivé :
        demandez confirmation à un référent avant de conclure à un problème technique. Sur les petits écrans (mobile, tablette), la navigation peut se replier dans un menu compact : le contenu proposé
        reste identique, seule la présentation change pour s’adapter à l’espace disponible.
    </p>
    <p>
        Après un changement de communauté active, comme expliqué au chapitre <a href="#communaute-et-contexte">Communauté &amp; contexte</a>, les menus se recalculent entièrement selon vos droits dans la
        nouvelle communauté : ne soyez pas surpris de voir des entrées apparaître ou disparaître d’un coup.
    </p>
</section>

<section id="tableau-de-bord" class="site-docs__section">
    <h2>Tableau de bord</h2>
    <p class="site-docs__lead">
        Le tableau de bord est l’écran d’accueil qui vous attend après connexion : il résume ce qui compte pour vous aujourd’hui, sans que vous ayez à parcourir tous les modules pour le savoir.
    </p>

    <h3>Présentation générale</h3>
    <p>
        Sa raison d’être est de faire gagner du temps : plutôt que de vérifier tour à tour le forum, les formations, les événements et le mur opérationnel, le tableau de bord met en avant les éléments qui
        vous concernent directement — rappels, dossiers à suivre pour les équipes habilitées, liens vers les modules que vous utilisez le plus souvent. Il ne remplace aucun module en détail ; il en est le
        point d’entrée synthétique.
    </p>

    <h3>Fonctionnement</h3>
    <p>
        Le contenu du tableau de bord est composé de <strong>blocs</strong> alimentés par les différents modules du site : messages importants, recrutements en attente pour les équipes concernées,
        activités ou missions à venir, rappels de formation, etc. Chaque bloc n’apparaît que si vous disposez des habilitations nécessaires pour voir l’information qu’il contient, et que si une donnée
        pertinente existe réellement à afficher : un tableau de bord peut donc sembler « vide » pour un compte tout juste créé, simplement parce qu’aucune activité ne le concerne encore.
    </p>
    <p>
        Les administrateurs de communauté peuvent en outre proposer des <strong>raccourcis</strong> vers des pages fréquemment utilisées (back-office, modération, pilotage du mur opérationnel, etc.),
        afin que les équipes habilitées y accèdent en un clic depuis leur écran d’accueil plutôt qu’en naviguant par les menus.
    </p>

    <h3>Utilisation</h3>
    <p>
        Consultez le tableau de bord en début de session pour repérer rapidement ce qui demande votre attention : un rappel, un message à lire, une action attendue de votre part sur un dossier en cours.
        Pour l’encadrement, il constitue souvent le point de départ naturel avant d’ouvrir un module précis en détail, par exemple le pilotage du mur opérationnel ou la liste des candidatures en attente.
    </p>

    <h3>Cas particuliers</h3>
    <p>
        Un tableau de bord très différent entre un membre simple et un cadre de la même communauté est normal : chacun voit les blocs correspondant à ses propres habilitations et à ses propres
        responsabilités. Si un bloc attendu ne s’affiche pas, vérifiez d’abord s’il existe réellement une donnée à afficher (par exemple aucune candidature en attente) avant de suspecter une permission
        manquante ; en cas de doute persistant, un référent pourra confirmer si le bloc devrait apparaître pour votre rôle.
    </p>
</section>

<section id="mur-operationnel" class="site-docs__section">
    <h2>Mur &amp; tableau opérationnel</h2>
    <p class="site-docs__lead">
        Le mur opérationnel est le tableau de situation de votre communauté : permanences, consignes, informations flash, missions, formations et tâches internes y sont rassemblées pour que chacun sache,
        d’un coup d’œil, quoi regarder sans fouiller le forum ou la messagerie. Ce chapitre en détaille le fonctionnement complet : c’est, avec les droits et rôles, le module le plus riche du portail.
    </p>

    <h3>Présentation générale</h3>
    <p>
        Ce module répond à un besoin très concret dans une unité milsim : centraliser en un seul endroit une situation qui évolue en permanence — qui tient une permanence aujourd’hui, quelle mission est
        en cours, quelle consigne vient de changer — plutôt que de la faire circuler de façon dispersée entre le forum, la messagerie interne et le bouche-à-oreille. L’état-major y <strong>publie une
        situation claire</strong> ; les membres y consultent <strong>ce qui les concerne</strong>, filtré selon leur unité, leur emploi et le niveau de sensibilité de l’information.
    </p>

    <h4>Le mur et le tableau : deux écrans, un seul outil</h4>
    <p>
        Il est important de bien distinguer deux écrans qui partagent la même base de données mais servent des publics différents. Le <strong>mur opérationnel</strong>, accessible depuis le menu du même
        nom, est l’écran de <strong>consultation</strong> destiné à tous les membres autorisés à le voir : il n’affiche que les fiches déjà <strong>publiées</strong> et pertinentes pour la personne qui
        le consulte. Le <strong>tableau opérationnel</strong>, accessible depuis le back-office sous l’intitulé « Pilotage du mur opérationnel », est l’écran de <strong>gestion</strong> réservé aux
        personnes habilitées à créer, valider, publier, clôturer une fiche, définir des modèles ou changer la posture de la communauté.
    </p>
    <p>
        Pour garder une vision d’ensemble sans quitter le pilotage, un bouton <strong>Vue membres</strong> permet de basculer instantanément vers ce que voient réellement les membres consultant le mur —
        utile pour vérifier qu’une fiche publiée apparaît bien comme prévu, avec le bon niveau de visibilité, avant de considérer la publication comme terminée. À l’inverse, depuis le mur, une personne
        habilitée retrouve un accès direct vers <strong>Ouvrir le pilotage</strong> ou vers <strong>Publier une fiche</strong>, sans devoir chercher l’écran de gestion dans les menus généraux.
    </p>
    <div class="site-docs__callout site-docs__callout--tip">
        <strong>Droits.</strong> Deux habilitations distinctes gouvernent ce module : <strong>Consulter le tableau opérationnel (portail)</strong> pour voir le mur, et <strong>Créer et modifier les
        entrées du tableau opérationnel</strong> pour accéder au pilotage. Si vous voyez le mur sans le moindre bouton de gestion, votre rôle est volontairement en lecture seule : c’est le cas le plus
        courant, pas une anomalie.
    </div>

    <h3>Fonctionnement</h3>
    <p>
        Le fonctionnement du mur opérationnel repose sur quatre notions qui s’articulent entre elles : une <strong>posture</strong> globale de la communauté, des <strong>types de fiches</strong> adaptés
        à chaque situation, un <strong>cycle de vie</strong> qui encadre la publication et le suivi de chaque fiche, et des mécanismes de <strong>réutilisation</strong> (mise à jour opérationnelle,
        modèles) pour éviter de repartir de zéro à chaque fois.
    </p>

    <h4>La posture de la communauté</h4>
    <p>
        Un badge de <strong>posture</strong> s’affiche en permanence en haut du mur comme du tableau : il donne, en un seul coup d’œil, le niveau de tension global de l’unité, indépendamment du détail de
        chaque fiche. Seul le pilotage peut changer cette posture, via une liste déroulante suivie du bouton <strong>Appliquer</strong> ; les membres la consultent, mais ne la modifient jamais depuis le
        mur.
    </p>
