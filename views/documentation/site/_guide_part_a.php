<section id="introduction" class="site-docs__section">
    <h2>Introduction</h2>
    <p class="site-docs__lead">
        Athena est le portail qui rassemble, pour une communauté milsim, tout ce qui se trouvait auparavant éparpillé entre un serveur de discussion, quelques fichiers partagés et des tableurs personnels :
        les effectifs, les rôles et les droits, le forum, les documents officiels, les formations, le courrier, et le pilotage des activités au jour le jour via le mur opérationnel. Ce chapitre pose les repères
        indispensables avant de parcourir le reste du guide.
    </p>

    <h3>Présentation générale</h3>
    <p>
        Concrètement, le portail sert deux publics à la fois. D’un côté, les <strong>membres</strong> qui viennent consulter une consigne, s’inscrire à une formation, lire un sujet de forum ou vérifier
        leur fiche personnel. De l’autre, l’<strong>encadrement</strong> (état-major, cadres, référents de pôle) qui prépare le contenu, valide les décisions et pilote la vie de l’unité : publication d’une
        situation sur le mur, mise en ligne d’une formation, gestion des accès, suivi du recrutement. Le même site sert donc à la fois de vitrine de consultation et d’outil de gestion, la différence entre
        les deux tenant presque toujours à une question de <strong>droits</strong>, pas de compte différent.
    </p>
    <p>
        Le portail n’essaie pas d’imposer une doctrine ou un vocabulaire à votre unité. Les intitulés de rôles, les rubriques de classement, la manière dont vous découpez vos formations, tout cela reste
        <strong>configurable</strong> par votre organisation. Ce guide décrit le comportement standard proposé par le site ; il ne remplace jamais le règlement intérieur ou les consignes internes de votre
        chaîne de commandement lorsque celles-ci sont plus strictes.
    </p>

    <h3>Fonctionnement</h3>
    <p>
        Deux principes structurent presque tous les modules du portail, et les comprendre une bonne fois vous fera gagner beaucoup de temps par la suite. Le premier est celui de la <strong>communauté active</strong> :
        tout ce que vous voyez (personnel, documents, forum, formations, mur opérationnel) est rattaché à l’organisation dans laquelle vous êtes actuellement connecté ; ce point est détaillé dans le chapitre
        <a href="#communaute-et-contexte">Communauté &amp; contexte</a>. Le second est celui du <strong>cycle brouillon → publié</strong> : que ce soit une fiche du mur opérationnel, une formation dans le Studio
        ou un courrier officiel, le contenu passe presque toujours par une phase de préparation invisible du grand public avant d’être diffusé de façon contrôlée. Une fois ce schéma reconnu dans un module,
        vous le retrouverez presque à l’identique dans les autres.
    </p>
    <p>
        Par-dessus ces deux principes vient la couche des <strong>habilitations</strong> : chaque action sensible (publier, modifier, supprimer, consulter une information restreinte) est reliée à une permission
        précise, elle-même regroupée dans des rôles attribués aux comptes. Le chapitre <a href="#droits-permissions-et-roles">Droits, permissions &amp; rôles</a> explique ce mécanisme en détail ; retenez pour
        l’instant que <strong>ne pas voir un bouton ou un menu est presque toujours normal</strong> et ne traduit pas un dysfonctionnement du site.
    </p>

    <h3>Utilisation</h3>
    <p>
        Ce guide est organisé en chapitres autonomes, accessibles depuis le sommaire affiché à côté de ce texte (ou via le bouton dédié sur mobile). Chaque chapitre répond, dans l’ordre, à des questions
        pratiques : à quoi sert le module, comment il fonctionne dans les grandes lignes, comment on l’utilise au quotidien, puis quelles sont les situations particulières à connaître. Vous pouvez lire le
        guide dans l’ordre pour découvrir le portail pas à pas, ou aller directement au chapitre qui vous concerne grâce au filtre de recherche du sommaire.
    </p>
    <p>
        La plupart des membres n’ont besoin de lire en détail que quelques chapitres : compte et sécurité, navigation, tableau de bord, et le ou les modules réellement utilisés par leur unité (mur
        opérationnel, formations, forum, personnel…). Les chapitres orientés pilotage (droits et rôles, back-office, administration) intéressent surtout l’état-major et les référents de pôle.
    </p>
    <div class="site-docs__callout site-docs__callout--tip">
        <strong>À retenir.</strong> Gardez votre adresse courriel à jour dans votre profil : elle sert à confirmer les actions sensibles, à recevoir les rappels importants et, le cas échéant,
        à débloquer votre compte en cas d’incident de connexion.
    </div>

    <h3>Cas particuliers</h3>
    <p>
        Si vous participez à plusieurs communautés sur la même plateforme, le contenu affiché change selon celle qui est active au moment où vous naviguez : un document ou une fiche du mur vus dans une
        unité ne réapparaissent pas automatiquement dans une autre. Si une page attendue reste introuvable après avoir vérifié la communauté active, le plus efficace est de demander confirmation à un
        référent plutôt que de multiplier les tentatives : il peut s’agir d’une fonctionnalité non activée pour votre organisation, et non d’un problème sur votre compte.
    </p>
    <p>
        Enfin, gardez à l’esprit que ce guide décrit un comportement général : votre organisation peut avoir renommé certains rôles, adapté des libellés ou désactivé un module entier. En cas d’écart entre
        ce texte et ce que vous observez à l’écran, l’interface et les consignes internes de votre unité font foi.
    </p>
</section>

<section id="compte-et-securite" class="site-docs__section">
    <h2>Compte &amp; sécurité</h2>
    <p class="site-docs__lead">
        Votre compte est la porte d’entrée unique vers le portail : identifiants, adresse courriel de contact, profil visible par les autres membres et préférences de notifications. Ce chapitre explique
        comment le protéger, comment le tenir à jour, et que faire lorsqu’une vérification de sécurité vous est demandée.
    </p>

    <h3>Présentation générale</h3>
    <p>
        Un compte Athena regroupe trois familles d’informations : des <strong>identifiants de connexion</strong> (adresse courriel et mot de passe), une <strong>adresse courriel de contact</strong> utilisée pour
        les échanges sensibles et les rappels, et un <strong>profil</strong> qui décrit qui vous êtes au sein de votre communauté (selon ce que votre organisation autorise à afficher). Ces trois éléments sont
        indépendants des permissions : posséder un compte ne donne accès qu’aux fonctions de base ; le reste dépend du rôle qui vous a été attribué dans votre organisation.
    </p>
    <p>
        La sécurité du compte est traitée comme un sujet à part entière plutôt que comme un simple détail technique, parce qu’un compte compromis dans une unité milsim peut donner accès à des informations
        de coordination, des coordonnées de membres ou des documents internes. Le site combine donc plusieurs mécanismes de protection classiques : mot de passe, vérification de l’adresse courriel, et
        surveillance des tentatives de connexion inhabituelles.
    </p>

    <h3>Fonctionnement</h3>
    <p>
        La connexion se fait avec votre adresse courriel et votre mot de passe. En cas d’oubli, un lien dédié sur la page de connexion permet de recevoir un message pour <strong>choisir un nouveau mot de
        passe</strong> de manière sécurisée ; ce lien de réinitialisation n’est valable que pendant une durée limitée et ne peut être utilisé qu’une seule fois, par prudence.
    </p>
    <p>
        Lorsque vous créez un compte ou que vous changez d’adresse courriel, le site vous demande généralement de <strong>confirmer</strong> cette adresse en cliquant sur un lien reçu par courrier
        électronique. Cette étape existe pour s’assurer que l’adresse indiquée vous appartient réellement : tant qu’elle n’est pas validée, certaines actions sensibles (recevoir des messages officiels,
        finaliser certaines démarches) peuvent rester bloquées, sans que le reste du compte soit inutilisable pour autant.
    </p>
    <p>
        En arrière-plan, le portail observe les signaux de connexion suspects : plusieurs échecs de mot de passe rapprochés, connexion depuis un contexte inhabituel, etc. Selon la configuration de votre
        organisation, cela peut se traduire par une alerte affichée à l’écran, un message envoyé sur votre adresse courriel, ou une limitation temporaire des nouvelles tentatives afin de décourager les
        essais automatisés.
    </p>

    <h3>Utilisation</h3>
    <p>
        Depuis votre espace personnel, vous pouvez à tout moment mettre à jour votre <strong>profil</strong> (informations visibles selon les règles fixées par votre communauté) et ajuster vos
        <strong>préférences</strong> : canaux de notification, affichage de certaines informations aux autres membres, etc. Il est recommandé de revoir ces réglages après un changement d’affectation, de
        grade ou de moyen de contact, pour que les informations utiles à votre unité restent exactes.
    </p>
    <p>
        Le changement de mot de passe se fait depuis les paramètres de sécurité de votre compte, ou via le lien de réinitialisation si vous êtes déconnecté. Après l’avoir modifié, on vous demande en
        général de vous reconnecter avec le nouveau mot de passe ; pensez à le mettre à jour partout où vous l’aviez éventuellement enregistré (gestionnaire de mots de passe, appareil mobile).
    </p>
    <div class="site-docs__callout site-docs__callout--warn">
        <strong>Vigilance.</strong> Ne partagez jamais vos identifiants, même avec un camarade d’unité de confiance, et déconnectez-vous systématiquement des postes partagés (salle de briefing, ordinateur
        commun). Un compte permet d’identifier une action précise (message, publication, modification) ; le prêter revient à effacer cette traçabilité.
    </div>

    <h3>Cas particuliers</h3>
    <p>
        Si vous ne recevez pas le message de confirmation ou de réinitialisation attendu, vérifiez d’abord le dossier des courriers indésirables, puis l’exactitude de l’adresse enregistrée sur votre
        compte, avant de redemander un nouvel envoi : multiplier les demandes rapprochées peut déclencher un délai d’attente de sécurité.
    </p>
    <p>
        En cas de doute sur une utilisation frauduleuse de votre compte (connexion que vous ne reconnaissez pas, modification que vous n’avez pas faite), changez immédiatement votre mot de passe puis
        prévenez un référent de votre organisation : selon les outils disponibles pour votre communauté, l’administration peut consulter l’historique des actions récentes pour évaluer la situation.
        Si vous avez perdu l’accès à votre adresse courriel de compte, un administrateur de votre organisation peut vous aider à en enregistrer une nouvelle après vérification de votre identité.
    </p>
</section>

<section id="communaute-et-contexte" class="site-docs__section">
    <h2>Communauté &amp; contexte</h2>
    <p class="site-docs__lead">
        Le portail peut héberger plusieurs communautés indépendantes sur la même plateforme. Votre session est toujours rattachée à une <strong>communauté active</strong> : comprendre ce mécanisme évite
        bien des confusions, notamment si vous appartenez à plusieurs unités ou si vous coopérez ponctuellement avec une autre.
    </p>

    <h3>Présentation générale</h3>
    <p>
        Une communauté correspond, dans le vocabulaire du site, à votre <strong>unité</strong> ou <strong>organisation</strong> : elle possède ses propres membres, ses propres rôles, son propre forum, ses
        propres documents, ses propres formations et son propre mur opérationnel. Deux communautés distinctes ne partagent en principe aucune de ces données entre elles, sauf lorsqu’un module de
        collaboration explicite (comme les coopérations inter-unités) est utilisé pour ouvrir un espace commun limité et encadré.
    </p>
    <p>
        Cette séparation par communauté existe pour protéger la confidentialité de chaque unité : les effectifs, les échanges internes et les documents d’une organisation ne doivent pas être visibles par
        une autre organisation qui utiliserait la même plateforme, à moins qu’un partage explicite ne l’autorise.
    </p>

    <h3>Fonctionnement</h3>
    <p>
        Lorsque vous êtes connecté, le site retient quelle communauté est actuellement <strong>active</strong> pour votre session : c’est cette communauté qui déterminera les menus affichés, les
        permissions appliquées, et le contenu que vous verrez dans chaque module (personnel, forum, mur opérationnel, formations, documents…). Si votre compte n’est associé qu’à une seule communauté,
        cette étape est invisible et se fait automatiquement.
    </p>
    <p>
        Si vous appartenez à plusieurs communautés, un mécanisme de <strong>changement de contexte</strong> vous est proposé, en général depuis le menu de votre profil ou depuis l’en-tête du portail.
        Basculer d’une communauté à une autre recharge entièrement le contenu affiché : menus, listes et droits peuvent changer d’un coup, puisque vous n’avez pas nécessairement le même rôle ni les mêmes
        habilitations dans chaque organisation.
    </p>

    <h3>Utilisation</h3>
    <p>
        Avant toute action sensible — publier un message officiel, déposer un document, créer une fiche sur le mur opérationnel — prenez l’habitude de vérifier <strong>quelle communauté est active</strong>,
        en particulier si vous jonglez régulièrement entre plusieurs unités. Cette vérification prend quelques secondes et évite l’erreur la plus fréquente de ce mécanisme : publier au bon endroit, mais
        dans la mauvaise organisation.
    </p>
    <p>
        Si votre rôle diffère d’une communauté à l’autre (par exemple simple membre dans l’une, cadre dans l’autre), attendez-vous à voir apparaître ou disparaître des menus entiers après un changement de
        contexte : ce n’est pas une anomalie, c’est le reflet exact de vos habilitations respectives dans chaque organisation.
    </p>

    <h3>Cas particuliers</h3>
    <p>
        Un module de <strong>coopération inter-unités</strong>, lorsqu’il est activé, permet à deux organisations ou plus d’ouvrir un espace commun encadré (fil de discussion partagé, journal, autorisations
        de partage explicites) sans pour autant fusionner leurs communautés ni donner un accès complet à leurs données internes respectives. Ce module reste l’exception qui confirme la règle : en dehors de
        lui, chaque communauté demeure cloisonnée.
    </p>
    <p>
        Si vous ne retrouvez plus un contenu que vous aviez consulté récemment, la cause la plus fréquente est un changement de communauté active depuis votre dernière visite. Revérifiez le sélecteur de
        communauté avant de conclure à une suppression ou à un problème d’accès.
    </p>
</section>

<section id="etapes-de-mise-en-service" class="site-docs__section">
    <h2>Étapes de mise en service</h2>
    <p class="site-docs__lead">
        Ce chapitre présente un parcours type pour une unité qui déploie Athena pour la première fois. Il ne s’agit pas d’une procédure imposée par le site, mais d’un enchaînement logique observé dans la
        plupart des organisations, que vous pouvez adapter à votre contexte.
    </p>

    <h3>Présentation générale</h3>
    <p>
        Mettre en service le portail consiste, dans l’ordre, à installer le cadre (organisation, rôles), puis à peupler les espaces de contenu (forum, documents, formations), puis à faire entrer les
        effectifs, avant de basculer en exploitation courante. Respecter globalement cet ordre évite l’écueil le plus fréquent des déploiements précipités : inviter tous les membres avant que les rôles et
        les règles de base ne soient prêts, ce qui génère de la confusion et des demandes de support répétées.
    </p>

    <h3>Fonctionnement</h3>
    <p>
        Chaque étape du parcours dépend en partie de la précédente. Les rôles doivent exister avant que les invitations n’aient un sens, puisque c’est le rôle qui détermine ce qu’un nouveau membre pourra
        faire dès sa première connexion. De la même façon, les catégories de forum et les dossiers documentaires gagnent à être définis avant l’arrivée massive de membres, pour éviter que chacun ne crée
        ses propres repères de façon désordonnée.
    </p>
    <p>
        Certaines étapes nécessitent des droits élevés (administration de l’organisation, gestion documentaire, publication de formations) et sont donc naturellement réservées à l’état-major ou aux
        référents de pôle désignés ; les membres « simples » n’interviennent qu’une fois la communauté prête à les accueillir, ce qui est normal et attendu.
    </p>

    <h3>Utilisation</h3>
    <p>
        Voici le déroulé habituel, étape par étape ; l’ordre exact peut varier légèrement selon les priorités de votre organisation.
    </p>
    <ol class="site-docs__steps">
        <li>
            <strong>Création ou rattachement de la communauté</strong>
            La structure de l’unité est configurée (nom, identité visuelle le cas échéant) et les premiers comptes reçoivent les habilitations de pilotage nécessaires pour continuer la mise en place.
            C’est le socle sur lequel tout le reste repose.
        </li>
        <li>
            <strong>Rôles et invitations</strong>
            L’état-major définit les rôles utiles à l’unité (voir <a href="#droits-permissions-et-roles">Droits, permissions &amp; rôles</a> et <a href="#roles-communaute-et-metiers">Rôles communauté &amp; métiers</a>),
            envoie les invitations et valide les comptes créés. Prendre le temps de bien calibrer les rôles à ce stade évite d’avoir à corriger des dizaines de comptes individuellement plus tard.
        </li>
        <li>
            <strong>Forum et documents</strong>
            Mise en place des catégories de discussion et des règles de publication, puis des dossiers documentaires et de leurs niveaux d’accès. Ces deux espaces servent de socle d’information stable
            pour toute la suite du déploiement.
        </li>
        <li>
            <strong>Formations</strong>
            Création des parcours dans l’espace d’édition dédié, construction des modules et leçons, relecture en brouillon, puis passage à l’état publié pour qu’ils apparaissent au catalogue des
            apprenants. Il est recommandé de tester un parcours en interne avant de l’ouvrir largement.
        </li>
        <li>
            <strong>Effectifs</strong>
            Saisie ou import des fiches personnel, affectations et structure hiérarchique ; le cas échéant, ouverture du recrutement et du dossier opérateur pour les nouvelles candidatures. C’est
            généralement à cette étape que l’essentiel des membres rejoint effectivement le portail.
        </li>
        <li>
            <strong>Exploitation courante</strong>
            Une fois les fondations posées, la vie de l’unité repose sur les modules déjà configurés : mur opérationnel pour la situation courante, événements, pointage, messagerie interne. Le
            déploiement initial cède la place à un usage régulier, qui appelle surtout de la maintenance légère (mise à jour des rôles, des documents, du catalogue de formations).
        </li>
    </ol>
    <div class="site-docs__callout">
        <strong>Remarque.</strong> Rien n’empêche de mener plusieurs étapes en parallèle (par exemple préparer le forum pendant que les formations sont encore en rédaction) : l’ordre proposé ici sert de
        repère logique, pas de contrainte rigide imposée par le site.
    </div>

    <h3>Cas particuliers</h3>
    <p>
        Une unité qui migre depuis un autre outil peut être tentée d’importer massivement du contenu ancien sans relecture : mieux vaut le passer d’abord en brouillon ou en accès restreint, puis le publier
        progressivement une fois vérifié, plutôt que de tout exposer d’un coup à des membres qui découvrent le nouvel outil.
    </p>
    <p>
        Une réorganisation ultérieure (fusion de rôles, refonte des catégories de forum, changement de structure hiérarchique) reste toujours possible après la mise en service initiale ; elle demande
        simplement plus de coordination puisque des membres actifs utilisent déjà l’outil au quotidien. Une unité peut également choisir de n’activer qu’une partie des modules (par exemple sans mur
        opérationnel dans un premier temps) : le parcours ci-dessus s’applique alors uniquement aux étapes réellement utilisées.
    </p>
</section>

<section id="droits-permissions-et-roles" class="site-docs__section">
    <h2>Droits, permissions &amp; rôles</h2>
    <p class="site-docs__lead">
        Comprendre la différence entre une permission et un rôle est la clé pour se repérer dans tout le reste du portail : ce chapitre explique ce mécanisme une fois pour toutes, afin que les autres
        chapitres puissent s’y référer sans le répéter.
    </p>

    <h3>Présentation générale</h3>
    <p>
        Le site distingue ce que <strong>vous pouvez faire concrètement</strong> — voir un document, publier un message, créer une fiche sur le mur opérationnel, assigner une formation — de la manière dont
        ces capacités sont <strong>regroupées et attribuées</strong> à un compte. La première notion s’appelle une <strong>permission</strong> ; la seconde s’appelle un <strong>rôle</strong>. Un rôle n’est
        rien d’autre qu’un ensemble cohérent de permissions, réuni sous un intitulé métier facile à attribuer.
    </p>
    <p>
        Cette séparation permet à votre organisation de rester souple : elle peut créer autant de rôles qu’elle le souhaite, avec les intitulés qui font sens pour son fonctionnement interne (chef de
        section, officier renseignement, cellule communication…), sans que le site n’impose une liste figée. Ce qui compte réellement pour le comportement du portail, ce sont les permissions attachées à
        ce rôle, pas son nom.
    </p>

    <h3>Fonctionnement</h3>
    <p>
        Les permissions sont regroupées par grands domaines fonctionnels : forum (lire, écrire, modérer), documents (consulter, déposer, gérer les accès), formations (suivre un parcours, être assigné,
        corriger des rendus, publier du contenu), personnel (consulter ou modifier des fiches, informations sensibles, affectations), mur opérationnel (consulter, créer et modifier les entrées),
        invitations et gestion des membres, courrier officiel, et ainsi de suite. Les libellés exacts affichés à l’écran restent d’ordre métier, jamais des codes techniques.
    </p>
    <p>
        Deux périmètres bien distincts se superposent à ces domaines fonctionnels, résumés dans le tableau ci-dessous.
    </p>
    <div class="site-docs__table-wrap">
        <table class="site-docs__table">
            <thead>
                <tr>
                    <th scope="col">Périmètre</th>
                    <th scope="col">Ce qu’il couvre</th>
                    <th scope="col">Qui en dispose typiquement</th>
                </tr>
            </thead>
            <tbody>
                <tr>
                    <td>Organisation (communauté)</td>
                    <td>La quasi-totalité des actions du quotidien : forum, personnel, formations, documents, mur opérationnel, invitations, back-office de l’unité.</td>
                    <td>État-major, cadres, référents de pôle, membres selon leur rôle dans <em>votre</em> communauté.</td>
                </tr>
                <tr>
                    <td>Plateforme entière</td>
                    <td>Un petit nombre de réglages transverses à toutes les communautés : supervision globale, maintenance, audit technique.</td>
                    <td>Administrateurs de la plateforme, hors périmètre d’une unité classique.</td>
                </tr>
            </tbody>
        </table>
    </div>
    <p>
        En pratique, la très grande majorité des membres — y compris l’état-major d’une unité — n’a jamais besoin du second périmètre : il concerne l’équipe qui maintient la plateforme pour l’ensemble des
        communautés qu’elle héberge, pas la gouvernance d’une unité en particulier.
    </p>

    <h3>Utilisation</h3>
    <p>
        Attribuer une permission par une permission à chaque nouveau compte serait long et source d’erreurs ; c’est pourquoi l’administration peut appliquer des <strong>profils prédéfinis</strong> qui
        activent d’un coup un ensemble cohérent de permissions adapté à une fonction courante. On retrouve par exemple des profils comme <em>Membre actif</em>, <em>Instructeur / formateur</em>,
        <em>RH &amp; recrutement</em>, <em>Modérateur forum (organisation)</em>, <em>Gestion documentaire</em>, <em>Commandement unité</em>, <em>Pôle formation</em>, <em>Cellule recrutement</em> ou
        <em>Administration organisation (complète)</em>. Ces profils accélèrent la mise en place ; des ajustements fins restent toujours possibles ensuite pour un compte précis, sans devoir repartir de
        zéro.
    </p>
    <p>
        Lorsqu’un compte cumule plusieurs rôles, les permissions qui en résultent s’additionnent : rien de ce qui est autorisé par un rôle n’est retiré par un autre. À l’inverse, retirer un rôle retire
        immédiatement les permissions qui n’étaient portées que par lui — sauf si une autre source (rôle ou attribution individuelle) les couvre également.
    </p>
    <div class="site-docs__callout site-docs__callout--tip">
        <strong>Publication des formations.</strong> Passer une formation en « publié », comme créer ou modifier une entrée du mur opérationnel, peut être réservé à certains rôles seulement : si le menu
        existe mais que l’action est refusée, c’est en général une permission précise qui manque (publication, gestion du mur), pas un dysfonctionnement du site.
    </div>

    <h3>Cas particuliers</h3>
    <p>
        Une bonne pratique largement recommandée est le <strong>principe du moindre privilège</strong> : attribuer à chaque rôle uniquement les permissions réellement nécessaires à sa fonction, plutôt que
        d’accorder « tout » par défaut pour éviter les demandes répétées. Cela limite les conséquences d’une erreur ou d’un compte compromis, et clarifie les responsabilités au sein de l’unité.
    </p>
    <p>
        Il arrive qu’un membre voie un menu apparaître sans pouvoir en utiliser le contenu (par exemple consulter le mur opérationnel sans pouvoir y créer de fiche) : c’est le signe que seule la
        permission de <strong>consultation</strong> lui a été accordée, et non celle de <strong>création ou de modification</strong>. Ce cas est fréquent et volontaire : de nombreux modules distinguent
        justement une population qui regarde d’une population plus restreinte qui pilote.
    </p>
</section>

<section id="roles-communaute-et-metiers" class="site-docs__section">
    <h2>Rôles communauté &amp; métiers</h2>
    <p class="site-docs__lead">
        Chaque communauté dispose d’un ensemble de rôles système aux intitulés directement inspirés du vocabulaire milsim. Ce chapitre décrit l’esprit de chacun d’eux ; les permissions réellement actives
        restent celles effectivement attachées au rôle dans votre organisation.
    </p>

    <h3>Présentation générale</h3>
    <p>
        Les rôles livrés par défaut couvrent deux grandes familles : les rôles de <strong>gouvernance</strong>, qui pilotent l’unité dans son ensemble, et les rôles <strong>opérationnels</strong>, qui
        correspondent à des fonctions courantes au sein d’une communauté (instruction, modération, ressources humaines, recrutement, santé, logistique, transmissions…). Ces intitulés servent de point de
        départ ; votre organisation peut les renommer, les dupliquer ou en créer de nouveaux selon son organigramme réel.
    </p>

    <h3>Fonctionnement</h3>
    <p>
        Le <strong>Fondateur</strong> porte la vision et la validation stratégique de la communauté, sans que ce rôle confère à lui seul l’administration technique de l’ensemble de la plateforme.
        L’<strong>État-major</strong> assure la direction courante : effectifs, structure, rôles, invitations, modération au niveau organisationnel et paramètres généraux de l’unité. Ces deux rôles forment
        le socle de gouvernance ; tous les autres rôles opérationnels s’organisent en dessous.
    </p>
    <p>
        Les rôles opérationnels, quant à eux, correspondent chacun à une fonction précise et reconnaissable dans une unité milsim. L’<strong>Opérateur</strong> est le membre titulaire type, avec accès au
        forum, aux documents standards et aux formations selon son affectation. Le <strong>Cadre</strong> assure l’encadrement et la coordination d’équipe, avec une visibilité renforcée sur les ressources
        utiles au commandement. Le <strong>Modérateur forum</strong> gère les espaces de discussion de l’unité — épinglage, signalements, catégories — mais uniquement à l’échelle de son organisation, pas
        de la plateforme entière. Le <strong>RH (S1)</strong> tient les dossiers personnel, les grades et le suivi administratif des effectifs, tandis que le <strong>Recruteur</strong> anime le pipeline
        de recrutement et les échanges avec les candidats, en liaison avec le commandement. Le <strong>Visiteur</strong> dispose d’un accès limité, en attente d’intégration ou en tant que compte
        prospect, avec une lecture ciblée. L’<strong>Instructeur</strong> pilote le pôle formation : parcours, assignations, correction des rendus et suivi des qualifications. L’<strong>OPSAN</strong>
        couvre le volet santé et secours, avec une visibilité sur les informations médicales autorisées lorsque la politique de l’unité le permet. La <strong>Logistique</strong> gère le soutien matériel,
        les fiches équipement et la documentation associée, tandis que le <strong>R2 (transmissions)</strong> diffuse les informations officielles et coordonne les annonces. Enfin, la <strong>Période
        d’essai</strong> encadre la participation d’un nouveau membre au forum en attendant sa titularisation complète.
    </p>
