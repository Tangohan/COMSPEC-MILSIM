    <h4>Les types de fiches</h4>
    <p>
        Chaque fiche créée sur le tableau opérationnel appartient à un <strong>type</strong>, qui détermine à la fois sa présentation sur le mur et l’usage qu’on en attend. Une <strong>permanence</strong>
        décrit une astreinte, une veille ou un poste fixe ; elle est regroupée sur le mur en fonction de sa proximité dans le temps, entre ce qui se déroule aujourd’hui, ce qui est en cours et ce qui est à
        venir, pour permettre un repérage rapide des relèves. Une <strong>information pratique</strong> couvre des éléments plus durables — horaires, contacts, consignes permanentes — qui n’ont pas
        vocation à changer d’un jour à l’autre. Une <strong>manifestation</strong> correspond à un dispositif public ou à un événement structuré nécessitant une préparation spécifique. Une
        <strong>mission</strong> décrit une opération avec des objectifs et des moyens identifiés, tandis qu’une <strong>tâche</strong> représente plutôt une action interne de coordination, souvent plus
        modeste qu’une mission complète. Une <strong>formation</strong> signale un stage ou une séance pédagogique cadrée, en complément du catalogue de formations proprement dit. Enfin, la
        <strong>flash information</strong> se distingue des autres types par son urgence : elle est mise en avant dans un bandeau dédié, pensé pour être vu immédiatement, y compris en mode synthèse crise.
    </p>
    <p>
        Choisir le bon type dès la création n’est pas un détail cosmétique : il conditionne l’endroit où la fiche apparaîtra sur le mur et la manière dont les membres s’attendent à la retrouver. Une
        mission classée par erreur comme simple tâche risque, par exemple, de passer inaperçue dans un contexte où l’attention se porte avant tout sur les opérations en cours.
    </p>

    <h4>Le cycle de vie d’une fiche</h4>
    <p>
        Toute fiche du tableau opérationnel suit un cycle en cinq grandes étapes, de sa création jusqu’à sa clôture. Ce cycle garantit qu’aucune information n’atterrit sur le mur des membres sans être
        passée par une préparation et, selon les cas, une validation.
    </p>
    <ol class="site-docs__steps">
        <li>
            <strong>Création</strong>
            Une fiche peut naître de plusieurs façons : une nouvelle entrée créée librement, un modèle réutilisé, une création rapide, ou encore le bouton <strong>Publier au mur opérationnel</strong>
            disponible depuis un événement, une formation ou une coopération inter-unités, qui prégénère un brouillon lié à sa source. Dans tous les cas, ce premier enregistrement produit un
            <strong>brouillon</strong>, invisible sur le mur des membres tant qu’il n’a pas été publié.
        </li>
        <li>
            <strong>Préparation</strong>
            La fiche est ensuite complétée : intitulé clair, rubrique de classement, dates de validité, niveau de priorité (Faible, Normale, Élevée ou Critique), public visé (qui, sur le mur, doit voir
            cette fiche), niveau de sensibilité, description, responsabilités, effectifs et moyens engagés, et le cas échéant les points de contrôle attendus avant clôture. Cette étape se conclut par
            l’enregistrement de la fiche, qui reste encore au statut brouillon.
        </li>
        <li>
            <strong>Publication</strong>
            Une fois la fiche jugée prête, l’action <strong>Approuver</strong> — ou <strong>Mettre en ligne</strong> selon le contexte — la fait basculer sur le mur, où elle devient visible par les
            membres correspondant au public défini. L’action <strong>Refuser</strong> permet, à l’inverse, d’annuler cette diffusion si la fiche n’est finalement pas prête ou pertinente.
        </li>
        <li>
            <strong>Suivi</strong>
            Pendant toute la durée de vie opérationnelle de la fiche, son statut est mis à jour pour refléter la réalité du terrain : Planifié, En cours, Suspendu, Terminé ou Annulé, avec le cas échéant
            un découpage en phases successives (Phase 1, Phase 2, Phase 3) pour les actions les plus longues. Tenir ce statut à jour est ce qui rend le mur réellement utile en cours d’exécution, plutôt
            qu’une simple photographie figée au moment de la publication.
        </li>
        <li>
            <strong>Clôture</strong>
            Lorsque l’action est terminée, la fiche est <strong>clôturée</strong>, ce qui la fait passer au statut Terminé. Si des points de contrôle obligatoires restent ouverts, la clôture est refusée
            par le site : ils doivent d’abord être validés, afin que rien d’important ne soit oublié au moment de refermer le dossier.
        </li>
    </ol>
    <p>
        Deux mécanismes complètent ce cycle sans en faire formellement partie. Le <strong>retrait du mur</strong> permet de faire disparaître une fiche de la vue des membres — avec un motif optionnel
        conservé pour le journal — tout en gardant son historique consultable en pilotage via le filtre <strong>Retirées du mur</strong> ; rien n’est donc jamais perdu, seule la diffusion cesse. La
        <strong>réutilisation</strong>, quant à elle, permet de partir d’une fiche existante plutôt que de repartir de zéro, via <strong>Copier en brouillon</strong>, via la mise à jour opérationnelle
        détaillée ci-dessous, ou via <strong>Enregistrer comme modèle</strong> pour capitaliser sur une fiche bien construite.
    </p>

    <h4>Mise à jour opérationnelle (FRAGO)</h4>
    <p>
        Sur une fiche publiée ou en cours d’exécution, le bouton <strong>Mise à jour opérationnelle</strong> crée une nouvelle fiche dérivée, dont le titre reprend le type « FRAGO » (ordre fragmentaire),
        en reprenant le contenu, les effectifs, les moyens et les points de contrôle de la fiche d’origine — ces derniers étant remis à l’état non validé, puisqu’un amendement peut modifier ce qui doit
        être vérifié. Ce mécanisme est particulièrement adapté lorsqu’une situation évolue en cours d’exécution et qu’il faut communiquer un changement sans effacer la trace de la fiche initiale : les
        deux fiches restent consultables, la nouvelle prolongeant explicitement l’historique de la précédente.
    </p>

    <h4>Points de contrôle</h4>
    <p>
        Certaines fiches embarquent une liste de <strong>points de contrôle</strong> — des vérifications concrètes attendues avant de considérer l’action comme terminée. Leur état d’avancement est
        affiché directement sur la carte, sous la forme <strong>Points de contrôle : X / Y</strong>, ce qui permet à quiconque consulte le mur ou le pilotage d’évaluer en un instant si une action est
        réellement prête à être clôturée. Chaque point se valide ou s’annule individuellement depuis la fiche.
    </p>
    <div class="site-docs__callout site-docs__callout--warn">
        <strong>Règle de clôture.</strong> Il est impossible de clôturer une fiche tant qu’un point de contrôle obligatoire reste ouvert. Cette contrainte est volontaire : elle évite qu’une action soit
        déclarée terminée alors qu’une vérification essentielle (sécurité, matériel, présence) n’a pas été faite.
    </div>

    <h4>Rubriques et modèles</h4>
    <p>
        Pour garder un mur lisible malgré le volume de fiches qui s’accumulent, deux outils de classement sont disponibles. Les <strong>rubriques</strong> permettent d’ajouter une catégorie de classement
        personnalisée, définie par un nom et une couleur, puis d’assigner cette rubrique à chaque fiche pour faciliter le filtrage visuel sur le mur. Les <strong>modèles</strong>, quant à eux, servent à
        gagner du temps sur les fiches récurrentes : générer un brouillon directement depuis un modèle existant, créer un squelette entièrement vide pour démarrer une nouvelle famille de modèles, ou
        transformer une fiche déjà rédigée en modèle réutilisable — sans conserver ses dates ni son rattachement à une source métier spécifique, puisqu’un modèle doit rester générique.
    </p>
    <p>
        Si votre communauté n’a encore défini aucun modèle, le site propose d’emblée quelques exemples types (permanence de formation, mission type, flash court) pour amorcer la bibliothèque plutôt que
        de partir d’une page blanche.
    </p>

    <h4>Publication liée à un événement, une formation ou une coopération</h4>
    <p>
        Plusieurs modules du portail permettent de faire naître directement une fiche du tableau opérationnel depuis leur propre écran, plutôt que de dupliquer manuellement une information déjà saisie
        ailleurs. Depuis un événement, une formation ou un dossier de coopération inter-unités, le bouton <strong>Publier au mur opérationnel</strong> crée un brouillon prérempli et explicitement
        <strong>lié</strong> à sa source d’origine ; il ne reste plus qu’à le compléter avant de l’approuver ou de le mettre en ligne comme n’importe quelle autre fiche.
    </p>
    <p>
        Ce lien évite les doublons involontaires : si une fiche non annulée est déjà rattachée à la même source, le portail vous y renvoie directement plutôt que d’ouvrir une deuxième fiche parallèle
        pour le même événement. Une fois cette fiche retirée du mur, une nouvelle publication liée à la même source peut de nouveau être créée si le besoin se représente.
    </p>

    <h3>Utilisation</h3>
    <p>
        Utiliser le tableau opérationnel au quotidien consiste surtout à combiner les <strong>filtres et modes d’affichage</strong> du pilotage pour se concentrer sur ce qui compte à un instant donné, à
        respecter les <strong>audiences et niveaux de sensibilité</strong> définis sur chaque fiche, et à connaître la portée exacte des <strong>deux habilitations</strong> du module.
    </p>

    <h4>Filtres et modes d’affichage (pilotage)</h4>
    <p>
        Depuis le pilotage, la liste des fiches peut être filtrée par état de publication — publiées, brouillons, retirées du mur, ou toutes confondues —, par période, par type de fiche, par statut
        opérationnel ou par étiquette, afin de retrouver rapidement un sous-ensemble pertinent parmi un volume qui peut vite devenir important. En complément des filtres de liste, trois modes de vue
        adaptent l’affichage à l’usage du moment : la <strong>vue complète</strong> montre toutes les cartes correspondant aux filtres actifs, la <strong>vue synthèse crise</strong> met en avant les
        fiches critiques et celles en cours d’exécution, et la <strong>vue briefing</strong> allège la présentation des cartes pour un point de situation rapide, par exemple en début de session.
    </p>
    <p>
        Deux outils de suivi complètent ces filtres : un <strong>journal récent</strong> qui retrace les actions effectuées sur le mur, et une <strong>activité temps réel</strong> qui rafraîchit
        automatiquement le flux des événements côté pilotage, utile lorsqu’une situation évolue rapidement et que plusieurs personnes interviennent en parallèle sur le tableau.
    </p>

    <h4>Audiences et niveau de sensibilité</h4>
    <p>
        Chaque fiche définit précisément <strong>qui</strong> doit la voir sur le mur : l’ensemble de la communauté, une unité particulière, un ou plusieurs emplois désignés, ou encore un usage strictement
        personnel tant que la fiche reste en brouillon. Ce réglage se combine avec un <strong>niveau de sensibilité</strong>, qui distingue une diffusion large d’une information réservée à l’encadrement
        ou traitée comme confidentielle. Sur le mur, un membre ne voit donc jamais que les fiches qui lui sont réellement destinées ; les personnes habilitées au pilotage voient, en plus, les niveaux les
        plus restreints, puisque leur rôle suppose une vision d’ensemble de la situation.
    </p>

    <h4>Droits : consulter vs créer et modifier</h4>
    <p>
        Le module repose sur deux habilitations bien séparées, qu’il est utile de garder à l’esprit en permanence. <strong>Consulter le tableau opérationnel (portail)</strong> donne accès au mur en
        lecture : c’est l’habilitation la plus largement distribuée, puisqu’elle correspond simplement au besoin de connaître la situation de son unité. <strong>Créer et modifier les entrées du tableau
        opérationnel</strong> ouvre en revanche le pilotage complet : création, validation, publication, clôture, gestion des modèles et changement de posture. Sur le mur destiné aux membres, aucune
        création ni validation n’est jamais possible, quelles que soient les habilitations : c’est une consultation filtrée selon l’audience et la sensibilité, point final.
    </p>

    <h4>Bonnes pratiques</h4>
    <p>
        Quelques réflexes simples améliorent nettement la qualité d’un mur opérationnel dans le temps. Formulez des titres <strong>actionnables</strong>, construits sur le schéma verbe, objet et
        échéance, plutôt que des intitulés vagues : « Tenir permanence radio — vendredi 20 h » se comprend instantanément, à la différence d’un simple « Permanence ». Renseignez la rubrique et les
        mots-clés dès la création plutôt qu’après coup, pour que le classement reste exploitable dès le premier jour. Maintenez le statut opérationnel à jour pendant l’exécution : un mur dont les statuts
        ne bougent jamais perd rapidement la confiance des membres qui le consultent. Évitez d’ouvrir deux fiches distinctes pour une même action en cours ; privilégiez la publication liée ou la
        duplication plutôt que la création parallèle, qui sème la confusion sur la version de référence. Validez systématiquement les points de contrôle avant de songer à clôturer, et retirez du mur ce
        qui n’est plus d’actualité plutôt que de laisser s’accumuler des fiches obsolètes. Enfin, en période de tension, basculez la posture sur <strong>Crise</strong>, activez le mode <strong>synthèse
        crise</strong> en pilotage, et privilégiez des flashs courts plutôt que des fiches longues, pour que l’essentiel reste immédiatement lisible.
    </p>

    <h4>Scénarios types</h4>
    <p>
        <strong>Côté état-major :</strong> une session commence typiquement par l’ouverture du tableau opérationnel, suivie d’une vérification rapide de la posture affichée. Vient ensuite la création
        d’une fiche — librement, depuis un modèle, ou directement depuis un événement grâce à la publication liée —, puis la définition précise du public visé et du niveau de sensibilité avant de publier
        via Approuver ou Mettre en ligne. Le reste de la session consiste à suivre l’évolution du statut, à valider les points de contrôle au fil de l’exécution, puis à clôturer la fiche une fois l’action
        terminée, ou à la retirer du mur si elle n’a plus lieu d’être maintenue visible.
    </p>
    <p>
        <strong>Côté membre :</strong> l’usage est volontairement plus simple. On ouvre le mur opérationnel, on lit la posture affichée en haut de l’écran ainsi que les éventuels flashs d’information, puis
        on parcourt les colonnes utiles à son propre rôle — les permanences du jour pour savoir qui assurer la relève, les informations pratiques pour une consigne durable, les missions en cours pour
        suivre une opération à laquelle on participe. Si une information semble manquante ou erronée, le réflexe attendu reste de solliciter l’état-major plutôt que de chercher à corriger soi-même une
        fiche, sauf si l’on dispose soi-même de l’habilitation de pilotage.
    </p>

    <h3>Cas particuliers</h3>
    <p>
        Si vous tentez de créer une publication liée depuis un événement, une formation ou une coopération alors qu’une fiche non annulée existe déjà pour cette même source, le portail vous redirige vers
        cette fiche existante plutôt que d’en ouvrir une seconde : c’est un comportement volontaire pour éviter les doublons, pas une erreur de manipulation de votre part. Vous pouvez, si besoin, retirer
        du mur la fiche existante et en publier une nouvelle si son contenu doit repartir de zéro.
    </p>
    <p>
        Une clôture refusée sans message d’erreur explicite provient presque toujours d’un point de contrôle obligatoire resté ouvert : reprenez la fiche, vérifiez la liste des points de contrôle, et
        validez ceux qui manquent avant de retenter la clôture. Une fiche retirée du mur n’est jamais supprimée : elle reste consultable en pilotage via le filtre dédié, et son historique demeure exploitable
        pour un retour d’expérience ultérieur ou pour resservir de base à une mise à jour opérationnelle.
    </p>
    <p>
        Enfin, en situation de forte activité (posture Alerte ou Crise, plusieurs fiches critiques ouvertes simultanément), privilégiez systématiquement la vue synthèse crise en pilotage plutôt que la vue
        complète : elle a précisément été conçue pour ce contexte, en mettant mécaniquement en avant les fiches critiques et celles en cours, sans effort de filtrage manuel supplémentaire de votre part.
    </p>

