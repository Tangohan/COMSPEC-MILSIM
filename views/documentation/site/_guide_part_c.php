<section id="equipement-et-modpacks" class="site-docs__section">
    <h2>Équipement &amp; modpacks</h2>
    <p class="site-docs__lead">
        Ce module rassemble tout ce qui décrit <strong>ce que porte et utilise un membre</strong> lorsqu’il rejoint une activité : la dotation
        individuelle, les classes d’équipement associées à un poste, et les <strong>modpacks</strong> qui listent les modules attendus pour participer
        à une session sur un environnement donné. L’objectif est simple : que chacun arrive préparé avec le bon matériel logiciel et la bonne dotation,
        sans avoir à reconstituer la liste par bouche-à-oreille avant chaque manœuvre.
    </p>

    <h3>Présentation générale</h3>
    <p>
        Dans une unité milsim, deux réalités se superposent en permanence. La première est la <strong>dotation individuelle</strong> : le paquetage,
        les tenues, l’armement simulé, les moyens de transmission qu’un membre est censé posséder ou avoir déclaré. La seconde est le
        <strong>modpack</strong> : l’ensemble des modules logiciels (extensions du simulateur, cartes, contenus additionnels) qu’il faut avoir installés
        et activés pour rejoindre une session sans provoquer d’incompatibilité. Ces deux volets répondent à la même question — « suis-je prêt à
        participer ? » — mais concernent des plans différents, et le module les présente côte à côte pour éviter de les confondre.
    </p>
    <p>
        La dotation reste avant tout <strong>déclarative et documentaire</strong> : elle sert de référence commune pour vérifier qu’une section dispose
        du matériel attendu, pour préparer une commande groupée, ou pour cadrer ce qu’un nouveau membre doit se procurer avant sa première sortie. Le
        portail ne prétend pas gérer un inventaire physique en temps réel ; il fournit un cadre lisible où l’équipement de référence, les classes de
        poste et les besoins par activité sont décrits une fois, puis réutilisés sans ressaisie.
    </p>
    <p>
        Le modpack, lui, joue un rôle plus opérationnel : c’est la liste faisant foi de ce qu’il faut installer. Une divergence de modpack entre deux
        participants est l’une des causes les plus fréquentes d’échec de connexion à une session ; centraliser cette liste dans le portail plutôt que
        dans un message éphémère évite les « moi je n’ai pas le même que toi » de dernière minute, juste avant le lancement.
    </p>

    <h3>Fonctionnement</h3>
    <p>
        L’équipement s’organise autour de <strong>classes</strong> rattachées à un poste ou à un profil métier. Une classe regroupe un ensemble
        cohérent de dotation attendue pour une fonction donnée — fusilier, opérateur transmissions, secouriste, pilote — et sert de gabarit lorsqu’un
        membre reçoit une affectation. Comme pour les fiches personnel décrites dans le chapitre <a href="#personnel-et-orbat">Personnel &amp; ORBAT</a>,
        ces classes sont un point de départ ajustable, pas un carcan : un membre peut compléter ou adapter sa dotation réelle sans casser la référence
        de sa classe.
    </p>
