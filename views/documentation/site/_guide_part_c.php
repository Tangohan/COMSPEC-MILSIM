    <h4>La situation tactique et le TACMAP</h4>
    <p>
        Sur le TACMAP, la situation se lit à travers des <strong>marqueurs</strong> normalisés qui distinguent au minimum les éléments amis, neutres
        et hostiles, et précisent quand c’est utile la nature de l’élément (unité d’infanterie, poste de commandement, moyen particulier). Cette
        symbologie partagée est essentielle : elle permet à deux participants qui ne se sont jamais parlé de lire la même carte de la même manière,
        sans traduction ni légende improvisée. Les annotations et tracés éventuels (axes, zones, points de rendez-vous) viennent enrichir cette lecture
        commune pour préparer ou suivre une manœuvre. La
        <a href="<?= htmlspecialchars(url('documentation/marqueurs'), ENT_QUOTES, 'UTF-8') ?>">bibliothèque de marqueurs</a>
        regroupe les aperçus et libellés de référence.
    </p>
    <p>
        La carte évolue en <strong>temps quasi réel</strong> : les positions se rafraîchissent au fil des remontées, ce qui fait du TACMAP un outil de
        conduite et non une simple photographie de départ. Cette fraîcheur suppose en retour que chaque participant maintienne sa liaison active et
        remonte correctement sa position, faute de quoi la carte affiche une situation partielle qui peut induire le commandement en erreur.
    </p>

    <h4>L’Overwatch et ses filtres</h4>
    <p>
        L’Overwatch s’adresse à ceux qui doivent <strong>superviser</strong> plutôt que manœuvrer. Il propose des <strong>filtres de
        commandement</strong> pour isoler un sous-ensemble pertinent — une unité précise, un type d’élément, une zone — sans être noyé sous
        l’intégralité des marqueurs, et un <strong>suivi de l’état des personnels</strong> (dimension santé) permettant de repérer rapidement les
        éléments signalés en difficulté. L’idée directrice est de donner au commandement la bonne densité d’information : assez pour décider, pas au
        point de perdre l’essentiel dans le détail.
    </p>
    <p>
        Ces filtres ne modifient pas la situation elle-même : ils changent seulement ce qui est affiché à l’écran de celui qui supervise. Deux
        superviseurs peuvent donc regarder la même situation sous des angles différents — l’un centré sur la santé des éléments, l’autre sur une zone
        géographique — sans se gêner mutuellement ni altérer la carte partagée.
    </p>

    <h4>Le poste de commandement (C2)</h4>
    <p>
        Le <strong>poste de commandement</strong> est le point de pilotage d’où l’on conduit l’activité : il combine la vue d’ensemble de la situation
        et la capacité de coordonner. C’est typiquement depuis le C2 que l’on décide d’un mouvement, que l’on répartit l’attention entre plusieurs
        zones, et que l’on croise la situation cartographique avec les autres informations de l’unité (fiches du mur, briefings, effectifs engagés).
        Le C2 ne remplace pas le TACMAP ou l’Overwatch : il les fédère au service de la décision.
    </p>

    <h4>Callsigns liés aux fiches</h4>
    <p>
        Chaque <strong>callsign</strong> affiché est rattaché à un membre et à sa fiche personnel, ce qui ancre la carte dans la réalité humaine de
        l’unité. Concrètement, un marqueur n’est jamais anonyme : derrière l’indicatif se trouvent un compte, un poste et une affectation cohérents
        avec l’<a href="#personnel-et-orbat">ORBAT</a>. Cette liaison sert autant à la lisibilité (savoir qui est qui) qu’à la fiabilité (éviter deux
        marqueurs prétendant être le même élément), et elle explique pourquoi la mise à jour des fiches personnel a un effet direct sur la clarté de
        la situation tactique.
    </p>

    <h4>Première liaison ATAK</h4>
    <p>
        Rejoindre la situation tactique pour la première fois passe par une <strong>première liaison</strong> : l’étape où un participant connecte son
        client à l’environnement de l’unité et apparaît pour la première fois sur la carte partagée. Cette liaison associe l’appareil ou le client au
        callsign du membre, de sorte que ses remontées ultérieures soient correctement attribuées. C’est une étape à réaliser au calme, avant une
        activité, plutôt que dans la précipitation juste avant un lancement.
    </p>
    <ol class="site-docs__steps">
        <li><strong>Vérifier les prérequis</strong> — Assurez-vous que votre <a href="#equipement-et-modpacks">modpack</a> est à jour et que votre
            compte dispose bien de l’accès aux outils cartes &amp; tactique.</li>
        <li><strong>Récupérer les paramètres de liaison</strong> — Depuis le portail, obtenez les éléments de connexion fournis par votre organisation
            pour rejoindre l’environnement de situation.</li>
        <li><strong>Associer votre callsign</strong> — Établissez la liaison de façon à ce que votre indicatif corresponde à votre fiche personnel,
            sans réutiliser celui d’un autre membre.</li>
        <li><strong>Confirmer votre présence sur la carte</strong> — Vérifiez que votre marqueur apparaît au bon endroit et avec le bon état avant de
            considérer la liaison comme réussie.</li>
        <li><strong>Tester avant l’activité</strong> — Réalisez cette première liaison en amont, pour disposer du temps nécessaire en cas d’ajustement,
            plutôt qu’au moment du rassemblement.</li>
    </ol>

    <h4>Configuration ATAK (administration)</h4>
    <p>
        La <strong>configuration ATAK</strong> côté administration est l’espace où les personnes habilitées préparent l’environnement de situation
        pour toute la communauté : paramètres de liaison, référentiels utilisés, réglages de visibilité et d’accès aux différentes vues. Cette
        configuration relève d’un rôle technique désigné, pas de chaque participant : un membre se contente en général de sa première liaison et de
        l’usage courant, tandis que la mise en place initiale et les ajustements structurants restent centralisés pour garantir la cohérence de la
        carte partagée.
    </p>
    <div class="site-docs__callout site-docs__callout--warn">
        <strong>Cohérence de la situation.</strong> Une carte tactique ne vaut que par la fiabilité de ce qu’elle affiche. Une liaison mal établie,
        un callsign réutilisé à tort ou une position non remontée dégradent la situation pour tout le monde, y compris pour le commandement qui décide
        à partir de cette image. En cas de doute sur votre propre affichage, signalez-le plutôt que de laisser un marqueur incohérent en place.
    </div>

    <h3>Utilisation</h3>
    <p>
        <strong>Côté participant engagé :</strong>
    </p>
    <ol class="site-docs__steps">
        <li><strong>Établir sa liaison</strong> — Connectez-vous à la situation tactique et vérifiez que votre callsign apparaît correctement sur le
            TACMAP.</li>
        <li><strong>Lire la situation avant d’agir</strong> — Prenez le temps d’identifier les éléments amis, neutres et hostiles et les éventuels
            tracés déjà posés avant d’entamer un mouvement.</li>
        <li><strong>Maintenir sa position à jour</strong> — Gardez votre liaison active pour que le commandement dispose d’une image fidèle ; une
            position figée fausse la lecture des superviseurs.</li>
        <li><strong>Respecter la symbologie commune</strong> — Utilisez les marqueurs et annotations selon les conventions de l’unité plutôt que d’en
            inventer, afin que la carte reste lisible par tous.</li>
    </ol>
    <p>
        <strong>Côté commandement et supervision :</strong>
    </p>
    <ol class="site-docs__steps">
        <li><strong>Ouvrir la vue adaptée</strong> — Utilisez le TACMAP pour le détail, l’Overwatch pour la supervision filtrée, le poste de
            commandement pour piloter l’ensemble.</li>
        <li><strong>Régler les filtres de commandement</strong> — Isolez l’unité, la zone ou le type d’élément pertinent pour la décision du moment
            plutôt que d’afficher tout en permanence.</li>
        <li><strong>Suivre l’état des personnels</strong> — Surveillez les éléments signalés en difficulté via le suivi santé pour orienter le soutien
            au bon moment.</li>
        <li><strong>Croiser avec les autres modules</strong> — Rapprochez la situation cartographique des fiches du mur opérationnel et des briefings
            pour décider en connaissant l’ensemble du contexte.</li>
        <li><strong>Débriefer à partir de la situation</strong> — Réutilisez la carte comme support de retour d’expérience une fois l’activité
            terminée, pour analyser les mouvements avec un support commun.</li>
    </ol>

    <h3>Cas particuliers</h3>
    <p>
        <strong>Menu ATAK absent malgré un rôle adapté.</strong> Si les outils cartes &amp; tactique n’apparaissent pas alors que votre rôle devrait
        vous y donner accès, la cause première à vérifier est le plan d’abonnement de votre organisation : ce module y est soumis. Une permission
        adéquate ne suffit pas si le plan actif n’inclut pas la situation tactique.
    </p>
    <p>
        <strong>Callsign déjà utilisé.</strong> Si votre indicatif entre en conflit avec celui d’un autre membre, ne forcez pas la liaison : cela
        créerait deux marqueurs ambigus sur la carte. Signalez le conflit au référent technique, qui rétablira la correspondance correcte entre chaque
        callsign et sa fiche personnel.
    </p>
    <p>
        <strong>Marqueur figé ou position obsolète.</strong> Une position qui ne bouge plus alors que l’élément se déplace indique en général une
        liaison interrompue. Rétablissez la liaison plutôt que de laisser un marqueur trompeur : le commandement décide à partir de ce qu’il voit, un
        marqueur figé peut l’induire en erreur bien plus qu’une absence assumée.
    </p>
    <p>
        <strong>Overwatch surchargé.</strong> Si la vue de supervision devient illisible par excès de marqueurs, resserrez les filtres de commandement
        sur ce qui compte à cet instant plutôt que de chercher à tout afficher : l’Overwatch a précisément été conçu pour prioriser, pas pour tout
        montrer en même temps.
    </p>
    <p>
        <strong>Nouvelle recrue sans première liaison.</strong> Un membre qui n’a jamais réalisé sa première liaison n’apparaîtra pas sur la carte,
        même présent physiquement à l’activité : prévoyez cette étape en amont, idéalement lors de l’intégration, plutôt que de la découvrir au moment
        du lancement d’une session.
    </p>
    <p>
        <strong>Fiche personnel incomplète et callsign.</strong> Comme le callsign s’appuie sur la fiche personnel, un dossier incomplet ou en doublon
        peut brouiller l’affichage tactique. Tenir les <a href="#personnel-et-orbat">fiches personnel</a> à jour n’est donc pas qu’une question
        administrative : c’est aussi une condition de lisibilité de la situation tactique.
    </p>
    <div class="site-docs__callout">
        <strong>Bon réflexe.</strong> Traitez la première liaison et la vérification du modpack comme des prérequis à part entière d’une activité
        tactique, au même titre que la lecture du briefing. Un participant « prêt » est un participant qui apparaît correctement sur la carte avant le
        début de la manœuvre, pas pendant.
    </div>
</section>

