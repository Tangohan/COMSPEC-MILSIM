    </div>
    <p>
        Lorsqu’un quota est atteint, le portail affiche un <strong>message de limite</strong> explicite, formulé en langage courant : il indique quelle
        ressource est concernée et invite à libérer de la place ou à envisager un plan plus complet. Ce message se distingue nettement d’un refus lié
        aux droits : il ne dit pas « vous n’avez pas le droit », mais « la capacité prévue par votre abonnement est atteinte ». La nuance est
        essentielle pour réagir correctement.
    </p>
    <p>
        C’est là qu’intervient la distinction la plus importante de ce chapitre : différencier une <strong>permission manquante</strong> d’une
        <strong>limite de quota</strong>. Une permission manquante signifie que <em>votre rôle</em> ne vous autorise pas une action — elle se règle en
        ajustant vos habilitations, comme expliqué au chapitre <a href="#droits-permissions-et-roles">Droits, permissions &amp; rôles</a>. Une limite
        de quota signifie que <em>la communauté entière</em> a atteint la capacité de son plan — elle se règle en libérant une ressource ou en faisant
        évoluer l’abonnement. Deux situations, deux interlocuteurs, deux solutions.
    </p>
    <div class="site-docs__table-wrap">
        <table class="site-docs__table">
            <thead>
                <tr>
                    <th>Symptôme</th>
                    <th>Permission manquante</th>
                    <th>Limite de plan</th>
                </tr>
            </thead>
            <tbody>
                <tr>
                    <td>Portée du blocage</td>
                    <td>Propre à votre compte ou à votre rôle</td>
                    <td>Commune à toute la communauté</td>
                </tr>
                <tr>
                    <td>Message affiché</td>
                    <td>Action non autorisée pour votre rôle</td>
                    <td>Capacité du plan atteinte pour cette ressource</td>
                </tr>
                <tr>
                    <td>Qui peut lever le blocage</td>
                    <td>Un responsable ajuste vos habilitations</td>
                    <td>Libérer une ressource ou faire évoluer l’abonnement</td>
                </tr>
            </tbody>
        </table>
    </div>
    <div class="site-docs__callout site-docs__callout--tip">
        <strong>Test rapide.</strong> Un même blocage touche-t-il aussi vos collègues au rôle plus élevé ? Si oui, c’est probablement une limite de
        plan commune à la communauté ; si le blocage ne concerne que vous, c’est plus vraisemblablement une permission liée à votre rôle.
    </div>

    <h3>Utilisation</h3>
    <ol class="site-docs__steps">
        <li><strong>Lire le message affiché</strong> — Distinguez un refus de droits (« action non autorisée ») d’un message de capacité (« limite du
            plan atteinte ») avant de réagir.</li>
        <li><strong>Vérifier la portée du blocage</strong> — Déterminez si le problème ne concerne que vous ou toute la communauté, pour identifier la
            bonne piste.</li>
        <li><strong>Libérer une ressource si possible</strong> — Pour un quota atteint, archivez ou retirez ce qui n’est plus utile (événements passés,
            formations obsolètes, comptes inactifs) avant d’envisager un changement de plan.</li>
        <li><strong>Solliciter le bon interlocuteur</strong> — Adressez-vous à un responsable des habilitations pour une permission, ou au responsable
            de l’abonnement pour une limite de plan.</li>
        <li><strong>Envisager une évolution de plan</strong> — Si les quotas sont durablement insuffisants au regard de l’activité réelle, un plan plus
            complet est la réponse adaptée, pas un contournement.</li>
    </ol>
    <p>
        Anticiper vaut mieux que subir : une communauté qui approche régulièrement de ses quotas gagne à surveiller ses <a href="#analytics-et-integrations">indicateurs
        d’activité</a> et à planifier une évolution de plan avant que la limite ne bloque une intégration ou une publication au plus mauvais moment,
        par exemple juste avant une vague de recrutement ou un cycle d’activités chargé.
    </p>

    <h3>Cas particuliers</h3>
    <p>
        <strong>Intégration bloquée par le quota de membres.</strong> Si une candidature acceptée ne peut pas être intégrée parce que le plafond de
        membres est atteint, il ne s’agit pas d’un problème de droits du recruteur : la communauté doit libérer un compte inactif ou faire évoluer son
        plan avant de finaliser l’intégration.
    </p>
    <p>
        <strong>Création d’événement refusée en fin de période.</strong> Un quota d’événements calculé sur une période peut être atteint avant son
        renouvellement : dans ce cas, la création reprend au cycle suivant, sauf évolution de plan. Priorisez alors les événements réellement
        nécessaires plutôt que de multiplier les créations en début de période.
    </p>
    <p>
        <strong>Module ATAK indisponible.</strong> L’accès à la situation tactique dépend directement du plan. Si le module cartes &amp; tactique
        n’apparaît pas, vérifiez le plan actif avant de suspecter une permission : comme rappelé au chapitre
        <a href="#outils-cartes-et-tactique">Outils cartes &amp; tactique (ATAK)</a>, ce module y est soumis.
    </p>
    <p>
        <strong>Analytics avancées absentes.</strong> Des indicateurs approfondis ou des intégrations externes manquants relèvent souvent d’une limite
        de plan plutôt que d’un défaut de configuration : les fonctions avancées sont réservées aux abonnements les plus complets.
    </p>
    <p>
        <strong>Blocage confondu avec une panne.</strong> Un message de limite de plan bien lu évite d’ouvrir à tort un signalement technique : le
        portail fonctionne normalement, c’est simplement la capacité prévue qui est atteinte. Reformuler le besoin auprès du responsable de
        l’abonnement est plus efficace que de chercher une cause technique inexistante.
    </p>
    <div class="site-docs__callout site-docs__callout--warn">
        <strong>Ne pas contourner un quota.</strong> Supprimer massivement des contenus utiles ou créer des comptes fictifs pour tricher avec un
        plafond dégrade la qualité des données de l’unité sans résoudre le fond. Si les quotas sont réellement trop justes, la bonne réponse est
        d’ajuster l’abonnement, pas de le contourner.
    </div>
</section>

<section id="pilotage-organisation" class="site-docs__section">
    <h2>Pilotage de l’organisation</h2>
    <p class="site-docs__lead">
        Le pilotage regroupe les outils de <strong>back-office</strong> par lesquels l’état-major administre sa communauté : gestion des
        <strong>rôles</strong>, envoi des <strong>invitations</strong>, application du principe de <strong>moindre privilège</strong>, et
        compréhension de la frontière entre l’administration d’une communauté et l’administration de la <strong>plateforme</strong> entière. C’est le
        poste de conduite d’une unité, réservé à ceux qui en portent la responsabilité.
    </p>

    <h3>Présentation générale</h3>
    <p>
        Le <strong>back-office</strong> d’une communauté est l’ensemble des écrans de gestion qui ne concernent pas la consultation courante mais le
        pilotage : qui fait partie de l’unité, avec quels droits, comment les nouveaux membres entrent, comment les rôles sont définis et attribués. Il
        prolonge naturellement les principes posés aux chapitres <a href="#droits-permissions-et-roles">Droits, permissions &amp; rôles</a> et
        <a href="#roles-communaute-et-metiers">Rôles communauté &amp; métiers</a> : ici, on ne décrit plus le mécanisme, on l’administre concrètement.
    </p>
    <p>
        Ce pilotage est structurant parce qu’il conditionne l’expérience de tous les autres membres. Un back-office bien tenu — rôles cohérents,
        invitations maîtrisées, droits ajustés — rend le portail fluide et prévisible ; un back-office négligé multiplie les « je ne vois pas ce
        menu », les comptes mal calibrés et les demandes de support répétées. Le soin apporté à cette gestion se ressent donc bien au-delà de
        l’encadrement qui l’exerce.
    </p>
    <p>
        La distinction la plus importante à garder à l’esprit est celle entre l’<strong>administration d’une communauté</strong> et
        l’<strong>administration de la plateforme</strong>. Piloter votre unité — ses membres, ses rôles, ses invitations — relève du premier niveau
        et concerne l’état-major. Administrer la plateforme entière — supervision globale, maintenance, réglages transverses à toutes les communautés —
        relève d’un second niveau, réservé aux équipes techniques du site, et ne fait pas partie de la gouvernance d’une unité ordinaire.
    </p>

    <h3>Fonctionnement</h3>
    <p>
        Le pilotage s’organise autour de quelques leviers principaux, que l’état-major manie au quotidien. Les comprendre comme un ensemble cohérent
        évite de les utiliser isolément, au risque d’incohérences entre les droits déclarés et la réalité vécue par les membres.
    </p>
    <div class="site-docs__table-wrap">
        <table class="site-docs__table">
            <thead>
                <tr>
                    <th>Levier</th>
                    <th>Ce qu’il permet</th>
                    <th>Vigilance associée</th>
                </tr>
            </thead>
            <tbody>
                <tr>
                    <td>Gestion des rôles</td>
                    <td>Créer, renommer, ajuster les ensembles de permissions</td>
                    <td>Un rôle trop large diffuse des droits à toute sa population</td>
                </tr>
                <tr>
                    <td>Invitations</td>
                    <td>Faire entrer de nouveaux membres avec un rôle initial</td>
                    <td>Choisir un rôle de départ mesuré plutôt que généreux</td>
                </tr>
                <tr>
                    <td>Attribution individuelle</td>
                    <td>Ajuster finement les droits d’un compte précis</td>
                    <td>Documenter les écarts pour ne pas perdre la logique</td>
                </tr>
                <tr>
                    <td>Retrait de droits</td>
                    <td>Réduire ou révoquer l’accès d’un membre</td>
                    <td>Vérifier qu’aucun autre rôle ne recouvre le droit retiré</td>
                </tr>
            </tbody>
        </table>
    </div>
    <p>
        La <strong>gestion des rôles</strong> est le levier le plus puissant, et donc le plus sensible. Modifier un rôle affecte instantanément tous
        les membres qui le portent : élargir un rôle « Cadre » pour dépanner une personne accorde le même surcroît de droits à tous les cadres. C’est
        pourquoi il vaut souvent mieux ajuster individuellement un compte particulier que d’élargir un rôle entier pour un cas isolé, afin de ne pas
        propager silencieusement un droit à une population plus large que prévu.
    </p>
    <p>
        Les <strong>invitations</strong> sont la porte d’entrée de nouveaux membres. Une invitation associe en général un rôle de départ : le choisir
        avec mesure est déterminant, car c’est lui qui définit ce qu’un nouvel arrivant pourra faire dès sa première connexion. Comme le rappelle le
        chapitre <a href="#etapes-de-mise-en-service">Étapes de mise en service</a>, il est préférable que les rôles soient stabilisés avant d’inviter
        massivement, plutôt que de corriger ensuite des dizaines de comptes un par un.
    </p>
    <p>
        Le <strong>principe de moindre privilège</strong> irrigue tout ce pilotage : n’accorder à chaque rôle et à chaque compte que les droits
        réellement nécessaires à sa fonction, plutôt que d’ouvrir largement « pour éviter les demandes ». Ce principe n’est pas une méfiance envers les
        membres : c’est une protection collective. Il limite les conséquences d’une erreur ou d’un compte compromis, clarifie les responsabilités, et
        rend le portail plus lisible en faisant correspondre les droits aux fonctions réelles.
    </p>
    <div class="site-docs__callout site-docs__callout--tip">
        <strong>Réflexe de pilotage.</strong> Avant d’élargir un rôle pour résoudre un cas particulier, demandez-vous si une attribution individuelle
        ne serait pas plus adaptée. Élargir un rôle est rapide, mais ses effets se propagent à toute une population et se rattrapent difficilement.
    </div>

    <h3>Utilisation</h3>
    <ol class="site-docs__steps">
        <li><strong>Cartographier les fonctions réelles</strong> — Partez de l’organigramme de l’unité pour définir des rôles qui correspondent à des
            fonctions, pas à des personnes.</li>
        <li><strong>Calibrer chaque rôle au juste besoin</strong> — Attribuez à chaque rôle les seules permissions nécessaires à sa fonction, dans
            l’esprit du moindre privilège.</li>
        <li><strong>Inviter avec un rôle de départ mesuré</strong> — Choisissez pour les nouveaux membres un rôle initial prudent, quitte à l’élargir
            ensuite une fois l’intégration confirmée.</li>
        <li><strong>Ajuster au cas par cas</strong> — Pour un besoin isolé, privilégiez une attribution individuelle plutôt qu’une modification de rôle
            qui toucherait toute une population.</li>
        <li><strong>Retirer les droits devenus inutiles</strong> — À chaque changement d’affectation ou départ, révisez les droits pour qu’ils
            reflètent la fonction actuelle, sans accumulation d’habilitations héritées.</li>
        <li><strong>Distinguer les niveaux d’administration</strong> — Traitez ce qui relève de votre communauté à votre niveau, et n’attendez pas de
            pouvoir agir sur des réglages qui relèvent de la plateforme entière.</li>
    </ol>
    <p>
        Une revue périodique des rôles et des comptes est une hygiène de pilotage saine : au fil des mutations, des départs et des dépannages ponctuels,
        les droits ont tendance à s’accumuler. Reprendre régulièrement la cohérence entre fonctions réelles et habilitations effectives évite qu’une
        communauté dérive lentement vers un état où « tout le monde peut à peu près tout », ce qui est précisément ce que le moindre privilège cherche
        à prévenir.
    </p>

    <h3>Cas particuliers</h3>
    <p>
        <strong>Droit accordé à trop de monde par erreur.</strong> Si une modification de rôle a ouvert un droit plus largement que prévu, revenez sur
        le rôle plutôt que de retirer le droit compte par compte : corriger à la source est plus fiable que de rattraper les effets un par un.
    </p>
    <p>
        <strong>Membre qui cumule des rôles hérités.</strong> Un membre ayant changé plusieurs fois de fonction peut conserver des rôles qui ne
        correspondent plus à son poste actuel. Retirez les rôles devenus sans objet, en vérifiant au préalable qu’aucun droit encore utile n’était
        porté uniquement par eux.
    </p>
    <p>
        <strong>Invitation restée sans suite.</strong> Une invitation non honorée n’intègre personne : relancez ou retirez-la plutôt que de la laisser
        indéfiniment ouverte, ce qui garde la liste des invitations lisible et évite de compter comme « en cours » un rattachement qui n’aboutira pas.
    </p>
    <p>
        <strong>Demande d’action relevant de la plateforme.</strong> Si un membre attend de l’état-major une action qui relève en réalité de
        l’administration de la plateforme (réglage transverse, maintenance globale), expliquez la frontière : votre pilotage porte sur la communauté,
        pas sur l’ensemble du site. Confondre les deux niveaux mène à des attentes qui ne peuvent pas être satisfaites au bon endroit.
    </p>
    <p>
        <strong>Rôle sur mesure devenu illisible.</strong> À force d’ajustements, un rôle peut accumuler des permissions disparates au point qu’on ne
        sache plus ce qu’il recouvre. Mieux vaut alors le repenser proprement à partir de la fonction visée que d’empiler de nouvelles exceptions sur
        une base devenue confuse.
    </p>
    <p>
        <strong>Blocage qui n’est pas un problème de droits.</strong> Si un ajustement de rôle ne débloque pas une action, la cause peut être ailleurs :
        une limite de plan, par exemple. Rapprochez-vous alors du chapitre <a href="#abonnements-et-limites-plan">Abonnements &amp; limites de plan</a>
        avant de continuer à modifier des habilitations qui ne sont peut-être pas en cause.
    </p>
    <div class="site-docs__callout site-docs__callout--warn">
        <strong>Responsabilité du pilotage.</strong> Les droits que vous attribuez engagent la sécurité et la traçabilité de toute la communauté. Un
        rôle trop large ou un compte sur-habilité augmente les risques en cas d’erreur ou de compromission. Le moindre privilège n’est pas une
        contrainte administrative : c’est une manière de protéger l’unité dans son ensemble.
    </div>
</section>

<section id="bonnes-pratiques" class="site-docs__section">
    <h2>Bonnes pratiques</h2>
    <p class="site-docs__lead">
        Ce dernier chapitre ne présente pas un module, mais une manière d’utiliser l’ensemble du portail avec cohérence. Il rassemble les réflexes
        transversaux qui reviennent d’un module à l’autre : vérifier son contexte, respecter le cycle de préparation avant diffusion, appliquer le
        moindre privilège, tenir l’information à jour, et distinguer une limite d’un dysfonctionnement. Ces principes, une fois acquis, rendent tout le
        reste plus simple.
    </p>

    <h3>Présentation générale</h3>
    <p>
        Un portail comme Athena n’est pas seulement une collection d’outils : c’est un espace commun où les gestes de chacun se répercutent sur les
        autres. Publier une fiche au mauvais endroit, laisser un droit trop large, oublier de mettre à jour un statut ou diffuser une annonce dans la
        mauvaise forme n’ont rien d’anodin : ces petits écarts, accumulés, sont ce qui fait la différence entre une communauté où l’information circule
        avec fluidité et une autre où chacun doute en permanence de ce qu’il voit. Les bonnes pratiques ne sont donc pas des règles supplémentaires,
        mais l’art d’utiliser le portail de manière à ce qu’il reste digne de confiance pour tous.
    </p>
    <p>
        La première d’entre elles est la conscience du <strong>contexte</strong>. Presque tout, dans le portail, dépend de la
        <a href="#communaute-et-contexte">communauté active</a> et du <a href="#droits-permissions-et-roles">rôle</a> qui est le vôtre à un instant
        donné. Prendre l’habitude de vérifier « où suis-je et avec quels droits » avant une action sensible désamorce à lui seul la majorité des
        confusions : publier dans la mauvaise unité, s’étonner d’un menu absent, croire à une panne là où il n’y a qu’un périmètre différent. Ce réflexe
        coûte quelques secondes et évite des erreurs difficiles à rattraper.
    </p>
    <p>
        La deuxième est le respect du <strong>cycle de préparation avant diffusion</strong>. Que ce soit une fiche du <a href="#mur-operationnel">mur
        opérationnel</a>, une <a href="#formations">formation</a> dans le Studio, un <a href="#courrier-officiel">courrier officiel</a> ou une
        publication liée, le portail fait presque toujours passer un contenu par une phase préparatoire invisible du public avant sa diffusion
        contrôlée. Court-circuiter cette phase — publier trop tôt, diffuser un brouillon, sauter une validation — revient à exposer un contenu
        incomplet à des membres qui le prendront pourtant pour une référence. La patience du cycle brouillon → publié est une forme de respect envers
        ceux qui liront.
    </p>

    <h3>Fonctionnement</h3>
    <p>
        Ces principes se déclinent différemment selon qu’on est membre ou encadrant, mais ils partagent une même logique de fond : préférer la clarté
        durable à la facilité immédiate. Un membre gagne à concentrer sa lecture sur ce qui le concerne réellement plutôt qu’à tout parcourir, à
        signaler plutôt qu’à corriger de force ce qui ne relève pas de lui, et à faire remonter une information manquante par le bon canal plutôt qu’à
        contourner une restriction. Un encadrant, lui, porte une responsabilité supplémentaire : ce qu’il publie et les droits qu’il attribue façonnent
        l’expérience de toute la communauté.
    </p>
    <p>
        Le <strong>moindre privilège</strong>, détaillé au chapitre <a href="#pilotage-organisation">Pilotage de l’organisation</a>, mérite d’être
        rappelé comme réflexe transversal : n’accorder que ce qui est nécessaire, retirer ce qui ne l’est plus, et préférer un ajustement individuel à
        l’élargissement d’un rôle entier. Ce principe protège l’unité bien au-delà du confort de gestion : il limite les conséquences d’une erreur,
        clarifie qui est responsable de quoi, et garde le portail lisible en faisant coïncider les droits avec les fonctions réelles.
    </p>
    <p>
        La <strong>mise à jour de l’information</strong> est le pendant quotidien de tout cela. Un statut opérationnel qui ne bouge plus, une fiche
        personnel jamais complétée, un modpack laissé en version ancienne, un dossier de recrutement sans suite : chacun de ces oublis dégrade
        silencieusement la confiance dans le module concerné. Tenir l’information à jour n’est pas une corvée administrative, c’est ce qui fait qu’un
        écran reste utile plutôt que trompeur. Un mur dont les statuts sont fiables, des fiches complètes, une situation tactique où chaque callsign
        correspond à une personne réelle : c’est cette rigueur cumulée qui rend le portail crédible.
    </p>
    <p>
        Enfin, savoir <strong>distinguer une limite d’un dysfonctionnement</strong> est un réflexe qui évite beaucoup de faux signalements. Ne pas voir
        un bouton relève presque toujours d’une permission ; ne pas voir un module entier peut relever d’une <a href="#abonnements-et-limites-plan">limite
        de plan</a> ; ne pas retrouver un contenu tient souvent à un changement de communauté active. Avant de conclure à une panne, il vaut la peine de
        passer en revue ces explications ordinaires, qui couvrent l’immense majorité des situations perçues comme anormales.
    </p>
    <div class="site-docs__callout site-docs__callout--tip">
        <strong>Fil conducteur.</strong> Presque chaque difficulté rencontrée dans le portail se ramène à l’une de ces quatre questions : suis-je dans
        la bonne communauté ? mon rôle couvre-t-il cette action ? mon plan inclut-il ce module ? l’information que je regarde est-elle à jour ? Les
        poser dans l’ordre résout la plupart des situations sans aide extérieure.
    </div>

    <h3>Utilisation</h3>
    <p>
        Les listes ci-dessous condensent les réflexes évoqués plus haut. Elles ne remplacent pas la lecture des chapitres concernés, mais servent
        d’aide-mémoire une fois ceux-ci assimilés.
    </p>
    <h4>Réflexes pour tous les membres</h4>
    <ol class="site-docs__steps">
        <li><strong>Vérifier la communauté active</strong> — Avant toute action sensible, confirmez l’unité dans laquelle vous agissez.</li>
        <li><strong>Lire avant d’agir</strong> — Consultez briefing, mur et annonces avant une activité plutôt que de poser des questions déjà
            traitées.</li>
        <li><strong>Signaler plutôt que corriger de force</strong> — Pour un contenu qui ne relève pas de vous, utilisez le signalement ou le référent
            adéquat.</li>
        <li><strong>Tenir son profil à jour</strong> — Gardez adresse de contact, fiche personnel et préférences exactes pour que l’unité reste bien
            informée.</li>
        <li><strong>Préparer ses prérequis techniques</strong> — Modpack et première liaison ATAK se règlent en amont, pas au moment du lancement.</li>
    </ol>
    <h4>Réflexes pour l’encadrement</h4>
    <ol class="site-docs__steps">
        <li><strong>Respecter le cycle brouillon → publié</strong> — Préparez et validez avant de diffuser, plutôt que d’exposer un contenu
            incomplet.</li>
        <li><strong>Appliquer le moindre privilège</strong> — N’accordez que les droits nécessaires et révisez-les régulièrement.</li>
        <li><strong>Choisir la bonne forme de diffusion</strong> — Réservez le bandeau à l’urgent, l’annonce durable à la page dédiée ou au sujet
            épinglé.</li>
        <li><strong>Maintenir les statuts et les données</strong> — Un mur et des indicateurs fiables valent mieux qu’un affichage abondant mais
            périmé.</li>
        <li><strong>Anticiper les limites de plan</strong> — Surveillez les quotas avant qu’ils ne bloquent une intégration ou une publication au plus
            mauvais moment.</li>
    </ol>

    <h3>Cas particuliers</h3>
    <p>
        <strong>Situation qui semble anormale.</strong> Avant de signaler un incident, parcourez les explications ordinaires — communauté active, rôle,
        plan, fraîcheur de l’information : elles couvrent la grande majorité des cas perçus comme des anomalies, et un signalement mieux qualifié fait
        gagner du temps à tout le monde.
    </p>
    <p>
        <strong>Tentation de contourner une restriction.</strong> Contourner un droit manquant ou un quota atteint (compte partagé, contenu supprimé
        pour tricher avec un plafond) crée plus de problèmes qu’il n’en résout et abîme la traçabilité de l’unité. La bonne voie reste toujours de
        solliciter le bon interlocuteur ou de faire évoluer le cadre.
    </p>
    <p>
        <strong>Information urgente à diffuser largement.</strong> Ne comptez pas sur un seul canal fugace pour une consigne importante : doublez un
        bandeau d’un support durable (page Alertes &amp; annonces, sujet épinglé) afin que ceux qui ne se connectent pas au bon moment la retrouvent
        malgré tout.
    </p>
    <p>
        <strong>Écart entre le guide et l’écran.</strong> Ce guide décrit un comportement standard ; votre organisation peut avoir renommé des rôles,
        adapté des libellés ou désactivé un module. En cas de divergence, l’interface et les consignes internes de votre chaîne de commandement font
        foi, comme rappelé dès l’<a href="#introduction">introduction</a>.
    </p>
    <p>
        <strong>Doute persistant malgré les vérifications.</strong> Si, après avoir passé en revue contexte, rôle, plan et fraîcheur de l’information,
        une situation reste incompréhensible, sollicitez un référent avec une description précise de ce que vous observez : un problème bien décrit se
        résout bien plus vite qu’une plainte vague, et évite les allers-retours inutiles.
    </p>
