    <p>
        Un <strong>modpack</strong> est décrit comme une liste ordonnée de modules, chacun accompagné des informations utiles à son installation :
        nom lisible, rôle du module, et éventuellement un lien de récupération lorsque votre organisation en fournit un. Le portail présente cette liste
        de façon à ce qu’un membre puisse la parcourir méthodiquement et cocher mentalement ce qu’il a déjà, plutôt que de deviner. Selon la
        configuration, plusieurs modpacks peuvent coexister — un modpack principal permanent, un modpack allégé pour les sorties courtes, un modpack
        spécifique à un environnement particulier — chacun clairement nommé pour éviter toute confusion.
    </p>
    <p>
        Les modpacks portent en général une <strong>notion de version</strong> : lorsqu’un module est ajouté, retiré ou mis à jour, la liste de
        référence évolue et il devient important que tous les participants s’alignent sur la même version avant une session commune. Le portail met
        cette version en évidence pour qu’un membre reparte de la liste à jour plutôt que d’une capture d’écran ancienne récupérée des semaines plus tôt.
    </p>
    <p>
        Côté dotation, chaque classe peut détailler des <strong>rubriques</strong> stables — protection, armement simulé, transmissions, matériel
        d’appui, effets personnels — pour que la lecture reste homogène d’un poste à l’autre. Ce découpage aide un nouveau membre à comprendre non
        seulement <em>quoi</em> se procurer, mais aussi <em>pourquoi</em> : une rubrique transmissions rappelle par exemple qu’une radio compatible est
        attendue, même si le modèle exact reste au choix du membre selon les consignes de l’unité.
    </p>
    <div class="site-docs__callout site-docs__callout--tip">
        <strong>À retenir.</strong> Le modpack décrit le logiciel à installer, la classe d’équipement décrit la dotation à posséder. Les deux se
        vérifient avant une activité, mais ils ne se remplacent pas : être « à jour côté modpack » ne dispense pas d’avoir la dotation attendue pour
        son poste, et inversement.
    </div>

    <h3>Utilisation</h3>
    <ol class="site-docs__steps">
        <li><strong>Repérer la classe de votre poste</strong> — Identifiez la classe d’équipement associée à votre affectation pour connaître la
            dotation de référence attendue.</li>
        <li><strong>Comparer avec votre dotation réelle</strong> — Parcourez les rubriques et notez ce qu’il vous manque avant de solliciter la
            logistique ou de compléter par vous-même.</li>
        <li><strong>Installer le modpack de référence</strong> — Ouvrez la liste des modules à jour et installez-les dans l’ordre indiqué, en vous
            appuyant sur les liens fournis par votre organisation lorsqu’ils existent.</li>
        <li><strong>Vérifier la version avant une session</strong> — Avant chaque activité, confirmez que le modpack correspond bien à la version
            annoncée pour l’événement, plutôt que de réutiliser une installation ancienne.</li>
        <li><strong>Signaler une divergence</strong> — Si un module manque ou entre en conflit, prévenez le référent technique en amont plutôt que
            d’attendre le lancement de la session.</li>
        <li><strong>Confirmer votre préparation</strong> — Lorsque l’organisateur le demande, indiquez que votre dotation et votre modpack sont prêts
            avant le rendez-vous.</li>
    </ol>
    <p>
        Côté logistique et organisation, la démarche est symétrique : maintenir les classes d’équipement à jour au rythme des évolutions de l’unité,
        publier une version de modpack clairement datée avant chaque cycle d’activités, et rappeler les prérequis directement sur l’événement concerné
        plutôt que dans un canal séparé. Un modpack tenu à jour dans le portail devient la source unique vers laquelle renvoyer toutes les questions,
        ce qui allège nettement la charge d’assistance juste avant les sessions.
    </p>

    <h3>Cas particuliers</h3>
    <p>
        <strong>Membre bloqué à la connexion à cause d’un module.</strong> Une incompatibilité de modpack se traduit souvent par une impossibilité de
        rejoindre la session. Reprenez la liste de référence à jour depuis le portail, vérifiez chaque module un par un plutôt que de réinstaller au
        hasard, et confirmez la version attendue auprès de l’organisateur avant de conclure à un problème plus large.
    </p>
    <p>
        <strong>Modpack allégé pour une sortie courte.</strong> Certaines activités n’exigent qu’une partie des modules habituels ; dans ce cas, suivez
        le modpack spécifiquement désigné pour l’événement plutôt que d’installer l’intégralité du modpack permanent, ce qui évite des temps
        d’installation inutiles pour une session brève.
    </p>
    <p>
        <strong>Dotation non conforme à la classe.</strong> Si votre équipement réel s’écarte de la classe de référence (matériel différent mais
        équivalent, pièce manquante en attente de réception), signalez-le à la logistique plutôt que de laisser la fiche en décalage : l’écart déclaré
        est toujours plus utile qu’un écart silencieux découvert le jour de l’activité.
    </p>
    <p>
        <strong>Mise à jour de modpack en cours de cycle.</strong> Lorsqu’un module est ajouté ou remplacé en plein cycle d’activités, considérez la
        nouvelle version comme obligatoire uniquement à partir de la date annoncée par votre organisation : appliquer une mise à jour trop tôt peut au
        contraire créer une divergence avec les participants encore sur l’ancienne version.
    </p>
    <p>
        <strong>Classe d’équipement partagée entre plusieurs postes.</strong> Une même classe peut servir de base à des postes proches ; si votre
        fonction exige une variante spécifique, appuyez-vous sur la classe commune comme socle, puis complétez la dotation propre à votre spécialité
        sans dupliquer inutilement une classe entière.
    </p>
    <div class="site-docs__callout site-docs__callout--warn">
        <strong>Sécurité des liens de récupération.</strong> Installez uniquement les modules à partir des sources indiquées par votre organisation
        dans le portail. Un module récupéré d’une source non validée peut introduire une incompatibilité, voire un risque de sécurité pour l’ensemble
        des participants d’une session.
    </div>
</section>

<section id="outils-cartes-et-tactique" class="site-docs__section">
    <h2>Outils cartes &amp; tactique (ATAK)</h2>
    <p class="site-docs__lead">
        Ce module regroupe les outils de <strong>situation tactique</strong> du portail, articulés autour d’ATAK : une carte partagée qui affiche en
        temps quasi réel la position et l’état des éléments engagés, un écran de supervision pour le commandement, et les liaisons qui rattachent chaque
        marqueur à un membre réel de votre communauté. C’est l’espace où la situation cesse d’être décrite par des mots pour devenir une image commune,
        lisible d’un coup d’œil par tous ceux qui y ont accès. Ce module est <strong>soumis au plan d’abonnement</strong> de votre organisation.
    </p>

    <h3>Présentation générale</h3>
    <p>
        La <strong>situation tactique ATAK</strong> est la représentation cartographique vivante de ce qui se passe sur le terrain simulé : des
        marqueurs symbolisent les éléments amis, neutres ou hostiles, positionnés sur un fond de carte partagé par tous les participants autorisés.
        Là où un briefing du <a href="#forum-et-briefings">forum</a> décrit une intention par écrit et où le <a href="#mur-operationnel">mur
        opérationnel</a> centralise l’état des fiches, la situation tactique répond à une question plus immédiate : « où sont les uns et les autres,
        et dans quel état, <em>maintenant</em> ? »
    </p>
    <p>
        Autour de cette carte gravitent plusieurs écrans complémentaires. L’<strong>Overwatch</strong> est la vue de supervision destinée au
        commandement : elle agrège la situation à un niveau plus élevé, avec des filtres permettant d’isoler ce qui intéresse le commandement ou le
        suivi de l’état des personnels. Le <strong>TACMAP</strong> est la carte tactique de travail au sens strict — celle sur laquelle on lit et
        annote la situation. Enfin, le <strong>poste de commandement (C2)</strong> constitue le point de pilotage d’où l’on coordonne l’ensemble,
        combinant vue d’ensemble et capacité de décision.
    </p>
    <p>
        Le principe qui rend l’ensemble cohérent est celui des <strong>callsigns liés aux fiches</strong> : chaque indicatif visible sur la carte
        n’est pas une simple étiquette libre, il est rattaché à un membre réel de la communauté et à sa fiche personnel. Cette liaison évite les
        homonymes et les marqueurs orphelins : lorsqu’on voit un callsign se déplacer sur le TACMAP, on sait à quelle personne, à quel poste et à
        quelle affectation il correspond, sans avoir à le deviner.
    </p>
    <div class="site-docs__callout site-docs__callout--tip">
        <strong>Module soumis au plan.</strong> Les outils cartes &amp; tactique dépendent du plan d’abonnement souscrit par votre organisation. Si
        le menu ATAK n’apparaît pas, ou si certaines vues (Overwatch, C2) restent inaccessibles, il peut s’agir d’une limite de plan plutôt que d’une
        permission manquante. Le chapitre <a href="#abonnements-et-limites-plan">Abonnements &amp; limites de plan</a> détaille cette distinction.
    </div>

    <h3>Fonctionnement</h3>
    <p>
        L’ensemble repose sur une base de situation partagée : les positions et états remontés par les participants alimentent une même carte, que les
        différents écrans exploitent ensuite selon leur vocation. Comprendre à quoi sert chaque écran évite d’ouvrir l’Overwatch quand on cherche à
        annoter le TACMAP, ou l’inverse.
    </p>
