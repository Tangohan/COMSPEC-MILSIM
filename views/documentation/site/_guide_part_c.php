<section id="recrutement-et-enrolement" class="site-docs__section">
    <h2>Recrutement &amp; enrôlement</h2>
    <p class="site-docs__lead">
        Le module de recrutement structure tout le parcours d’une candidature, depuis son dépôt jusqu’à l’intégration effective d’un nouveau membre :
        le <strong>bureau recrutement</strong> où les candidatures sont suivies, les <strong>statuts</strong> qui rythment leur traitement, les échanges
        avec le candidat via des <strong>messages prédéfinis</strong>, la proposition d’un <strong>entretien</strong>, et la gestion de candidats
        <strong>avec ou sans compte portail</strong>. C’est le point de contact entre l’extérieur et votre communauté, et donc un module où le soin
        apporté aux réponses engage l’image de l’unité.
    </p>

    <h3>Présentation générale</h3>
    <p>
        Le <strong>bureau recrutement</strong> est l’espace de travail des recruteurs et de l’état-major chargé de l’enrôlement : il rassemble en un
        seul endroit toutes les candidatures reçues, leur état d’avancement et les actions attendues. Il remplace avantageusement une gestion éparpillée
        entre messages privés, tableurs et souvenirs individuels : chaque dossier y a une place stable, un statut clair et un historique consultable,
        ce qui évite qu’une candidature se perde ou reste sans réponse faute d’avoir été « prise » par quelqu’un.
    </p>
    <p>
        Une candidature n’est pas seulement un formulaire : c’est le début d’une relation avec une personne qui, si tout se passe bien, deviendra un
        membre de l’unité. Le module est donc pensé pour que ce parcours reste <strong>lisible des deux côtés</strong> — côté recruteur, qui suit et
        décide, et côté candidat, qui doit comprendre où en est sa démarche sans avoir à relancer sans cesse. Cette symétrie est ce qui distingue un
        recrutement soigné d’un simple tri administratif.
    </p>
    <p>
        Le recrutement s’articule étroitement avec d’autres modules déjà décrits. Les rôles de <strong>Recruteur</strong> et de <strong>RH (S1)</strong>
        présentés au chapitre <a href="#roles-communaute-et-metiers">Rôles communauté &amp; métiers</a> encadrent qui peut agir sur les candidatures.
        Une fois la candidature acceptée, la personne bascule vers les <a href="#personnel-et-orbat">fiches personnel</a> et, le cas échéant, vers un
        <a href="#dossier-operateur">dossier opérateur</a> pour son accréditation. Le bureau recrutement est donc la première marche d’un escalier qui
        mène ensuite au reste du portail.
    </p>

    <h3>Fonctionnement</h3>
    <p>
        Chaque candidature progresse à travers un ensemble de <strong>statuts</strong> qui décrivent, à tout instant, où en est le dossier. Ces statuts
        ne sont pas de simples étiquettes de rangement : ils déterminent les actions possibles et servent de langage commun entre recruteurs pour se
        répartir le travail sans se marcher dessus.
    </p>
    <div class="site-docs__table-wrap">
        <table class="site-docs__table">
            <thead>
                <tr>
                    <th>Statut</th>
                    <th>Signification</th>
                    <th>Action attendue</th>
                </tr>
            </thead>
            <tbody>
                <tr>
                    <td>À traiter</td>
                    <td>Candidature reçue, pas encore prise en charge</td>
                    <td>Un recruteur ouvre le dossier et amorce l’examen</td>
                </tr>
                <tr>
                    <td>Acceptée</td>
                    <td>Candidature retenue, intégration à enclencher</td>
                    <td>Basculer le candidat vers l’effectif et le dossier opérateur</td>
                </tr>
                <tr>
                    <td>Refusée</td>
                    <td>Candidature écartée après examen, avec motif</td>
                    <td>Notifier le candidat avec un message clair et courtois</td>
                </tr>
                <tr>
                    <td>Non admis</td>
                    <td>Candidat ne remplissant pas les conditions requises</td>
                    <td>Clore le dossier en expliquant le critère non satisfait</td>
                </tr>
            </tbody>
        </table>
    </div>
    <p>
        La distinction entre <strong>Refusée</strong> et <strong>Non admis</strong> mérite une attention particulière. « Refusée » traduit une décision
        prise après examen d’un dossier recevable — le profil ne correspond pas au besoin, la place n’est pas disponible, le moment n’est pas opportun.
        « Non admis » renvoie plutôt à un critère d’éligibilité non satisfait dès le départ (condition d’âge, prérequis explicite, incompatibilité de
        principe). Employer le bon statut aide autant le suivi interne que la clarté du message envoyé au candidat, qui ne recevra pas la même
        explication dans l’un et l’autre cas.
    </p>
    <p>
        Entre la réception et la décision, le recruteur peut proposer un <strong>entretien</strong> : un échange, écrit ou de vive voix selon les
        usages de l’unité, destiné à mieux cerner la motivation, l’expérience et la disponibilité du candidat. La proposition d’entretien s’inscrit
        dans le dossier, de sorte que l’ensemble de la cellule recrutement sache qu’un échange est prévu ou a eu lieu, sans dépendre de la mémoire d’une
        seule personne.
    </p>
    <p>
        Pour fluidifier et homogénéiser les réponses, le module s’appuie sur des <strong>messages prédéfinis</strong> : des modèles de réponse
        réutilisables (accusé de réception, invitation à un entretien, refus courtois, demande de complément) que le recruteur adapte au cas par cas
        plutôt que de tout rédiger depuis une page blanche. Ces modèles garantissent un ton cohérent d’un recruteur à l’autre et évitent qu’un candidat
        reçoive une réponse expédiée un jour et soignée le lendemain selon la personne qui traite son dossier.
    </p>
    <div class="site-docs__callout site-docs__callout--tip">
        <strong>À retenir.</strong> Un message prédéfini est un point de départ, pas une réponse toute faite à envoyer telle quelle. Prenez toujours
        quelques secondes pour l’ajuster au dossier concerné : une réponse manifestement générique se repère immédiatement et donne une mauvaise
        première impression de l’unité.
    </div>

    <h4>Candidat avec ou sans compte portail</h4>
    <p>
        Le recrutement doit composer avec deux situations distinctes. Un <strong>candidat disposant déjà d’un compte portail</strong> — par exemple un
        membre d’une autre communauté, ou un visiteur qui s’est enregistré avant de postuler — est directement rattaché à son compte : les échanges et
        le suivi s’appuient sur son identité existante, et l’intégration éventuelle réutilise ce compte plutôt que d’en créer un nouveau. À l’inverse,
        un <strong>candidat sans compte portail</strong> postule depuis l’extérieur : le dossier vit alors de façon plus autonome, et la création du
        compte n’intervient qu’au moment de l’intégration, une fois la candidature acceptée.
    </p>
    <p>
        Cette distinction a des conséquences concrètes sur les échanges. Pour un candidat avec compte, la communication peut passer par les canaux
        internes du portail ; pour un candidat sans compte, elle repose davantage sur l’adresse de contact fournie dans la candidature. Le recruteur
        doit donc garder à l’esprit par quel canal le candidat sera effectivement joignable avant de choisir un message prédéfini, afin de ne pas
        écrire dans un espace que le candidat ne pourra pas consulter.
    </p>
    <div class="site-docs__table-wrap">
        <table class="site-docs__table">
            <thead>
                <tr>
                    <th>Situation du candidat</th>
                    <th>Canal d’échange privilégié</th>
                    <th>Au moment de l’intégration</th>
                </tr>
            </thead>
            <tbody>
                <tr>
                    <td>Avec compte portail</td>
                    <td>Canaux internes rattachés au compte existant</td>
                    <td>Réutilisation du compte, attribution d’un rôle et d’une fiche</td>
                </tr>
                <tr>
                    <td>Sans compte portail</td>
                    <td>Adresse de contact fournie dans la candidature</td>
                    <td>Création du compte puis rattachement du dossier</td>
                </tr>
            </tbody>
        </table>
    </div>

    <h4>SLA et suivi des dossiers</h4>
    <p>
        Un recrutement se juge aussi à sa <strong>réactivité</strong>. Beaucoup d’unités se fixent un délai de traitement de référence — un
        <strong>SLA</strong>, c’est-à-dire un engagement de délai — pour qu’aucune candidature ne reste sans premier retour au-delà d’un certain temps.
        Le bureau recrutement aide à tenir cet engagement en mettant en avant les dossiers en attente et l’ancienneté de chacun, afin que les
        candidatures les plus anciennes ne soient pas systématiquement doublées par les plus récentes qui apparaissent en tête de liste.
    </p>
    <p>
        Ce suivi des délais n’a pas pour but de bâcler les réponses, mais d’éviter le silence : un candidat prévenu d’un délai d’examen patiente
        sans inquiétude, alors qu’un candidat sans nouvelles se décourage ou postule ailleurs. Un simple accusé de réception rapide, suivi d’un examen
        plus posé, vaut donc mieux qu’une réponse parfaite arrivant trop tard.
    </p>

    <h3>Utilisation</h3>
    <p>
        <strong>Côté candidat :</strong>
    </p>
    <ol class="site-docs__steps">
        <li><strong>Déposer sa candidature</strong> — Renseignez le formulaire d’enrôlement avec une adresse de contact valide, que vous disposiez ou
            non déjà d’un compte.</li>
        <li><strong>Attendre l’accusé de réception</strong> — Vérifiez vos courriers, y compris les indésirables, plutôt que de redéposer plusieurs
            candidatures identiques.</li>
        <li><strong>Répondre à une proposition d’entretien</strong> — Confirmez votre disponibilité et préparez l’échange comme un premier contact
            réel avec l’unité.</li>
        <li><strong>Suivre la décision</strong> — Lisez attentivement le message reçu ; en cas de refus, tenez compte du motif avant d’envisager une
            nouvelle démarche.</li>
    </ol>
    <p>
        <strong>Côté recruteur :</strong>
    </p>
    <ol class="site-docs__steps">
        <li><strong>Prendre en charge un dossier « À traiter »</strong> — Ouvrez la candidature la plus ancienne en attente plutôt que de piocher au
            hasard, pour respecter le délai de réponse de l’unité.</li>
        <li><strong>Accuser réception</strong> — Envoyez rapidement un premier message, en adaptant un modèle prédéfini, pour signaler que le dossier
            est bien pris en compte.</li>
        <li><strong>Examiner et, si besoin, proposer un entretien</strong> — Évaluez le profil au regard des besoins de l’unité et enclenchez un
            échange lorsqu’un doute mérite d’être levé.</li>
        <li><strong>Décider avec le bon statut</strong> — Positionnez « Acceptée », « Refusée » ou « Non admis » selon la nature exacte de la décision,
            en distinguant bien un refus motivé d’une inéligibilité de principe.</li>
        <li><strong>Notifier clairement le candidat</strong> — Adaptez un message prédéfini au dossier, en veillant à écrire sur le canal réellement
            accessible au candidat (interne ou adresse de contact).</li>
        <li><strong>Enclencher l’intégration</strong> — Pour une candidature acceptée, créez ou rattachez le compte, attribuez le rôle adapté et ouvrez
            la fiche personnel, puis le dossier opérateur si l’accréditation l’exige.</li>
    </ol>

    <h3>Cas particuliers</h3>
    <p>
        <strong>Candidature en double.</strong> Si une même personne postule plusieurs fois (impatience, oubli du premier envoi), traitez un seul
        dossier de référence et clôturez les doublons en le signalant, plutôt que de mener des échanges parallèles qui finiraient par se contredire.
    </p>
    <p>
        <strong>Candidat qui ne répond plus.</strong> Après une proposition d’entretien restée sans suite malgré une relance, il est légitime de
        clôturer le dossier plutôt que de le laisser indéfiniment ouvert : notez le motif pour garder une trace, au cas où le candidat reviendrait
        plus tard.
    </p>
    <p>
        <strong>Refus mal vécu.</strong> Un candidat peut contester un refus. Le bon réflexe est de renvoyer au motif déjà communiqué, avec courtoisie,
        plutôt que de rouvrir un débat : un refus expliqué une fois clairement n’a pas à être renégocié dossier par dossier, sauf élément nouveau.
    </p>
    <p>
        <strong>Candidat sans compte devenu injoignable.</strong> Comme les échanges reposent sur l’adresse de contact, une adresse erronée rend le
        candidat impossible à joindre. Vérifiez l’adresse saisie avant de conclure à une absence de réponse volontaire, surtout si aucun accusé de
        réception n’a pu être délivré.
    </p>
    <p>
        <strong>Intégration à cheval sur plusieurs communautés.</strong> Un candidat déjà membre d’une autre communauté rejoint la vôtre sans perdre
        son compte : son enrôlement crée un rattachement supplémentaire, pas un nouveau compte. Vérifiez la <a href="#communaute-et-contexte">communauté
        active</a> lors de l’intégration pour attribuer le rôle dans la bonne organisation.
    </p>
    <p>
        <strong>Message prédéfini inadapté au cas.</strong> Si aucun modèle ne correspond exactement à la situation (dossier atypique, refus
        nécessitant une explication particulière), rédigez une réponse sur mesure plutôt que de forcer un modèle mal ajusté : la clarté prime sur la
        rapidité lorsque le message risque d’être mal compris.
    </p>
    <p>
        <strong>Délai de réponse dépassé.</strong> Si un dossier a dépassé le délai de référence de l’unité, priorisez-le et prévenez le candidat de
        l’examen en cours, même sans décision définitive : un signe de vie tardif reste préférable à un silence prolongé, qui donne l’image d’une unité
        désorganisée.
    </p>
    <div class="site-docs__callout site-docs__callout--warn">
        <strong>Image de l’unité.</strong> Chaque réponse envoyée à un candidat, acceptée ou refusée, engage la réputation de votre communauté
        au-delà du seul dossier concerné. Un refus courtois et clair laisse une bonne impression et peut susciter une nouvelle candidature plus tard ;
        une réponse sèche ou un silence circulent, eux aussi, en dehors du portail.
    </div>
</section>

<section id="alertes-et-annonces" class="site-docs__section">
    <h2>Alertes &amp; annonces</h2>
    <p class="site-docs__lead">
        Ce module regroupe les moyens de <strong>diffuser une information descendante</strong> et de la faire remonter à l’attention des membres : la
        page dédiée <strong>Alertes &amp; annonces</strong>, les <strong>bandeaux</strong> affichés en tête de portail, les <strong>sujets de forum
        épinglés</strong> et les <strong>messages flash</strong> qui confirment une action. Il distingue soigneusement ce qui relève de la
        <strong>plateforme</strong> de ce qui relève de votre <strong>communauté</strong>, car ces deux niveaux n’ont ni le même émetteur ni le même
        public.
    </p>

    <h3>Présentation générale</h3>
    <p>
        Toute organisation a besoin d’un canal fiable pour dire « ceci est important, lisez-le ». Le module Alertes &amp; annonces répond à ce besoin
        en proposant plusieurs formes de diffusion, adaptées à des degrés d’urgence et de permanence différents. Une annonce durable n’a pas la même
        forme qu’une alerte ponctuelle, et un simple retour de confirmation après une action ne s’affiche pas comme un message destiné à toute l’unité.
    </p>
    <p>
        La distinction la plus structurante est celle entre le niveau <strong>plateforme</strong> et le niveau <strong>communauté</strong>. Une
        annonce de <strong>plateforme</strong> émane de l’équipe qui maintient l’ensemble du site et s’adresse à toutes les communautés hébergées :
        maintenance prévue, évolution générale, information transverse. Une annonce de <strong>communauté</strong> émane de votre propre unité et ne
        concerne qu’elle : consigne interne, information d’activité, rappel propre à votre organisation. Confondre les deux conduit à s’adresser au
        mauvais public, ou à s’étonner de voir une annonce que l’on n’a pas soi-même publiée.
    </p>
    <p>
        La <strong>page Alertes &amp; annonces</strong> centralise ces communications pour qu’un membre dispose d’un endroit unique où retrouver ce qui
        a été diffusé, plutôt que de dépendre d’un affichage fugace vu une seule fois à la connexion. Elle complète, sans les remplacer, le
        <a href="#forum-et-briefings">forum</a> pour les échanges durables et le <a href="#mur-operationnel">mur opérationnel</a> pour la situation
        courante.
    </p>

    <h3>Fonctionnement</h3>
    <p>
        Chaque forme de diffusion a sa vocation propre. Les comprendre évite d’employer un bandeau permanent pour une information éphémère, ou un flash
        pour une consigne que les membres devront pouvoir retrouver plus tard.
    </p>
    <div class="site-docs__table-wrap">
        <table class="site-docs__table">
            <thead>
                <tr>
                    <th>Forme</th>
                    <th>Vocation</th>
                    <th>Permanence</th>
                </tr>
            </thead>
            <tbody>
                <tr>
                    <td>Page Alertes &amp; annonces</td>
                    <td>Historique consultable des communications diffusées</td>
                    <td>Durable, consultable à la demande</td>
                </tr>
                <tr>
                    <td>Bandeau</td>
                    <td>Mise en avant en tête de portail d’une information marquante</td>
