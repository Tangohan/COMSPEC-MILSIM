    <p>
        Les <strong>bandeaux</strong> s’affichent en tête du portail pour capter l’attention sans obliger le membre à ouvrir un module précis. Ils
        conviennent à une information marquante mais temporaire : une échéance qui approche, une consigne exceptionnelle, un rappel avant une activité
        importante. Leur force — être vus par tous — est aussi leur limite : un bandeau qui reste affiché trop longtemps, ou plusieurs bandeaux
        empilés, finissent par ne plus être lus. Un bandeau se retire donc dès qu’il a rempli son office.
    </p>
    <p>
        Les <strong>sujets de forum épinglés</strong> servent les annonces qui gagnent à rester à portée de main dans une catégorie et qui peuvent
        appeler des questions. Comme décrit au chapitre <a href="#forum-et-briefings">Forum &amp; briefings</a>, l’épinglage maintient un sujet en tête
        de sa catégorie plutôt que de le laisser descendre dans le flux. C’est la forme adaptée lorsqu’une annonce mérite discussion ou lorsqu’on veut
        qu’elle reste retrouvable durablement, contrairement à un bandeau voué à disparaître.
    </p>
    <p>
        Les <strong>messages flash</strong> jouent un rôle différent : ils confirment qu’une action vient d’aboutir (« enregistré », « publié »,
        « envoyé ») ou signalent un problème immédiat à corriger. Ils apparaissent après une action et s’effacent une fois lus. Ce ne sont pas des
        annonces au sens communicationnel : ce sont des retours d’interface destinés à rassurer l’utilisateur sur l’effet de son geste, et ils n’ont
        pas vocation à être conservés ni consultés a posteriori.
    </p>
    <div class="site-docs__callout site-docs__callout--tip">
        <strong>Choisir la bonne forme.</strong> Une information à retrouver plus tard va sur la page Alertes &amp; annonces ou dans un sujet épinglé ;
        une information marquante mais temporaire justifie un bandeau ; une confirmation d’action se contente d’un flash. Employer la mauvaise forme,
        c’est risquer de noyer l’essentiel ou, au contraire, de faire disparaître trop vite une consigne importante.
    </div>

    <h3>Utilisation</h3>
    <ol class="site-docs__steps">
        <li><strong>Consulter la page Alertes &amp; annonces</strong> — Ouvrez-la régulièrement pour retrouver les communications diffusées, sans
            dépendre d’un affichage vu une seule fois.</li>
        <li><strong>Distinguer l’émetteur</strong> — Repérez si une annonce vient de la plateforme (transverse à toutes les communautés) ou de votre
            propre communauté, pour interpréter correctement à qui elle s’adresse.</li>
        <li><strong>Traiter les bandeaux comme des priorités du moment</strong> — Lisez un bandeau dès qu’il apparaît ; il signale en général une
            information à ne pas manquer avant une échéance proche.</li>
        <li><strong>Suivre les sujets épinglés</strong> — Considérez les annonces épinglées d’une catégorie comme des références durables à connaître
            avant de participer à une activité.</li>
        <li><strong>Tenir compte des flashs</strong> — Lisez les messages de confirmation ou d’erreur qui suivent vos actions pour vérifier qu’elles
            ont bien abouti.</li>
    </ol>
    <p>
        Côté encadrement, diffuser une annonce suppose de choisir sciemment sa forme et sa durée : réserver le bandeau aux informations réellement
        marquantes, préférer un sujet épinglé lorsqu’un échange est possible, et penser à retirer une mise en avant devenue obsolète. Une communauté
        qui laisse s’accumuler des bandeaux périmés habitue ses membres à ne plus les lire, ce qui affaiblit précisément le canal qu’elle cherchait à
        renforcer.
    </p>

    <h3>Cas particuliers</h3>
    <p>
        <strong>Annonce plateforme prise pour une consigne interne.</strong> Une annonce de maintenance ou d’évolution émise au niveau plateforme
        s’applique à toutes les communautés et ne traduit aucune décision de votre unité : ne la relayez pas comme une consigne interne sans l’avoir
        identifiée comme telle, au risque de créer de la confusion sur qui en est à l’origine.
    </p>
    <p>
        <strong>Bandeau resté trop longtemps.</strong> Un bandeau affiché bien après la fin de son actualité perd son effet et décrédibilise les
        suivants. Retirez-le dès que l’information n’est plus d’actualité plutôt que de le laisser par habitude : la rareté d’un bandeau fait sa force.
    </p>
    <p>
        <strong>Annonce importante diffusée uniquement en flash.</strong> Un message flash disparaît après lecture ; il ne convient donc pas à une
        consigne que les membres devront retrouver. Pour une information durable, privilégiez la page Alertes &amp; annonces ou un sujet épinglé, en
        réservant le flash à la simple confirmation d’action.
    </p>
    <p>
        <strong>Membre qui « n’a rien vu passer ».</strong> Si un membre affirme n’avoir pas eu connaissance d’une annonce, vérifiez d’abord par quelle
        forme elle a été diffusée : une information passée uniquement par un bandeau fugace ou un flash a pu échapper à quelqu’un qui ne s’est pas
        connecté au bon moment. Une annonce vraiment importante gagne à être doublée sur un support durable.
    </p>
    <p>
        <strong>Superposition de plusieurs annonces.</strong> Lorsque plusieurs communications coexistent (bandeau plateforme, bandeau communauté,
        sujet épinglé), hiérarchisez : gardez visible ce qui est réellement prioritaire et déplacez le reste vers la page dédiée, afin que l’en-tête du
        portail ne devienne pas illisible.
    </p>
    <div class="site-docs__callout site-docs__callout--warn">
        <strong>Ne pas confondre les niveaux.</strong> Vous ne pouvez pas retirer ni modifier une annonce de plateforme depuis votre communauté, et
        inversement l’équipe plateforme ne gère pas vos annonces internes. En cas de doute sur l’origine d’une communication, identifiez d’abord son
        émetteur avant d’agir : agir au mauvais niveau est une source fréquente de malentendus.
    </div>
</section>

<section id="analytics-et-integrations" class="site-docs__section">
    <h2>Analytics &amp; intégrations</h2>
    <p class="site-docs__lead">
        Ce module éclaire le pilotage d’une communauté par des <strong>indicateurs d’activité</strong> et de <strong>conversion</strong>, et permet,
        sur les plans les plus complets, de relier le portail à des <strong>outils externes</strong>. Il ne s’agit pas de surveiller les membres, mais
        de donner à l’encadrement une image factuelle de la vie de l’unité pour décider sur des bases concrètes plutôt que sur des impressions.
    </p>

    <h3>Présentation générale</h3>
    <p>
        Les <strong>indicateurs d’activité</strong> mesurent la vitalité de la communauté : fréquentation des modules, participation aux événements,
        progression dans les formations, dynamique du forum. Ils répondent à des questions simples mais utiles — l’unité est-elle active ? un module
        est-il réellement utilisé ? une baisse d’engagement se dessine-t-elle ? — auxquelles il est difficile de répondre honnêtement de mémoire, sans
        chiffres pour appuyer l’intuition.
    </p>
    <p>
        Les indicateurs de <strong>conversion</strong> s’intéressent plus spécifiquement aux parcours qui transforment un contact en membre engagé :
        combien de candidatures aboutissent à une intégration, combien de nouveaux membres deviennent réellement actifs, combien de formations
        assignées sont menées à terme. La conversion complète l’activité brute : une unité peut recevoir beaucoup de candidatures tout en en
        transformant peu, et ce n’est qu’en regardant ces deux angles ensemble qu’on comprend où le parcours se grippe.
    </p>
    <p>
        Les <strong>intégrations externes</strong>, quant à elles, relèvent des plans les plus avancés : elles permettent de faire dialoguer le portail
        avec des outils tiers utilisés par votre organisation. Elles ne sont pas indispensables au fonctionnement quotidien — le portail vit très bien
        sans — mais elles évitent les doubles saisies et les ruptures entre le portail et l’écosystème d’une unité qui utilise déjà d’autres services.
    </p>

    <h3>Fonctionnement</h3>
    <p>
        Les indicateurs sont présentés sous forme de vues synthétiques qui privilégient la lecture d’ensemble sur le détail exhaustif. L’objectif est
        qu’un cadre saisisse une tendance en quelques secondes, quitte à ouvrir ensuite le module concerné pour le détail.
    </p>
    <div class="site-docs__table-wrap">
        <table class="site-docs__table">
            <thead>
                <tr>
                    <th>Famille d’indicateurs</th>
                    <th>Ce qu’elle éclaire</th>
                    <th>Usage type</th>
                </tr>
            </thead>
            <tbody>
                <tr>
                    <td>Activité</td>
                    <td>Fréquentation et participation aux modules</td>
                    <td>Repérer un module sous-utilisé ou une baisse d’engagement</td>
                </tr>
                <tr>
                    <td>Conversion</td>
                    <td>Passage de candidat à membre, puis à membre actif</td>
                    <td>Identifier où le parcours d’intégration décroche</td>
                </tr>
                <tr>
                    <td>Formation</td>
                    <td>Assignations menées à terme, réussite aux évaluations</td>
                    <td>Ajuster l’offre pédagogique et le suivi des apprenants</td>
                </tr>
            </tbody>
        </table>
    </div>
    <p>
        Les indicateurs respectent les mêmes <strong>habilitations</strong> que le reste du portail : consulter les analytics d’une communauté suppose
        un rôle adapté, en général au sein de l’encadrement. Un membre sans cette habilitation ne verra tout simplement pas le module, ce qui est
        cohérent avec le principe rappelé au chapitre <a href="#droits-permissions-et-roles">Droits, permissions &amp; rôles</a> : ne pas voir un écran
        d’analyse n’est pas une anomalie, c’est le reflet d’un périmètre de responsabilité.
    </p>
    <p>
        Les chiffres doivent être lus comme des <strong>signaux</strong>, pas comme des verdicts. Une baisse de participation à un instant donné peut
        s’expliquer par une période creuse, un événement reporté ou une saisonnalité, autant que par un réel désengagement. L’intérêt des indicateurs
        est de faire émerger une question à instruire — « pourquoi cette baisse ? » — plutôt que de fournir une réponse automatique qu’il suffirait
        d’appliquer.
    </p>
    <p>
        Les <strong>intégrations externes</strong> reposent sur une connexion établie entre le portail et un service tiers, réservée aux plans avancés
        et à des rôles techniques désignés. Leur mise en place n’est pas une action de tous les jours : elle se configure une fois, avec soin, puis
        fonctionne en arrière-plan. Le détail des services connectables dépend de votre plan et des choix de votre organisation ; le principe reste
        d’éviter la ressaisie et de garder le portail cohérent avec les autres outils déjà en usage.
    </p>
    <div class="site-docs__callout site-docs__callout--tip">
        <strong>À retenir.</strong> Les analytics servent à décider, pas à juger les personnes. Un indicateur en baisse invite à comprendre une
        cause, pas à désigner un responsable ; utilisé de travers, un tableau de bord d’activité peut abîmer la confiance qu’il était censé éclairer.
    </div>

    <h3>Utilisation</h3>
    <ol class="site-docs__steps">
        <li><strong>Ouvrir la vue de synthèse</strong> — Commencez par la tendance d’ensemble avant de descendre dans le détail d’un module précis.</li>
        <li><strong>Comparer sur une période</strong> — Regardez l’évolution dans le temps plutôt qu’un chiffre isolé, qui ne dit rien sans point de
            comparaison.</li>
        <li><strong>Croiser activité et conversion</strong> — Rapprochez le volume d’activité du taux de transformation pour distinguer un problème de
            flux d’un problème de parcours.</li>
        <li><strong>Instruire une anomalie</strong> — Face à un écart marquant, ouvrez le module concerné pour comprendre la cause avant de tirer une
            conclusion.</li>
        <li><strong>Configurer une intégration (plans avancés)</strong> — Si votre plan le permet et qu’un rôle technique vous y autorise, reliez le
            service externe voulu en une configuration soignée plutôt que répétée.</li>
    </ol>
    <p>
        Le meilleur usage des analytics est régulier et modéré : un point périodique par l’encadrement, quelques indicateurs suivis dans la durée,
        plutôt qu’une consultation frénétique qui sur-interprète chaque variation quotidienne. C’est la tendance, pas le soubresaut, qui porte
        l’information utile au pilotage.
    </p>

    <h3>Cas particuliers</h3>
    <p>
        <strong>Module analytics absent.</strong> Si les indicateurs n’apparaissent pas, deux causes sont possibles : une permission manquante pour
        votre rôle, ou une limite du plan d’abonnement de votre organisation. Cette distinction, détaillée au chapitre
        <a href="#abonnements-et-limites-plan">Abonnements &amp; limites de plan</a>, doit être vérifiée avant de conclure à un problème technique.
    </p>
    <p>
        <strong>Chiffres qui semblent faux.</strong> Un indicateur surprenant reflète parfois une réalité inattendue plutôt qu’une erreur : avant de
        contester la donnée, vérifiez la période affichée et le périmètre pris en compte, car un filtre mal réglé donne facilement une impression
        d’incohérence.
    </p>
    <p>
        <strong>Intégration externe indisponible.</strong> Les intégrations relevant des plans avancés, leur absence n’est pas un défaut mais une
        caractéristique du plan actif. Un passage à un plan supérieur peut être nécessaire pour connecter un outil tiers ; c’est une décision
        d’organisation, pas un réglage individuel.
    </p>
    <p>
        <strong>Sur-interprétation d’une baisse.</strong> Une diminution ponctuelle d’activité ne justifie pas une réaction immédiate : replacez-la
        dans la durée et le contexte (période de vacances, activité reportée) avant d’en tirer une conclusion sur la santé de l’unité.
    </p>
    <p>
        <strong>Conversion faible malgré une forte activité.</strong> Beaucoup de candidatures pour peu d’intégrations peut signaler un point de
        blocage dans le parcours de <a href="#recrutement-et-enrolement">recrutement</a> ou d’intégration : c’est précisément le type de signal que les
        analytics servent à faire remonter, pour aller ensuite instruire l’étape concernée.
    </p>
    <div class="site-docs__callout site-docs__callout--warn">
        <strong>Respect des personnes.</strong> Les indicateurs agrègent l’activité d’une communauté ; ils ne doivent pas servir à surveiller
        individuellement un membre ou à justifier une sanction. Utilisez-les pour améliorer le fonctionnement collectif, dans le respect des règles de
        votre organisation sur les données des membres.
    </div>
</section>

<section id="abonnements-et-limites-plan" class="site-docs__section">
    <h2>Abonnements &amp; limites de plan</h2>
    <p class="site-docs__lead">
        Le portail fonctionne selon des <strong>plans d’abonnement</strong> qui déterminent, pour chaque communauté, l’ampleur des ressources
        disponibles : nombre de membres, d’événements, de formations, accès à la situation tactique ATAK ou aux analytics avancées. Comprendre ces
        <strong>quotas</strong> et savoir distinguer une <strong>limite de plan</strong> d’une <strong>permission manquante</strong> évite de
        confondre un choix d’abonnement avec un dysfonctionnement.
    </p>

    <h3>Présentation générale</h3>
    <p>
        Un plan d’abonnement définit ce que votre organisation peut faire à grande échelle sur le portail. Là où les rôles et permissions décrivent
        <em>qui</em> a le droit d’agir, le plan décrit <em>combien</em> et <em>jusqu’où</em> : combien de membres l’unité peut accueillir, combien
        d’événements elle peut planifier sur une période, combien de formations elle peut faire vivre, et si des modules avancés comme la situation
        tactique ATAK ou les intégrations externes sont inclus. Ces deux logiques se superposent en permanence, et beaucoup de blocages incompris
        viennent précisément de leur confusion.
    </p>
    <p>
        L’idée d’un plan n’est pas de brider une unité, mais d’aligner les ressources réellement mobilisées sur l’abonnement souscrit. Une petite
        communauté n’a pas les mêmes besoins qu’une organisation de plusieurs centaines de membres menant des activités hebdomadaires ; le plan permet
        à chacune de disposer d’un cadre proportionné, quitte à évoluer vers un plan supérieur lorsque l’activité grandit.
    </p>
    <p>
        La notion clé à retenir est celle de <strong>quota</strong> : une quantité maximale associée à une ressource, propre au plan actif. Tant que
        le quota n’est pas atteint, tout se passe normalement ; lorsqu’il l’est, le portail affiche un message expliquant que la limite du plan est
        atteinte, ce qui est une information de gestion, pas une erreur technique.
    </p>

