                    <td>Annonce discutable maintenue en tête de catégorie</td>
                    <td>Durable, avec possibilité d’échange</td>
                </tr>
                <tr>
                    <td>Message flash</td>
                    <td>Confirmation immédiate d’une action réalisée</td>
                    <td>Fugace, disparaît après lecture</td>
