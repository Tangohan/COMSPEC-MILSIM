<section id="investigations" class="site-docs__section">
    <h2>Investigations &amp; graphe</h2>
    <p class="site-docs__lead">
        Une investigation (toile de données) visualise les relations entre entités :
        personnes, lieux, véhicules, supports, documents. Elle ne remplace pas le dossier — elle l’éclaire.
    </p>

    <h3>Créer une toile</h3>
    <ol>
        <li>Ouvrez <strong>Investigations</strong> puis créez une nouvelle toile.</li>
        <li>Donnez un titre opérationnel et, si besoin, rattachez un dossier source.</li>
        <li>Ajoutez des entités (nœuds) puis des liens (arêtes) avec un libellé de relation.</li>
        <li>Disposez le graphe ; la disposition peut être enregistrée.</li>
    </ol>

    <h3>Bon usage</h3>
    <ul>
        <li>Un lien sans source ni motif est un bruit : précisez la nature de la relation.</li>
        <li>Distinguez « vu ensemble » (observation) et « même identité » (hypothèse lourde).</li>
        <li>Supprimez les nœuds ou liens erronés plutôt que de laisser le graphe mentir.</li>
    </ul>

    <h3>Chronologie &amp; croisements</h3>
    <p>
        La <strong>chronologie</strong> ordonne les événements dans le temps.
        Les <strong>croisements</strong> et listes de surveillance rapprochent des signaux ;
        les <strong>anomalies</strong> signalent des incohérences à examiner — pas à accepter aveuglément.
    </p>
</section>
