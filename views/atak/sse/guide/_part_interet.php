<section id="dossiers-interet" class="site-docs__section">
    <h2>Dossiers d’intérêt</h2>
    <p class="site-docs__lead">
        Un dossier d’intérêt accueille un signal non encore consolidé. Il porte une désignation temporaire,
        jamais un nom certain sans preuve.
    </p>

    <h3>Ouvrir un dossier</h3>
    <ol class="site-docs__steps">
        <li>Ouvrez <strong>Dossiers d’intérêt</strong>, puis créez un nouveau dossier.</li>
        <li>Donnez une <strong>désignation temporaire</strong> (alias, référence terrain, circumlocution).</li>
        <li>Saisissez le motif, l’origine du signal et la confiance initiale.</li>
        <li>Décrivez les observations et le contexte de mission.</li>
        <li>Séparez clairement faits, hypothèses, contradictions et questions.</li>
        <li>Indiquez les besoins de collecte, la source et sa fiabilité.</li>
    </ol>
    <p>
        Le dossier démarre en <strong>Signalement reçu</strong>. Une correspondance biométrique élevée,
        même frappante, ne change pas seule ce statut.
    </p>

    <h3>Examiner une proposition de rapprochement</h3>
    <ul>
        <li>Comparer facteurs concordants et discordants.</li>
        <li>Consigner votre appréciation.</li>
        <li>Accepter, rejeter, qualifier de probable, demander une collecte, ou créer une liaison sans fusion.</li>
        <li>Une consolidation exige une permission distincte et un motif écrit.</li>
        <li>Le rejet conserve la proposition originale (trace).</li>
    </ul>

    <div class="site-docs__callout site-docs__callout--info">
        <strong>Human in the loop.</strong>
        Les propositions aident ; elles ne remplacent pas le jugement. En cas de doute, demandez une collecte
        plutôt que de forcer une consolidation.
    </div>

    <h3>Suite du cycle</h3>
    <p>
        Après qualification : consolidation éventuelle vers une fiche personne / dossier validé,
        infirmation, classement sans suite, ou archivage. La réévaluation reste possible si de nouveaux éléments arrivent.
    </p>
</section>
