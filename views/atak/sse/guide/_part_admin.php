<section id="administration" class="site-docs__section">
    <h2>Administration des accès</h2>
    <p class="site-docs__lead">
        Réservée aux cadres habilités à délivrer des codes. Cette rubrique n’apparaît que si vos droits le permettent.
    </p>

    <h3>Délivrer un code</h3>
    <ol>
        <li>Ouvrez <strong>Administration</strong> dans le bureau SSE.</li>
        <li>Indiquez le libellé de l’invité (unité, fonction, surnom opérationnel).</li>
        <li>Choisissez la durée de validité.</li>
        <li>Transmettez le code par un canal sûr ; ne le publiez pas en clair sur un canal ouvert.</li>
    </ol>

    <h3>Révoquer</h3>
    <p>
        Dès qu’un besoin cesse (fin de vacation, perte de confiance, fin de mission),
        révoquez le code. La session associée devient immédiatement inutilisable.
    </p>

    <h3>Journal d’actions</h3>
    <p>
        L’écran d’administration affiche un journal des délivrances, révocations et actions SSE notables.
        Utilisez-le pour auditer qui a travaillé dans le compartiment et quand.
    </p>

