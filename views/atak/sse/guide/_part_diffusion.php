        vous pouvez en supprimer une si elle n’est plus pertinente.
    </p>

    <h3>Principes</h3>
    <ul>
        <li>Ne jamais copier-coller hors Athena un contenu classifié sans canal autorisé.</li>
        <li>Préférer un document validé et caviardé à une capture d’écran brute.</li>
        <li>Le bandeau de classification reste la référence visuelle permanente.</li>
        <li>Les invités n’ont accès qu’au périmètre de leur code — ne leur transférez pas de droits implicites.</li>
    </ul>

