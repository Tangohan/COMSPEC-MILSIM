    <h3>Engagement de confidentialité</h3>
    <p>
        À la première entrée (ou après renouvellement de l’engagement), un sas vous demande de confirmer
        que vous comprenez le caractère classifié du compartiment. Sans cet accord, le bureau reste fermé.
        L’engagement est lié à votre session SSE ; quitter le bureau ou expirer la session le réinitialise.
    </p>

    <h3>Bandeau permanent</h3>
    <p>
        Pendant toute la session, un bandeau rappelle le niveau de diffusion (par exemple « Confidentiel »)
        et le fait que la consultation est tracée. Respectez ce cadre : ne diffusez rien hors canal autorisé.
    </p>

