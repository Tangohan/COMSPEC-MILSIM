    <h2>Introduction</h2>
    <p class="site-docs__lead">
        Le bureau SSE transforme un signal brut — individu inconnu, alias, visage, véhicule, téléphone, lieu ou association —
        en dossier de travail traçable. Il sert le renseignement interpersonnel de votre communauté Athena, en mission et au poste de commandement.
    </p>

    <h3>Ce que couvre le bureau</h3>
    <ul>
        <li><strong>Dossiers d’intérêt</strong> — signalements à qualifier, sans identité certaine.</li>
        <li><strong>Dossiers validés</strong> — affaires structurées (notes, preuves, personnel, comptes rendus).</li>
        <li><strong>Identités et objets</strong> — personnes, organisations, sites, véhicules, matériels, pièces documentaires.</li>
        <li><strong>Investigations</strong> — toiles relationnelles pour visualiser les liens.</li>
        <li><strong>Exploitation numérique</strong> — supports saisis, acquisitions, analyses, chronologies.</li>
        <li><strong>Rédaction et diffusion</strong> — flash, comptes rendus, caviardage avant sortie du compartiment.</li>
    </ul>

    <h3>Règle fondamentale</h3>
    <div class="site-docs__callout site-docs__callout--danger">
        <strong>Aide à l’analyse, jamais preuve automatique.</strong>
        Une proposition produite par le système (rapprochement, signal, suggestion de consolidation)
        ne vaut ni identification, ni validation, ni preuve. Aucun traitement planifié ne fusionne une identité sans décision humaine motivée.
    </div>

    <h3>Cycle de travail</h3>
    <ol class="site-docs__steps">
        <li><strong>Recevoir et qualifier</strong> la source (terrain, Athena, importation).</li>
        <li><strong>Séparer</strong> faits établis, hypothèses, contradictions et questions ouvertes.</li>
        <li><strong>Émettre</strong> des besoins de collecte vers le terrain.</li>
        <li><strong>Examiner</strong> les propositions de rapprochement.</li>
        <li><strong>Décider</strong> (accepter, rejeter, demander une collecte, consolider avec motif).</li>
        <li><strong>Consolider, infirmer, classer sans suite ou archiver</strong> — avec trace.</li>
    </ol>
