<section id="dossiers-valides" class="site-docs__section">
    <h2>Dossiers validés</h2>
    <p class="site-docs__lead">
        Les dossiers validés structurent une affaire : personnel lié, notes, preuves, corrélations,
        captures de situation, comptes rendus et, le cas échéant, caviardage pour diffusion.
    </p>

    <h3>Organisation</h3>
    <ul>
        <li>Liste et arborescence (dossiers / sous-dossiers) selon votre organisation.</li>
        <li>Verrou de classification : certains contenus ne s’ouvrent qu’avec le niveau adapté.</li>
        <li>Statuts de suivi (ouvert, en cours, archive…) distincts de la confiance analytique.</li>
    </ul>

    <h3>Contenu type d’un dossier</h3>
    <table>
        <thead>
            <tr>
                <th>Bloc</th>
                <th>Usage</th>
            </tr>
        </thead>
        <tbody>
            <tr><td>Personnes liées</td><td>Rattacher des fiches identité au dossier</td></tr>
            <tr><td>Notes</td><td>Observations chronologiques, appréciations</td></tr>
            <tr><td>Preuves / pièces</td><td>Éléments matériels ou documentaires référencés</td></tr>
            <tr><td>Corrélations</td><td>Liens explicites vers d’autres objets ou dossiers</td></tr>
            <tr><td>Compte rendu</td><td>Synthèse structurée ; peut devenir un brouillon de rédaction</td></tr>
            <tr><td>Export / PDF</td><td>Sortie contrôlée selon vos droits</td></tr>
        </tbody>
    </table>

    <h3>Compte rendu</h3>
    <p>
        Depuis un dossier, ouvrez le compte rendu pour structurer situation, faits, personnel et matériel.
        Vous pouvez en faire un <strong>brouillon de document</strong> dans l’atelier de rédaction
        pour le faire relire et valider avant diffusion.
    </p>

