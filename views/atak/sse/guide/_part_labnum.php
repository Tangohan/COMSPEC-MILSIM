<section id="exploitation-numerique" class="site-docs__section">
    <h2>Exploitation numérique</h2>
    <p class="site-docs__lead">
        Sous-module du bureau pour les supports saisis : enregistrer le matériel, réaliser ou importer une acquisition,
        visualiser les données extraites, produire des signaux analytiques et des propositions —
        sans jamais conclure automatiquement.
    </p>

    <h3>Chaîne d’exploitation</h3>
    <ol class="site-docs__steps">
        <li><strong>Découverte</strong> du support sur le terrain ou en saisie.</li>
        <li><strong>Conditionnement</strong> et enregistrement dans Athena (type, état, contexte).</li>
        <li><strong>Acquisition</strong> — copie logique, extraction ou image simulée.</li>
        <li><strong>Intégrité</strong> — contrôle que l’acquisition reste cohérente.</li>
        <li><strong>Extraction</strong> — messages, contacts, fichiers, médias, localisations…</li>
        <li><strong>Analyse opérateur</strong> — annotations, intérêt, rattachements.</li>
        <li><strong>Rapprochements</strong> — propositions vers le SSE (jamais auto-fusion).</li>
        <li><strong>Validation</strong> puis compte rendu d’exploitation.</li>
    </ol>

    <h3>Distinctions strictes</h3>
    <table>
        <thead>
            <tr>
                <th>Couche</th>
                <th>Rôle</th>
            </tr>
        </thead>
        <tbody>
            <tr><td>Support physique</td><td>Objet saisi, conditionné, tracé</td></tr>
            <tr><td>Acquisition</td><td>Copie / extraction / image (simulée ou importée)</td></tr>
            <tr><td>Données extraites</td><td>Artefacts consultables (messages, fichiers…)</td></tr>
            <tr><td>Analyse opérateur</td><td>Annotations et décisions humaines</td></tr>
            <tr><td>Signaux / propositions</td><td>Aides automatiques, jamais conclusions</td></tr>
            <tr><td>Éléments validés</td><td>Décisions auditées, opposables dans le dossier</td></tr>
        </tbody>
    </table>

    <h3>Par où commencer</h3>
    <ol>
        <li>Ouvrez le hub <strong>Exploitation numérique</strong>.</li>
        <li>Enregistrez un support (téléphone, ordinateur, clé USB, etc.).</li>
        <li>Ajoutez une acquisition, puis explorez artefacts, analyses et chronologie.</li>
        <li>Tranchez les propositions dans les files de validation ; rédigez un rapport si besoin.</li>
    </ol>

    <p>
        Les vues téléphone et ordinateur aident à parcourir un support comme un opérateur le ferait
        dans un atelier — toujours dans le cadre du jeu et de la simulation.
    </p>
</section>
