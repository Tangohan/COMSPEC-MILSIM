    <h3>Qualification des informations</h3>
    <ul>
        <li><strong>Donnée brute</strong> — acquisition conservée avec source et contexte.</li>
        <li><strong>Fait établi</strong> — observé ou corroboré.</li>
        <li><strong>Hypothèse</strong> — interprétation révocable, explicitement marquée.</li>
        <li><strong>Identité déclarée</strong> — fournie, non forcément vérifiée.</li>
        <li><strong>Identité supposée</strong> — rapprochement analytique non validé.</li>
        <li><strong>Identité consolidée</strong> — conclusion humaine motivée sur preuves suffisantes.</li>
    </ul>
