    <h3>Trois axes indépendants</h3>
    <dl class="site-docs__lexicon">
        <dt>État de traitement</dt>
        <dd>Du brouillon à l’archive — où en est le dossier dans le flux de travail.</dd>
        <dt>Niveau de confiance</dt>
        <dd>De « non évalué » à « confirmé » — qualité de la connaissance, pas l’urgence.</dd>
