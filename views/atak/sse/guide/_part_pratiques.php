<section id="bonnes-pratiques" class="site-docs__section">
    <h2>Bonnes pratiques</h2>
    <p class="site-docs__lead">
        Quelques règles qui font la différence entre un bureau crédible et une base de données confuse.
    </p>

    <h3>Rédaction et qualification</h3>
    <ul>
        <li>Séparez toujours faits, hypothèses et questions ouvertes.</li>
        <li>Préférez une désignation temporaire à un nom « inventé pour faire propre ».</li>
        <li>Citez la source et sa fiabilité à chaque apport important.</li>
        <li>Ne transformez pas un score machine en phrase affirmative (« c’est X »).</li>
    </ul>

    <h3>Décision</h3>
    <ul>
        <li>En cas de doute : collecte, pas consolidation.</li>
        <li>Documentez le motif d’acceptation ou de rejet d’une proposition.</li>
        <li>Conservez les contradictions visibles après décision.</li>
        <li>Une fusion doit rester réversible et garder la mémoire des identifiants d’origine.</li>
    </ul>

    <h3>Sécurité de session</h3>
    <ul>
        <li>Quittez le bureau en fin de vacation.</li>
        <li>Ne laissez pas un poste ouvert avec une session invitée active.</li>
        <li>Révoquez les codes dès qu’ils ne sont plus nécessaires.</li>
    </ul>

    <h3>Qualité des données</h3>
    <ul>
        <li>Reliez les objets aux dossiers et toiles — évitez les fiches orphelines.</li>
        <li>Mettez à jour le statut du dossier quand l’état réel change.</li>
        <li>Archivez ce qui est clos ; ne laissez pas d’affaires mortes en « ouvert ».</li>
    </ul>

    <div class="site-docs__callout site-docs__callout--info">
        <strong>Besoin d’aide locale.</strong>
        La doctrine fine (seuils, qui valide quoi, canaux de diffusion) est définie par votre communauté.
        Ce manuel fixe le cadre produit ; votre responsable SSE précise les usages.
    </div>
</section>
