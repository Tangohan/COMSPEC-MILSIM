<section id="redaction-rapports" class="site-docs__section">
    <h2>Rédaction &amp; rapports</h2>
    <p class="site-docs__lead">
        L’atelier de rédaction produit flash, comptes rendus, notes d’analyse et synthèses.
        Rien ne sort du compartiment sans passage par un document relus et validé.
    </p>

    <h3>Types de documents</h3>
    <ul>
        <li><strong>Flash renseignement</strong> — alerte courte pour le poste de commandement.</li>
        <li><strong>Compte rendu</strong> — situation, faits, personnel, matériel.</li>
        <li><strong>Note d’analyse</strong> — raisonnement, hypothèses, recommandations.</li>
        <li><strong>Synthèse</strong> — vue consolidée pour un briefing ou une clôture.</li>
    </ul>

    <h3>Cycle rédactionnel</h3>
    <ol class="site-docs__steps">
        <li>Créer un document (ou partir d’un brouillon issu d’un compte rendu de dossier).</li>
        <li>Rédiger en séparant faits et appréciations.</li>
        <li>Relire ; faire évoluer le statut (brouillon → en relecture → validé).</li>
        <li>Diffuser uniquement le niveau autorisé, après caviardage si besoin.</li>
    </ol>

    <h3>Hub rapports</h3>
    <p>
        La rubrique <strong>Rapports</strong> regroupe les sorties utiles au pilotage
        (synthèses d’affaires, exports contrôlés). Respectez toujours le niveau de classification
        affiché et vos droits d’export.
    </p>
</section>
